import os
import re
import shutil
import sys

# The shared modules are beside this script, which `python -I` leaves off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import REPO, ROOT, case, fresh  # noqa: E402

FMT = "skp"
INCH = 0.0254
SPEC = "SketchUp .skp (closed; as openskp reads it)"
SRC = "saved by SketchUp, from openskp's test fixtures (packages/cpp/tests/fixtures)"
GEN = "generated by tools/corpus/skp.py"

FIXTURES = [
    "annotation_layers_vff", "arcs_2021", "blank_v17", "instance_scale_term_2021", "instance_scale_term_v6",
    "legacy_annotations", "legacy_empty_2020", "legacy_text_arrows_2017", "legacy_textured_colorize_2017",
    "legacy_v2020_textured", "legacy_v3_textured", "legacy_v4_textured", "legacy_v5_textured", "nesting_2013",
    "nesting_2017", "nesting_2020", "nesting_2021", "nesting_v6", "sdk_saved_2019", "single_material_v17",
    "zero_material_custom_layer_v18", "sdk_saved_tag_line_styles_2019", "sdk_saved_tag_line_styles_2020",
    "sdk_saved_tag_line_styles_materials_2020",
]


def load_fixtures():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    out = {}
    for name in FIXTURES:
        p = os.path.join(src, name + ".skp") if src else os.path.join(ROOT, FMT, name, name + ".skp")
        with open(p, "rb") as f:
            out[name] = f.read()
    return out


def application(data):
    """SketchUp's name for the version in the header: 3 to 8 kept the number, 13 on became years."""
    text = data[:200].replace(b"\x00", b"").decode("latin-1")
    major = int(re.search(r"\{(\d+)\.", text).group(1))
    return "SketchUp " + str(2000 + major if major >= 13 else major)


def gltf(p):
    """SketchUp's inches, Z up, as glTF's meters, Y up."""
    x, y, z = p
    return [x * INCH, z * INCH, -y * INCH]


def bounds(points):
    pts = [gltf(p) for p in points]
    return {"min": [min(p[i] for p in pts) for i in range(3)], "max": [max(p[i] for p in pts) for i in range(3)]}


def polygon(cx, r, sides, sweep):
    """The corners of an arc of `sides` segments about (cx, 0, 0) in the XY plane, from angle 0."""
    n = sides if sweep == 2 * math.pi else sides + 1
    return [(cx + r * math.cos(sweep * k / sides), r * math.sin(sweep * k / sides), 0.0) for k in range(n)]


def area(points):
    """A flat polygon's area, in square meters."""
    s = sum(points[i][0] * points[(i + 1) % len(points)][1] - points[(i + 1) % len(points)][0] * points[i][1]
            for i in range(len(points)))
    return abs(s) / 2 * INCH * INCH


fixtures = load_fixtures()
LICENSE = os.path.join(ROOT, FMT, "LICENSE-openskp")
fresh(FMT)
# The notice beside the cases stays as it is; the reader's copy stands in when there is none.
if not os.path.exists(LICENSE):
    shutil.copyfile(os.path.join(REPO, "src", "formats", "skp", "LICENSE-openskp"), LICENSE)


def fixture(name, spec, **expect):
    data = fixtures[name]
    document = {**expect.pop("document", {}), "source": {"tool": application(data)}}
    case(FMT, name, {name + ".skp": data},
         {"spec": SPEC + ": " + spec, "source": SRC, "document": document, **expect})


