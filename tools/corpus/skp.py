# --- damaged and invalid files ------------------------------------------------------------------


def header(version):
    """The string records every SketchUp file opens with: "SketchUp Model", then the version."""
    def string(s):
        return bytes([0xFF, 0xFE, 0xFF, len(s)]) + s.encode("utf-16-le")
    return string("SketchUp Model") + string(version)


