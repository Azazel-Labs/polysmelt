# Three arcs drawn through SketchUp's library: a loose quarter arc (radius 10 at the origin, an edge
# with no face), a disc (a 24-sided circle of radius 5 at x = 50, bounding a face) and a half disc
# (a 12-segment half circle of radius 8 at x = 100, closed by its chord). openskp's arc_curves_test.
disc = polygon(50, 5, 24, 2 * math.pi)
half = polygon(100, 8, 12, math.pi)
fixture("arcs_2021", "a disc and a half disc bounded by arcs, and a loose arc with no face, in a 2021+ (ZIP) file",
        triangles=(24 - 2) + (13 - 2), area=area(disc) + area(half), bounds=bounds(disc + half))

# One 100 in cube definition placed twice: through the 3x3 scaled by 0.01, and through the 13th
# value (1/w = 0.01) with a translation of 2000 in. SketchUp reports both as 1 in cubes, at x = 0
# and x = 20 in. openskp's instance_scale_term_test.
cubes = [(x, y, z) for x0 in (0, 20) for x in (x0, x0 + 1) for y in (0, 1) for z in (0, 1)]
for name, kind in [("instance_scale_term_2021", "a 2021+ (ZIP)"), ("instance_scale_term_v6", "a SketchUp 6")]:
    fixture(name, "an instance scaled through the transform's last value (1/w), in " + kind + " file",
            triangles=24, area=2 * 6 * INCH * INCH, bounds=bounds(cubes), uvs=False)

# The group "Outer" holds an instance of the component "Shelf", which holds the group "Inner", with
# a face at each level, saved by five versions. openskp's definition_is_group_test.
for name, kind in [("nesting_v6", "SketchUp 6"), ("nesting_2013", "SketchUp 2013"), ("nesting_2017", "SketchUp 2017"),
                   ("nesting_2020", "SketchUp 2020"), ("nesting_2021", "2021+ (ZIP)")]:
    fixture(name, "a group in a component in a group, a face at each level, as " + kind + " saves it",
            primitives=3, document={"node_names": ["Outer", "Shelf", "Inner"]})

# One 20 x 20 in face painted with "Checker", an 8 x 8 PNG, saved down to SketchUp 3; SketchUp 4
# and 5 store the same PNG byte for byte, and the 2020 save keeps it with its one face.
# openskp's legacy_v3_format_test and legacy_v4_v5_v2019_test.
fixture("legacy_v3_textured", "one face painted with a textured material, its PNG stored inline (SketchUp 3)",
        triangles=2, area=20 * 20 * INCH * INCH, uvs=True, image_count=1,
        materials=[{"name": "Checker", "textured": True}])
for name, version in [("legacy_v4_textured", "SketchUp 4"), ("legacy_v5_textured", "SketchUp 5"),
                      ("legacy_v2020_textured", "SketchUp 2020, with no component definitions")]:
    fixture(name, "one face painted with a textured material (" + version + ")",
            triangles=2, uvs=True, image_count=1, materials=[{"textured": True}])

# Tags with line styles ("Dash", "Dot"), one triangle on each tag: six tags (two plain) and no
# materials, saved as 2020 and as 2019 (which writes each style's preamble twice), and five tags
# with three unused materials. The style is written where a tag first uses it and referred to by
# later tags. openskp's legacy_tag_line_styles_test.
for name, tags, spec in [("sdk_saved_tag_line_styles_2020", 6, "six tags, four with a line style (SketchUp 2020)"),
                         ("sdk_saved_tag_line_styles_2019", 6, "six tags, four with a line style (SketchUp 2019)"),
                         ("sdk_saved_tag_line_styles_materials_2020", 5,
                          "five tags, four with a line style, and three materials (SketchUp 2020)")]:
    fixture(name, "a triangle on each tag, the tags carrying line styles: " + spec, triangles=tags)

# --- nothing to draw ----------------------------------------------------------------------------

# A file before 2021 names each class the first time it stores an object of it, in ASCII ("CFace"),
# so a file without that name has no face at all: these are checked here before claiming no mesh.
def faceless(name, spec):
    assert b"CFace" not in fixtures[name], name
    fixture(name, spec + "; no faces (no CFace class in its object stream), so nothing to convert",
            error="nothing to convert", error_kind="Empty")


faceless("blank_v17", "a model with no materials, definitions or instances, only Layer0")
faceless("legacy_empty_2020", "an empty SketchUp 2020 model: no faces, instances, definitions or materials")
faceless("zero_material_custom_layer_v18", "no materials, two guide lines on a custom tag")
faceless("single_material_v17", "one material (RedMat) and so no second for the reader to anchor on")
faceless("legacy_textured_colorize_2017", "textured materials with colorize modes and transparency")

