# --- the cases written here ---------------------------------------------------------------------

def floats(*values):
    return b"".join(struct.pack("<f", v) for v in values)


def close(a, b, eps=1e-9):
    return all(abs(x - y) <= eps * max(1.0, abs(y)) for x, y in zip(a, b))


def tile_case(name, files, model, what, spec=SPEC, check=None, extra=None, wrapped="auto", reach=None):
    """A case written here: its expectations decoded from the bytes as the real ones are, and
    held against `check`, the bounds its geometry was chosen to have."""
    files = {k: v.encode("utf-8") if isinstance(v, str) else v for k, v in files.items()}
    data = files[model]
    head = {"spec": "%s: %s" % (spec, what), "source": SRC}
    if len([f for f in files if f.rpartition(".")[2] in ("b3dm", "i3dm", "pnts", "cmpt", "glb", "gltf")]) != 1 \
            or model.endswith(".json"):
        head["file"] = model
    if model.endswith(".json"):
        drawn, reference = tileset(model, files)
        e = expectations(drawn, reference)
        e["document"] = {"source": {"format": "3D Tiles", "version": json.loads(data)["asset"]["version"]}}
        if "missing" in reference:
            e["facts"]["missing_tiles"] = len(reference["missing"])
            e["document"]["source"]["missingTiles"] = reference["missing"]
    else:
        drawn, reference = content(data, files)
        if reference["kind"] == "pnts" and drawn.cloud:
            e = pnts_expect(drawn, reference)
        else:
            e = expectations(drawn, reference, wrapped_node(data, files) if wrapped == "auto" else wrapped)
    if check is not None:
        got = drawn.bounds()
        assert close(got["min"], check[0]) and close(got["max"], check[1]), (name, got, check)
    for key, value in (extra or {}).items():
        if isinstance(value, dict) and isinstance(e.get(key), dict):
            e[key].update(value)
        else:
            e[key] = value
    if reach:
        # How far a placement's translation may be from the reference's, where it isn't a millimeter.
        reference["reach"] = reach
    write(name, files, {**head, **e}, rounded(reference, 12))


def error_case(name, files, model, what, error, kind, spec=SPEC, needs=None):
    e = {"spec": "%s: %s" % (spec, what), "source": SRC, "error": error, "error_kind": kind}
    if len(files) > 1 or model.endswith(".json"):
        e["file"] = model
    if needs:
        e["needs"] = needs
    write(name, files, e)


