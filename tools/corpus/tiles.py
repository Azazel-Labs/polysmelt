"""3D Tiles conformance cases: the tile formats of OGC 3D Tiles 1.0 (b3dm, i3dm, pnts, cmpt) and
tileset.json, as the specification defines them (github.com/CesiumGS/3d-tiles, specification/
TileFormats and the tileset schema).

This is a reference decoder written from the specification, and the expectations are what it
reads, never what Polysmelt reads:

- a tile's header (the two legacy b3dm layouts too), its feature table and batch table, with the
  properties their JSON places in the binary bodies;
- the embedded binary glTF 2.0, read far enough to place its meshes: nodes, accessors, indices;
- instances: positions (plain and quantized), NORMAL_UP and NORMAL_RIGHT (plain and oct-encoded
  in 32 bits), SCALE and SCALE_NON_UNIFORM, EAST_NORTH_UP on the WGS84 ellipsoid, RTC_CENTER;
- points: positions (plain and quantized), RGB, RGBA, RGB565 and CONSTANT_RGBA, NORMAL and
  NORMAL_OCT16P, BATCH_ID, and per-point batch table properties;
- a tileset's tree: transforms multiplied from the root down, REPLACE and ADD refinement to the
  finest level, external tilesets, glTF content.

Everything in tile space (Z up) is turned Y up for the expectations, (x, y, z) to (x, z, -y),
and the glTF in a tile is taken as it is: the specification's Y-up-to-Z-up transform and that
turn undo each other.

Beside each expect.json, reference.json holds what tests/tiles.rs compares exactly: hashes
(64-bit FNV-1a) of the positions as the file's single-precision values, of the colors as the
levels the file stores, and of each attribute; the node translation the file's RTC_CENTER or
quantized volume gives; each instance's transform; the batch table decoded; and each tile's
placement in a tileset. Draco data isn't decoded here: the three Draco tiles hold the same
clouds as uncompressed tiles beside them (their uncompressed properties are byte for byte the
same), and are held to those.

The real tiles are from CesiumJS's test data (CesiumGS/cesium, Specs/Data/Cesium3DTiles, at the
commit CESIUM below; Apache-2.0, LICENSE-cesium). They are kept in their case folders, or read
from the folder given as the first argument (a copy of that directory, with the repository's
LICENSE.md in it). The rest are written here, byte by byte, for what the samples lack.

Run from the repository root:

    python tools/corpus/tiles.py [folder holding Cesium3DTiles]
"""

