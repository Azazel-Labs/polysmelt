def gray_png(value, size=2):
    """A solid gray PNG, one channel a pixel."""
    raw = b"".join(b"\x00" + bytes([value]) * size for _ in range(size))

    def chunk(kind, data):
        c = kind + data
        return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 0, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")


def cube_v():
    return "".join(f"v {x} {y} {z}\n" for x, y, z in CUBE_V)


def cube_vt_vn():
    s = "".join(f"vt {u} {v}\n" for u, v in UV)
    s += "".join(f"vn {n[0]} {n[1]} {n[2]}\n" for _, n in CUBE_QUADS)
    return s


def cube_tris_faces(fmt=lambda i: str(i + 1)):
    out = ""
    for q, _ in CUBE_QUADS:
        for t in ((q[0], q[1], q[2]), (q[0], q[2], q[3])):
            out += "f " + " ".join(fmt(i) for i in t) + "\n"
    return out


