"""HTR conformance cases: Hierarchical Translation-Rotation motion capture as Motion Analysis Corporation's HTR
description defines it. The file is in `[`sections`]`: `[Header]` (`NumSegments`, `NumFrames`, `DataFrameRate`,
`EulerRotationOrder`, `CalibrationUnits`, `RotationUnits`, `GlobalAxisofGravity`, `BoneLengthAxis`, `ScaleFactor`),
`[SegmentNames&Hierarchy]` (each segment and its parent, `GLOBAL` for a root), `[BasePosition]` (each segment's
translation, three angles and bone length), a section per segment with a row per frame (frame number, translation,
three angles, scale factor), and `[EndOfFile]`.

The document is the segments as nodes, in hierarchy order, their base pose the rest pose, and a `<segment>_end` node
for each segment without children at its bone length along the bone length axis. A frame's row is relative to the
base pose: T(base + row)·R(base)·R(row) on column vectors, the Euler order's first axis outermost (`ZYX` is
Rz·Ry·Rx). The segments stay in the file's unit and axes, under the `RootNode` every reader makes, which scales to
meters by `CalibrationUnits` and turns a Z or X gravity axis to glTF's Y up. The expected quaternions come from
multiplying 3×3 rotation matrices with numpy and converting the product, not from the reader's quaternion products,
and where each root segment is in the world from the gravity axis's matrix times its translation times the unit.
"""

