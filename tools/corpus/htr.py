AXIS = {"X": 0, "Y": 1, "Z": 2}


def matrix(axis, degrees):
    """The rotation by `degrees` about axis 0, 1 or 2, for column vectors."""
    a = math.radians(degrees)
    c, s = math.cos(a), math.sin(a)
    if axis == 0:
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    if axis == 1:
        return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def quaternion(m):
    """The unit quaternion [x, y, z, w] of rotation matrix `m` (Shepperd's method)."""
    t = np.trace(m)
    if t > 0:
        s = math.sqrt(t + 1.0) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, 0.25 * s]
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = [0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s]
    elif m[1, 1] > m[2, 2]:
        s = math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = [(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s]
    else:
        s = math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = [(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s]
    return [r(float(c)) for c in q]


def up_matrix(gravity):
    """The rotation taking the gravity axis to +Y."""
    a = gravity.strip().upper().lstrip("+")
    return {"Y": np.eye(3), "-Y": matrix(0, 180), "Z": matrix(0, -90), "-Z": matrix(0, 90), "X": matrix(2, 90),
            "-X": matrix(2, -90)}[a]


for g, v in (("Y", [0, 1, 0]), ("-Y", [0, -1, 0]), ("Z", [0, 0, 1]), ("-Z", [0, 0, -1]), ("X", [1, 0, 0]),
             ("-X", [-1, 0, 0])):
    assert np.allclose(up_matrix(g) @ v, [0, 1, 0]), g


def num(v):
    return f"{v:.6f}".rstrip("0").rstrip(".") if v != int(v) else str(int(v))


class Htr:
    """`segments` is [(name, parent or None)]; `base` maps a name to (tx, ty, tz, rx, ry, rz, bone length); `rows`
    maps a name to [(frame, tx, ty, tz, rx, ry, rz, scale factor)]."""

    def __init__(self, segments, base, rows, order="ZYX", units="mm", meters=0.001, rotation="Degrees", gravity="Y",
                 length_axis="Y", rate=60.0, hierarchy=True):
        self.segments, self.base, self.rows = segments, base, rows
        self.order, self.units, self.meters, self.rotation = order, units, meters, rotation
        self.gravity, self.length_axis, self.rate, self.hierarchy = gravity, length_axis, rate, hierarchy

    def header(self):
        h = {"FileType": "htr", "DataType": "HTRS", "FileVersion": "1", "NumSegments": str(len(self.segments)),
             "NumFrames": str(max([len(v) for v in self.rows.values()] + [0])),
             "DataFrameRate": num(self.rate) if self.rate else None, "EulerRotationOrder": self.order,
             "CalibrationUnits": self.units, "RotationUnits": self.rotation, "GlobalAxisofGravity": self.gravity,
             "BoneLengthAxis": self.length_axis, "ScaleFactor": "1.000000"}
        return {k: v for k, v in h.items() if v is not None}

    def text(self, nl="\n"):
        lines = ["#Created for a conformance test", "#Hierarchical Translation-Rotation", "[Header]"]
        lines += [f"{k} {v}" for k, v in self.header().items()]
        if self.hierarchy:
            lines += ["[SegmentNames&Hierarchy]", "#CHILD\tPARENT"]
            lines += [f"{n}\t{p or 'GLOBAL'}" for n, p in self.segments]
        lines += ["[BasePosition]", "#SegmentName Tx, Ty, Tz, Rx, Ry, Rz, BoneLength"]
        lines += [f"{n}\t" + "\t".join(num(v) for v in self.base[n]) for n, _ in self.segments]
        for n, _ in self.segments:
            if n not in self.rows:
                continue
            lines += [f"[{n}]", "#Fr\tTx\tTy\tTz\tRx\tRy\tRz\tSF"]
            lines += ["\t".join(num(v) if k else str(v) for k, v in enumerate(row)) for row in self.rows[n]]
        lines.append("[EndOfFile]")
        return nl.join(lines) + nl

    def deg(self, v):
        return math.degrees(v) if self.rotation.lower().startswith("rad") else v

    def rot(self, angles):
        """The rotation of angles (rx, ry, rz) in the Euler order, its first axis outermost."""
        m = np.eye(3)
        for a in self.order.upper():
            m = m @ matrix(AXIS[a], self.deg(angles[AXIS[a]]))
        return m

    def names(self):
        """Node names: the segments, then an `_end` node for each segment without children."""
        known = {n for n, _ in self.segments}
        parents = {p for _, p in self.segments if p in known}
        return [n for n, _ in self.segments] + [n + "_end" for n, _ in self.segments if n not in parents]

    def parent(self, name):
        known = {n for n, _ in self.segments}
        p = dict(self.segments)[name]
        return p if p in known else None

    def up(self):
        try:
            return up_matrix(self.gravity)
        except KeyError:
            return np.eye(3)

    def place(self, name, t, m):
        """A segment's local translation and quaternion, in the file's unit and axes."""
        t = np.array(t, dtype=float)
        return [r(float(c)) for c in t], quaternion(m)

    def world(self, t):
        """Where a root segment at `t` is in glTF's space: turned so gravity's axis is up, in meters."""
        return [r(float(c)) for c in self.up() @ np.array(t, dtype=float) * self.meters]

    def rest(self):
        out = [{"node": ROOT_NODE, "parent": None, "translation": [0, 0, 0], "rotation": quaternion(self.up()),
                "scale": [self.meters] * 3}]
        axis = {"X": [1, 0, 0], "-X": [-1, 0, 0], "Y": [0, 1, 0], "-Y": [0, -1, 0], "Z": [0, 0, 1],
                "-Z": [0, 0, -1]}.get(self.length_axis.upper().lstrip("+"), [0, 1, 0])
        for n, _ in self.segments:
            b = self.base[n]
            t, q = self.place(n, b[:3], self.rot(b[3:6]))
            entry = {"node": n, "parent": self.parent(n) or ROOT_NODE, "translation": t, "rotation": q,
                     "scale": [1, 1, 1]}
            if self.parent(n) is None:
                entry["world"] = self.world(b[:3])
            out.append(entry)
        for name in self.names():
            if name.endswith("_end") and name not in dict(self.segments):
                seg = name[:-4]
                out.append({"node": name, "parent": seg,
                            "translation": [r(c * self.base[seg][6]) for c in axis],
                            "rotation": [0, 0, 0, 1]})
        return out

    def first(self):
        return min(rows[0][0] for rows in self.rows.values() if rows)

    def posed(self, name, k):
        row = self.rows[name][k]
        b = self.base[name]
        t, q = self.place(name, [b[i] + row[1 + i] for i in range(3)], self.rot(b[3:6]) @ self.rot(row[4:7]))
        return {"node": name, "time": r((row[0] - self.first()) / (self.rate or 30.0), 9), "translation": t,
                "rotation": q}

    def keys(self, name):
        return {"node": name, "keys": {
            p: [r((row[0] - self.first()) / (self.rate or 30.0), 9) for row in self.rows[name]]
            for p in ("translation", "rotation")}}


def expect(spec, h, extra=(), facts=None, every=True, **more):
    animated = [n for n, _ in h.segments if h.rows.get(n)]
    f = {"segments": len(h.segments), "frames": max([len(h.rows.get(n, [])) for n, _ in h.segments] + [0])}
    if not h.hierarchy:
        f["global"] = True
    scaled = sum(1 for n in animated for row in h.rows[n] if len(row) > 7 and abs(row[7] - 1) > 1e-9)
    if scaled:
        f["scale_factors_dropped"] = scaled
    f.update(facts or {})
    rig = h.rest()
    if every:
        for n in animated:
            rig.append(h.keys(n))
            rig += [h.posed(n, k) for k in range(len(h.rows[n]))]
    e = {
        "spec": SPEC + ": " + spec,
        "source": SRC,
        "no_mesh": True,
        "facts": f,
        "document": {"nodes": len(h.names()) + 1, "animations": 1 if animated else 0, "channels": 2 * len(animated),
                     "node_names": h.names() + [ROOT_NODE]},
        "json": {"/asset/extras/source/format": "HTR",
                 "/asset/extras/source/upAxis": h.gravity if h.gravity.startswith("-") else "+" + h.gravity,
                 **unit_source(h.meters, h.units), "/asset/extras/source/metersPerUnit": h.meters,
                 "/asset/extras/source/frameRate": h.rate or 30.0,
                 "/asset/extras/source/assumed": None if h.rate else ["frameRate"],
                 # The root node is the last node, and the only one the scene lists: the file's roots are its
                 # children. What it does is what was converted.
                 "/scenes/0/nodes": [len(h.names())],
                 f"/nodes/{len(h.names())}/children":
                     [i for i, (n, _) in enumerate(h.segments) if h.parent(n) is None],
                 "/asset/extras/source/converted":
                     (([] if h.meters == 1.0 else ["units"])
                      + ([] if np.allclose(h.up(), np.eye(3)) else ["upAxis"])) or None},
        "rig": rig + list(extra),
    }
    if animated:
        e["json"]["/animations/0/name"] = CLIP
        e["json"]["/animations/0/samplers/0/interpolation"] = "LINEAR"
    else:
        e["json"]["/animations"] = None
    for k, v in more.items():
        if isinstance(v, dict) and isinstance(e.get(k), dict):
            e[k].update(v)
        else:
            e[k] = v
    return e


def write(name, spec, h, extra=(), text=None, **more):
    case(FMT, name, {f"{name}.htr": text if text is not None else h.text()}, expect(spec, h, extra, **more))


