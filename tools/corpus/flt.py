def sgi(width, height, channels, rle=False):
    """An SGI image: `channels` lists each channel's rows, bottom row first; stored or run-length
    encoded (each row a literal run)."""
    head = bytearray(512)
    put(head, 0, struct.pack(">HBBHHHH", 0x01DA, 1 if rle else 0, 1, 3, width, height, len(channels)))
    if not rle:
        return bytes(head) + b"".join(bytes(row) for ch in channels for row in ch)
    rows = [bytes([0x80 | len(row)]) + bytes(row) + b"\0" for ch in channels for row in ch]
    starts, at = [], 512 + 8 * len(rows)
    for row in rows:
        starts.append(at)
        at += len(row)
    return (bytes(head) + b"".join(struct.pack(">I", s) for s in starts) +
            b"".join(struct.pack(">I", len(row)) for row in rows) + b"".join(rows))


