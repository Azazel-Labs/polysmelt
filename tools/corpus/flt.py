def put(r, at, b):
    r[at:at + len(b)] = b


def name_bytes(s, n):
    return s.encode("ascii")[:n - 1]


class Flt:
    """An OpenFlight file being written, record by record."""

    def __init__(self, version=1640, units=0):
        self.b = bytearray()
        self.palette = 0
        h = bytearray(324)
        put(h, 4, b"db")
        put(h, 12, struct.pack(">i", version))
        h[62] = units
        self.raw(1, h)

    def raw(self, op, r):
        """A record whose bytes `r` start with room for its opcode and length."""
        put(r, 0, struct.pack(">HH", op, len(r)))
        self.b += r
        return self

    def rec(self, op, body):
        return self.raw(op, bytearray(4) + bytearray(body))

    def push(self):
        return self.rec(10, b"")

    def pop(self):
        return self.rec(11, b"")

    def node(self, op, size, name, fields=()):
        """A node record of `size` bytes named `name`, `fields` (offset, bytes) set in it."""
        r = bytearray(size)
        put(r, 4, name_bytes(name, 8))
        for at, b in fields:
            put(r, at, b)
        return self.raw(op, r)

    def group(self, name, fields=()):
        return self.node(2, 44, name, fields)

    def object(self, name, transparency=0):
        return self.node(4, 28, name, [(18, struct.pack(">H", transparency))])

    def lod(self, name, switch_in, switch_out, center=(0.0, 0.0, 0.0)):
        return self.node(73, 80, name, [(16, struct.pack(">dd", switch_in, switch_out)),
                                        (40, struct.pack(">3d", *center))])

    def switch(self, name, current, masks):
        r = struct.pack(">III", current, len(masks), 1) + b"".join(struct.pack(">I", m) for m in masks)
        return self.node(96, 28 + 4 * len(masks), name, [(16, r)])

    def matrix(self, m):
        """A matrix of 16 numbers, row by row (row vectors: the translation in the last row)."""
        return self.rec(49, struct.pack(">16f", *m))

    def long_id(self, name):
        return self.rec(33, name.encode("ascii") + b"\0")

    def instance(self, op, number):
        return self.rec(op, struct.pack(">hH", 0, number))

    def replicate(self, n):
        return self.rec(60, struct.pack(">hh", n, 0))

    def external(self, path, flags):
        r = bytearray(216)
        put(r, 4, path.encode("ascii"))
        put(r, 208, struct.pack(">I", flags))
        return self.raw(63, r)

    def colors(self, colors):
        """A color palette: its entries' red, green and blue, stored as a, b, g, r."""
        r = bytearray(132 + 1024 * 4)
        for k, c in enumerate(colors):
            put(r, 132 + 4 * k, bytes([255, c[2], c[1], c[0]]))
        return self.raw(32, r)

    def material(self, index, name, diffuse, alpha=1.0, emissive=(0, 0, 0), specular=(0, 0, 0), shininess=0.0):
        r = bytearray(84)
        put(r, 4, struct.pack(">i", index))
        put(r, 8, name_bytes(name, 12))
        put(r, 24, struct.pack(">3f", 0.2, 0.2, 0.2))
        put(r, 36, struct.pack(">3f", *diffuse))
        put(r, 48, struct.pack(">3f", *specular))
        put(r, 60, struct.pack(">3f", *emissive))
        put(r, 72, struct.pack(">ff", shininess, alpha))
        return self.raw(113, r)

    def texture(self, index, path):
        r = bytearray(216)
        put(r, 4, path.encode("ascii"))
        put(r, 204, struct.pack(">i", index))
        return self.raw(64, r)

    def vertices(self, verts):
        """A vertex palette: each vertex a dict of "p" and optional "uv", "n" and "rgb" (packed);
        returns each one's offset from the palette's start."""
        records = []
        for v in verts:
            n, uv, rgb = v.get("n"), v.get("uv"), v.get("rgb")
            op, size = {(False, False): (68, 40), (True, False): (69, 56),
                        (True, True): (70, 64), (False, True): (71, 48)}[(n is not None, uv is not None)]
            r = bytearray(size)
            put(r, 6, struct.pack(">H", 0x1000 if rgb else 0x2000))
            put(r, 8, struct.pack(">3d", *v["p"]))
            at = 32
            if n is not None:
                put(r, at, struct.pack(">3f", *n))
                at += 12
            if uv is not None:
                put(r, at, struct.pack(">2f", *uv))
                at += 8
            if rgb:
                put(r, at, bytes([255, rgb[2], rgb[1], rgb[0]]))
            put(r, 0, struct.pack(">HH", op, size))
            records.append(r)
        offsets, at = [], 8
        for r in records:
            offsets.append(at)
            at += len(r)
        self.rec(67, struct.pack(">I", at))
        for r in records:
            self.b += r
        return offsets

    def face(self, name, corners, draw=0, light=2, flags=F_NO_COLOR, color=0xFFFFFFFF, packed=(255, 255, 255),
             texture=-1, material=-1, transparency=0, after=()):
        """A face of `corners` (vertex palette offsets); `after` are records between its push and
        pop before its vertex list."""
        r = bytearray(80)
        put(r, 4, name_bytes(name, 8))
        r[18] = draw
        put(r, 28, struct.pack(">hh", texture, material))
        put(r, 40, struct.pack(">H", transparency))
        put(r, 44, struct.pack(">I", flags))
        r[48] = light
        put(r, 56, bytes([255, packed[2], packed[1], packed[0]]))
        put(r, 68, struct.pack(">I", color))
        self.raw(5, r).push()
        for op, body in after:
            self.rec(op, body)
        self.rec(72, b"".join(struct.pack(">i", c) for c in corners))
        return self.pop()

    def bytes(self):
        return bytes(self.b)


def z_up(p, meters=1.0):
    return [p[0] * meters, p[2] * meters, -p[1] * meters]


def bounds(points):
    return {"min": [round(min(p[k] for p in points), 9) for k in range(3)],
            "max": [round(max(p[k] for p in points), 9) for k in range(3)]}


def lin(rgb):
    return [srgb_to_linear(c / 255) for c in rgb]


def quad_at(x, y=0.0, size=1.0, z=0.0, **more):
    """A square in the XY plane facing +Z, its corners counterclockwise."""
    return [dict(p=(x, y, z), **more), dict(p=(x + size, y, z), **more),
            dict(p=(x + size, y + size, z), **more), dict(p=(x, y + size, z), **more)]


def square_bounds(squares, meters=1.0):
    """The bounds of squares (x, y, size) in the XY plane, turned Y up."""
    pts = []
    for x, y, s in squares:
        pts += [z_up((x, y, 0), meters), z_up((x + s, y + s, 0), meters)]
    return bounds(pts)


