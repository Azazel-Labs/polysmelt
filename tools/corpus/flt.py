"""OpenFlight conformance cases: the binary scene database of visual simulation, as the OpenFlight
Scene Description Database Specification (version 16.4) defines it.

A file is a stream of big-endian records, each an opcode and a length: a header (version and
units), palettes (colors, materials, textures, light sources), a vertex palette, and a tree of
nodes (groups, objects, levels of detail, switches, instances, references to other files), whose
children sit between push and pop records. A face lists the vertex palette offsets of its corners;
a mesh lists triangle strips, fans, quadrilateral strips and polygons of its own vertex pool.
Matrix records place the node they follow (row vectors, the translation in the last row).

OpenFlight is Z up, counterclockwise from the front, in the header's units; glTF is Y up and in
meters, so a point (x, y, z) is (x, z, -y) there, times the units' meters. A face's color is a
packed RGB, or a color palette entry and an intensity (index >> 7, (index & 127) / 127); its
transparency t makes its alpha 1 - t / 65535. Colors are display (sRGB) values. A face's light
mode says whether it's lit (2, 3) and whether it takes its vertices' colors (1, 3). Draw type 1 is
two sided, 2 and 3 wireframe (closed and open), 8 and up light points. Of levels of detail sharing
a center, the most detailed is drawn; a switch draws the children its current mask shows; an
animated group shows its children in turn over its loop duration. A replicated node is drawn once
in place and once more for each replication, its matrix applied again each time.
"""

