def pool(points, uv_scale):
    """A local vertex pool of positions, normals (+Z) and texture coordinates."""
    mask = 0x80000000 | (0x80000000 >> 3) | (0x80000000 >> 4)
    body = struct.pack(">II", len(points), mask)
    for x, y in points:
        body += struct.pack(">3d3f2f", x, y, 0.0, 0.0, 0.0, 1.0, x * uv_scale[0], y * uv_scale[1])
    return body


def primitive(kind, size, idx):
    fmt = {1: "B", 2: "H", 4: "I"}[size]
    return struct.pack(">hHI", kind, size, len(idx)) + b"".join(struct.pack(">" + fmt, i) for i in idx)


