INDICES = " ".join(" ".join(str(i) for i in q) + " -1" for q, _ in CUBE_QUADS)
CUBE = {"triangles": 12, "bounds": {"min": [0, 0, 0], "max": [1, 1, 1]}, "area": 6.0, "faces_outward": True}


def lin(c):
    return [r(srgb_to_linear(x)) for x in c]


def ifs(extra="", coord_extra="", indices=INDICES):
    return (f"IndexedFaceSet {{ {extra} coord Coordinate {{ point [ {POINTS} ] {coord_extra} }} "
            f"coordIndex [ {indices} ] }}")


def shape(geometry, appearance="appearance Appearance { material Material { diffuseColor 1 0 0 } }"):
    return f"Shape {{ {appearance} geometry {geometry} }}"


def wrl(body):
    return "#VRML V2.0 utf8\n" + body + "\n"


def x3dv(body, version="3.3", head=""):
    return f"#X3D V{version} utf8\nPROFILE Interchange\n{head}" + body + "\n"


def x3d(body, version="3.3", head=""):
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<X3D profile="Interchange" version="{version}">\n'
            f"<head>{head}</head>\n<Scene>\n{body}\n</Scene>\n</X3D>\n")


XML_CUBE = (f'<IndexedFaceSet coordIndex="{INDICES}"><Coordinate point="{POINTS}"/></IndexedFaceSet>')
RED = "<Appearance><Material diffuseColor='1 0 0'/></Appearance>"


