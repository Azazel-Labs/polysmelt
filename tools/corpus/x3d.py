"""X3D and VRML97 conformance cases: the classic encoding (ISO/IEC 14772-1 VRML97, .wrl; ISO/IEC
19776-2 X3D classic VRML encoding, .x3dv), the XML encoding (ISO/IEC 19776-1, .x3d) and both
gzipped (.wrz, .x3dz). Covers grouping and transforms (center, scale orientation is identity),
DEF and USE, Inline, Switch and LOD, IndexedFaceSet with separate indices, per-face colors,
ccw and solid, the triangle sets, ElevationGrid and the primitives, Extrusion, the 2D nodes,
the line and point sets, PROTO and EXTERNPROTO (and their XML forms), Material,
PhysicalMaterial and textures, UNIT length, viewpoints and lights. X3D is Y up in meters, as
glTF is.
"""

