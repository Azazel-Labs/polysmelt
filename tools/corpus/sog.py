"""SOG conformance cases: PlayCanvas's Spatially Ordered Gaussians, a meta.json and lossless
WebP images a pixel a splat, zipped as `.sog` or loose in a folder (the model is meta.json).

Versions 2 and 3 follow the specification (developer.playcanvas.com, "The SOG Format" and "The
SOG Format (Version 2)"); version 1, which has none, follows splat-transform's read-sog-v1.ts.
`packed_splats.py` writes the files, images included, and returns each splat as its quantized
form decodes, by the specification's own rule; the expectations come from those. The axes are
3D gaussian splatting's (right, down, forward), so y and z flip on the way to glTF.

Also one real file from the PlayCanvas engine's examples (assets/splats/playbot/6_0, a level of
detail of a streamed scene, written by splat-transform 0.16.0): CC-BY-4.0, its notice kept
beside the case as LICENSE-playbot.txt. It is kept in its case folder when this script empties
the corpus (or taken from the folder given as the first argument, which holds the engine's
playbot/6_0 files and playbot.txt). Its expectations come from its images as ffmpeg or Pillow
decodes them, whichever is there, put through the specification's decoding here.
"""

import json
import math
import os
import subprocess
import sys

# The shared modules are beside this script, which `python -I` leaves off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, case, fresh, r, srgb_to_linear  # noqa: E402
from packed_splats import SH_C0, sog, webp, zipped  # noqa: E402

FMT = "sog"
SRC = "generated by tools/corpus/sog.py"
SPEC = "SOG (PlayCanvas, The SOG Format)"
EXT = "KHR_gaussian_splatting"
REAL = "playcanvas_playbot"
REAL_FILES = ["meta.json", "means_l.webp", "means_u.webp", "quats.webp", "scales.webp", "sh0.webp",
              "shN_centroids.webp", "shN_labels.webp"]
NOTICE = "LICENSE-playbot.txt"


def keep_real():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    out = {}
    for name in REAL_FILES + [NOTICE]:
        if src:
            p = os.path.join(src, "playbot.txt" if name == NOTICE else name)
        else:
            p = os.path.join(ROOT, FMT, *([] if name == NOTICE else [REAL]), name)
        with open(p, "rb") as f:
            out[name] = f.read()
    return out


def attributes(degree, more=()):
    names = ["POSITION", "COLOR_0", f"{EXT}:ROTATION", f"{EXT}:SCALE", f"{EXT}:OPACITY",
             f"{EXT}:SH_DEGREE_0_COEF_0"]
    for l in range(1, degree + 1):
        names += [f"{EXT}:SH_DEGREE_{l}_COEF_{k}" for k in range(2 * l + 1)]
    return names + list(more)


def color(s):
    """The flat color a splat is drawn in: its base color made linear, its opacity up to 1."""
    rgb = [min(max(0.5 + SH_C0 * c, 0.0), 1.0) for c in s["dc"]]
    return [r(srgb_to_linear(c), 4) for c in rgb] + [r(min(s["opacity"], 1.0), 4)]


def expect(spec, held, degree=0, source=None, more_attributes=(), every=1, **more):
    points = [[r(s["pos"][0]), r(-s["pos"][1]), r(-s["pos"][2])] for s in held]
    return {"spec": spec, "source": SRC, "triangles": 0, "points": len(held), "vertices": len(held),
            "colors": True, "tolerance": 1e-3, "facts": {"points": len(held), "splats": len(held)},
            "bounds": {"min": [min(p[k] for p in points) for k in range(3)],
                       "max": [max(p[k] for p in points) for k in range(3)]},
            "positions_include": points[::every], "colors_include": [color(s) for s in held[::every]],
            "document": {"attributes": attributes(degree, more_attributes),
                         "source": {"format": "SOG", "shDegree": degree, **(source or {})}},
            **more}


def splats(n, coeffs=0, seed=7, top=0.95):
    """`n` splats of values spread over each property's range, the same every run."""
    state = seed

    def rnd(lo=0.0, hi=1.0):
        nonlocal state
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        return lo + (hi - lo) * (state / 0x7FFFFFFF)

    out = []
    for i in range(n):
        q = [rnd(-1, 1) for _ in range(4)]
        # Each of w, x, y and z is the largest in turn.
        q[i % 4] = 2.0 if i % 8 < 4 else -2.0
        out.append({"pos": [rnd(-3, 3), rnd(-1, 2), rnd(-40, 40)], "rot": q,
                    "scale": [rnd(-6, 0) for _ in range(3)], "dc": [rnd(-1.7, 1.7) for _ in range(3)],
                    "opacity": rnd(0.05, top), "sh": [[rnd(-1, 1) for _ in range(3)] for _ in range(coeffs)]})
    return out


def error(name, files, spec, text, kind, file=None):
    e = {"spec": f"{SPEC}: {spec}", "source": SRC, "error": text, "error_kind": kind}
    if file:
        e["file"] = file
    case(FMT, name, files, e)


def rgba(data):
    """(width, height, RGBA bytes) of a WebP image, by Pillow or else ffmpeg."""
    try:
        import io

        from PIL import Image
        im = Image.open(io.BytesIO(data)).convert("RGBA")
        return im.width, im.height, im.tobytes()
    except ImportError:
        pass
    probe = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                            "stream=width,height", "-of", "csv=p=0", "-"], input=data, capture_output=True, check=True)
    w, h = (int(v) for v in probe.stdout.decode().strip().split(",")[:2])
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "-", "-f", "rawvideo", "-pix_fmt", "rgba", "-"],
                         input=data, capture_output=True, check=True).stdout
    assert len(raw) == w * h * 4
    return w, h, raw


def read_v2(files):
    """A version 2 SOG's positions, base colors and opacities, by the specification's sections
    3.1 and 3.4."""
    meta = json.loads(files["meta.json"])
    assert meta["version"] == 2
    n = meta["count"]
    _, _, lo = rgba(files[meta["means"]["files"][0]])
    _, _, hi = rgba(files[meta["means"]["files"][1]])
    _, _, c0 = rgba(files[meta["sh0"]["files"][0]])
    mins, maxs, book = meta["means"]["mins"], meta["means"]["maxs"], meta["sh0"]["codebook"]
    held = []
    for i in range(n):
        log = [mins[k] + (maxs[k] - mins[k]) * ((hi[4 * i + k] << 8 | lo[4 * i + k]) / 65535) for k in range(3)]
        held.append({"pos": [math.copysign(math.exp(abs(v)) - 1, v) for v in log],
                     "dc": [book[c0[4 * i + k]] for k in range(3)], "opacity": c0[4 * i + 3] / 255})
    return meta, held


def main():
    real = keep_real()
    notice = os.path.join(ROOT, FMT, NOTICE)
    if os.path.exists(notice):
        os.remove(notice)
    fresh(FMT)
    with open(notice, "wb") as f:
        f.write(real[NOTICE])

    # --- versions and layouts -----------------------------------------------------------------

    files, _, held = sog(splats(9), version=2)
    case(FMT, "version_2", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 2, zipped: codebooks, the smallest three of a rotation, opacity a byte", held,
                source={"version": "2", "zipped": True, "tool": "tools/corpus/sog.py", "upAxis": "-Y"}))

    case(FMT, "version_2_folder", files,
         expect(f"{SPEC}: version 2, a meta.json beside its images", held, source={"version": "2"},
                file="meta.json", json={"/asset/extras/source/zipped": None}))

    case(FMT, "meta_first_in_zip", {"scene.sog": zipped(files, ["meta.json"] + [n for n in files if n != "meta.json"])},
         expect(f"{SPEC}: a zip whose first entry is meta.json", held))

    files, _, held = sog(splats(9), version=1)
    case(FMT, "version_1", files,
         expect(f"{SPEC}: version 1 (no version; splat-transform's read-sog-v1.ts): bytes between each "
                "property's bounds, opacity a logit, the count in the means' shape", held,
                source={"version": "1"}, file="meta.json"))

    files, _, held = sog(splats(9, 8), version=1, bands=2)
    case(FMT, "version_1_sh_degree_2", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 1 with a palette of harmonics between two bounds, its bands told by the "
                "centroids image's width", held, 2, source={"version": "1"}))

    files, _, held = sog(splats(9), version=3)
    case(FMT, "version_3", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 3: a rotation's exponential map, opacity the square of a byte over 204", held,
                source={"version": "3"}))

    files, meta, held = sog(splats(9, top=1.5), version=3)
    assert meta["opacity"]["max"] > 1
    case(FMT, "version_3_opacity_above_1", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 3, opacities above 1 held to 1, the most KHR_gaussian_splatting has", held,
                source={"opacityMax": meta["opacity"]["max"]}))

    # --- spherical harmonics ------------------------------------------------------------------

    for bands in (1, 2, 3):
        ss = splats(70, [3, 8, 15][bands - 1])
        files, _, held = sog(ss, version=2, bands=bands)
        case(FMT, f"sh_degree_{bands}", {"scene.sog": zipped(files)},
             expect(f"{SPEC}: version 2, harmonics of {bands} bands in a palette of two rows", held, bands, every=9,
                    json={f"/meshes/0/primitives/0/attributes/{EXT}:SH_DEGREE_{bands + 1}_COEF_0": None}))

    ss = splats(9, 24)
    files, _, held = sog(ss, version=3, bands=4)
    case(FMT, "version_3_sh_degree_4", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 3, the fourth band dropped, KHR_gaussian_splatting stops at 3", held, 3,
                source={"droppedShDegree": 4},
                json={f"/meshes/0/primitives/0/attributes/{EXT}:SH_DEGREE_4_COEF_0": None}))

    ss = splats(9, 3)
    files, meta, held = sog(ss, version=2, bands=1, state_bands=False)
    assert "bands" not in meta["shN"] and "count" not in meta["shN"]
    case(FMT, "sh_bands_by_width", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: an early version 2 file, its shN without bands or count: the centroids image's "
                "width tells the bands, as PlayCanvas's engine has it", held, 1))

    # --- version 3's extras ---------------------------------------------------------------------

    ss = splats(9)
    blind = [[({"name": "segment", "type": "u16"}, [1000 * i + 7 for i in range(9)]),
              ({"name": "weight", "type": "unorm8"}, [i / 8 for i in range(9)]),
              ({"name": "depth", "type": "unorm8", "range": [0.5, 40]}, [0.5 + 4 * i for i in range(9)])],
             [({"name": "heat", "type": "f32"}, [0.25 * i - 1 for i in range(9)])]]
    files, _, held = sog(ss, version=3, blind=blind)
    case(FMT, "version_3_blind", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 3 blind data, two textures, as custom attributes", held,
                more_attributes=["_SEGMENT", "_WEIGHT", "_DEPTH", "_HEAT"]))

    files, _, held = sog(ss, version=3, meta_extra={
        "model": "antialiased", "extras": {"capturedBy": "rig-04"},
        "comments": ["Postshot v1.1.69", "postshot.color.eotf=sRGB"]})
    case(FMT, "version_3_model_extras_comments", {"scene.sog": zipped(files)},
         expect(f"{SPEC}: version 3's model, extras and comments, kept in the source", held,
                source={"model": "antialiased", "extras": {"capturedBy": "rig-04"},
                        "comments": ["Postshot v1.1.69", "postshot.color.eotf=sRGB"]}))

    files, _, _ = sog([], version=2)
    case(FMT, "empty", {"none.sog": zipped(files)},
         {"spec": f"{SPEC}: a file of no splats", "source": SRC, "no_mesh": True,
          "facts": {"points": 0, "splats": 0}})

    # --- errors ---------------------------------------------------------------------------------

    files, meta, _ = sog(splats(9), version=2)
    less = {n: d for n, d in files.items() if n != "quats.webp"}
    error("missing_image", less, "an image meta.json names isn't beside it", "quats.webp wasn't found",
          "MissingAsset", "meta.json")
    error("missing_image_zipped", {"scene.sog": zipped(less)}, "an image meta.json names isn't in the zip",
          "holds no quats.webp", "MissingAsset")
    error("no_meta", {"scene.sog": zipped({n: d for n, d in files.items() if n != "meta.json"}, list(less)[:2])},
          "a zip without meta.json", "no meta.json", "UnknownFormat")
    error("not_json", {"scene.sog": zipped({**files, "meta.json": b'{"version": 2, "count": 9, "means": {'})},
          "a meta.json cut short", "isn't JSON", "Corrupt")
    error("cut_zip", {"scene.sog": zipped(files)[:-40]}, "a zip without its directory", "can't be opened", "Corrupt")

    def with_meta(change):
        m = json.loads(json.dumps(meta))
        change(m)
        return {"scene.sog": zipped({**files, "meta.json": json.dumps(m).encode()})}

    def set_count(n):
        return lambda m: m.update(count=n)

    error("unknown_version", with_meta(lambda m: m.update(version=4)), "a version past 3", "version 4", "Unsupported")
    error("count_too_large", with_meta(set_count(4000000000)),
          "a count past Keep::max_points is refused before an image is read", "max_points", "LimitExceeded")
    error("count_past_images", with_meta(set_count(17)), "a count of more splats than the images have pixels",
          "fewer pixels", "Corrupt")
    error("short_codebook", with_meta(lambda m: m["scales"].update(codebook=m["scales"]["codebook"][:255])),
          "a codebook of fewer than 256 entries", "256 numbers", "Corrupt")
    error("no_files", with_meta(lambda m: m["means"].update(files=["means_l.webp"])),
          "positions with one image named", "too few files", "Corrupt")
    error("not_webp", {"scene.sog": zipped({**files, "scales.webp": b"\x89PNG\r\n\x1a\n" + bytes(40)})},
          "an image that isn't WebP", "isn't a WebP image", "Corrupt")
    error("cut_image", {"scene.sog": zipped({**files, "sh0.webp": files["sh0.webp"][:60]})},
          "an image cut short", "isn't a WebP image", "Corrupt")

    one = sog(splats(9, 3), version=2, bands=1)[0]
    error("centroids_width",
          {"scene.sog": zipped({**one, "shN_centroids.webp": webp(100, 1, [(128, 128, 128, 255)] * 100)})},
          "a centroids image whose width is no band count's", "wide", "Corrupt")

    # --- a real file ----------------------------------------------------------------------------

    files = {n: real[n] for n in REAL_FILES}
    meta, held = read_v2(files)
    e = expect("SOG version 2 as splat-transform 0.16.0 wrote it: a level of detail of a streamed scene, "
               "harmonics of 2 bands in a palette of 1024", held, 2, every=211, file="meta.json",
               source={"version": "2", "tool": meta["asset"]["generator"]})
    e["source"] = ("PlayCanvas engine examples (assets/splats/playbot/6_0), PLAYBOT by Stephane Agullo, "
                   "CC-BY-4.0, see ../LICENSE-playbot.txt")
    case(FMT, REAL, files, e)
    print("sog corpus written")


if __name__ == "__main__":
    main()
