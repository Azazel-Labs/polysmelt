"""TRC conformance cases: track row column marker motion as Motion Analysis Corporation's tools define it and
biomechanics tools read and write it. A TRC file is tab-separated text: `PathFileType`, a line
of header field names (`DataRate`, `CameraRate`, `NumFrames`, `NumMarkers`, `Units`, `OrigDataRate`, …) and a line
of their values, a line starting `Frame#` and `Time` that names each marker over its three columns, a line labeling
the columns `X1 Y1 Z1 …`, then a row per frame: its number, its time, and X, Y and Z per marker, empty cells where a
marker wasn't seen.

The document is a `markers` root and a node per marker, at its first sample, its track a linear translation channel
keyed at the rows where it was seen, the earliest sample at 0 seconds. Lengths become meters by `Units`; the file
doesn't say which way is up, and it's taken as Y up, as glTF is. Expectations come from the values the generator
wrote.
"""

