def bad(name, spec, text, error, kind):
    case(FMT, name, {f"{name}.trc": text}, {"spec": SPEC + ": " + spec, "source": SRC, "error": error,
                                            "error_kind": kind})


bad("not_trc", "a file that doesn't start with PathFileType", "Frame#\tTime\n1\t0\n", "not a TRC file", "UnknownFormat")
bad("empty_file", "an empty file", "", "the file is empty", "Empty")
bad("header_cut_short", "a file cut short before its header's values", "PathFileType\t4\nDataRate\tUnits\n",
    "header is missing", "Truncated")
bad("no_frame_line", "a fourth line that doesn't start with Frame#",
    write(NAMES, ROWS).replace("Frame#", "Time#", 1), "not Frame#", "Corrupt")
