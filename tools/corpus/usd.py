def ind(text, n=1):
    return "\n".join(("    " * n + line) if line else line for line in text.split("\n"))


def prim(typ, name, *body, meta=None, spec="def"):
    head = f'{spec} {typ} "{name}"' if typ else f'{spec} "{name}"'
    if meta:
        head += " (\n" + ind("\n".join(meta) if isinstance(meta, (list, tuple)) else meta) + "\n)"
    inner = "\n".join(b for b in body if b)
    return head + "\n{\n" + (ind(inner) + "\n" if inner else "") + "}"


def layer(*prims, up="Y", mpu=1.0, meta=()):
    head = ["#usda 1.0", "("]
    if up:
        head.append(f'    upAxis = "{up}"')
    if mpu is not None:
        head.append(f"    metersPerUnit = {mpu}")
    head += ["    " + m for m in meta]
    head.append(")")
    return "\n".join(head) + "\n\n" + "\n\n".join(prims) + "\n"


def v(seq):
    return "[" + ", ".join("(" + ", ".join(fnum(c) for c in p) + ")" for p in seq) + "]"


def fnum(c):
    return str(int(c)) if float(c) == int(c) else repr(float(c))


def ints(seq):
    return "[" + ", ".join(str(i) for i in seq) + "]"


def mesh(name, points, counts, indices, *extra, meta=None, sub="none"):
    body = [f"int[] faceVertexCounts = {ints(counts)}", f"int[] faceVertexIndices = {ints(indices)}",
            f"point3f[] points = {v(points)}"]
    if sub is not None:
        body.append(f'uniform token subdivisionScheme = "{sub}"')
    return prim("Mesh", name, *body, *extra, meta=meta)


def cube_points(size=1.0, at=(0, 0, 0)):
    return [tuple(at[k] + c * size for k, c in enumerate(p)) for p in CUBE_V]


CUBE_COUNTS = [4] * 6
