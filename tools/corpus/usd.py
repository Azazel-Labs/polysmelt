def case_dir(name):
    d = os.path.join(ROOT, FMT, name)
    os.makedirs(d, exist_ok=True)
    return d


def pin_zip_times(path):
    """Sets every entry's DOS time and date to 1980-01-01 00:00 in place, so regenerating a usdz gives the same
    bytes. Rewriting with zipfile would lose the 64-byte data alignment usdz requires."""
    data = bytearray(open(path, "rb").read())
    with zipfile.ZipFile(path) as z:
        infos = z.infolist()
    eocd = data.rfind(b"PK\x05\x06")
    central = struct.unpack_from("<I", data, eocd + 16)[0]
    for info in infos:
        assert data[info.header_offset:info.header_offset + 4] == b"PK\x03\x04"
        struct.pack_into("<HH", data, info.header_offset + 10, 0, 0x21)
    pos = central
    for _ in infos:
        assert data[pos:pos + 4] == b"PK\x01\x02"
        struct.pack_into("<HH", data, pos + 12, 0, 0x21)
        n, m, k = struct.unpack_from("<HHH", data, pos + 28)
        pos += 46 + n + m + k
    open(path, "wb").write(bytes(data))


def write(name, text, spec, expect, files=None, enc="usda", corners=False, measured=True, time=None):
    """Writes `text` as `name`.<enc>: usda as is; usdc and usd-crate exported by pxr; usdz packaged by pxr."""
    d = case_dir(name)
    for fname, data in (files or {}).items():
        p = os.path.join(d, fname)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        if fname.endswith(".usdc") and isinstance(data, str):
            tmp = p[:-1] + "a"
            with open(tmp, "w", encoding="utf-8", newline="\n") as f:
                f.write(data)
            Sdf.Layer.FindOrOpen(tmp).Export(p)
            os.remove(tmp)
            continue
        with open(p, "wb" if isinstance(data, bytes) else "w", **({} if isinstance(data, bytes) else
                                                                  {"encoding": "utf-8", "newline": "\n"})) as f:
            f.write(data)
    src = os.path.join(d, name + ".usda")
    with open(src, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    out = {"spec": f"{SPEC}: {spec}", "source": SRC}
    if measured:
        st, pts = measure(src, time)
        out.update(st)
        if corners:
            out["positions_include"] = pts
    out.update(expect)
    if enc == "usdc":
        Sdf.Layer.FindOrOpen(src).Export(os.path.join(d, name + ".usdc"))
        os.remove(src)
    elif enc == "usd-crate":
        Sdf.Layer.FindOrOpen(src).Export(os.path.join(d, name + ".usd"), args={"format": "usdc"})
        os.remove(src)
    elif enc == "usd-text":
        os.replace(src, os.path.join(d, name + ".usd"))
    elif enc.startswith("usdz"):
        root = src
        if enc == "usdz":
            root = os.path.join(d, name + "_root.usdc")
            Sdf.Layer.FindOrOpen(src).Export(root)
        assert UsdUtils.CreateNewUsdzPackage(Sdf.AssetPath(root), os.path.join(d, name + ".usdz"))
        pin_zip_times(os.path.join(d, name + ".usdz"))
        for f in os.listdir(d):
            if f != name + ".usdz":
                p = os.path.join(d, f)
                shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    if files:
        ext = {"usdc": ".usdc", "usd-crate": ".usd", "usd-text": ".usd"}.get(enc, ".usdz" if enc.startswith("usdz") else ".usda")
        out["file"] = name + ext
    case(FMT, name, {}, out)


