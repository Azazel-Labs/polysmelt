# --- expectations from pxr -------------------------------------------------------------------

def to_gltf(p, z_up, mpu):
    x, y, z = p
    if z_up:
        x, y, z = x, z, -y
    return (x * mpu, y * mpu, z * mpu)


def measure(path, time=None):
    """Triangles, surface area, bounds and corner positions of the meshes pxr shows."""
    stage = Usd.Stage.Open(path)
    z_up = UsdGeom.GetStageUpAxis(stage) == UsdGeom.Tokens.z
    mpu = UsdGeom.GetStageMetersPerUnit(stage)
    t = Usd.TimeCode.Default() if time is None else Usd.TimeCode(time)
    xc = UsdGeom.XformCache(t)
    tris, area, pts = 0, 0.0, []
    for p in stage.Traverse(Usd.TraverseInstanceProxies(Usd.PrimDefaultPredicate)):
        if not p.IsA(UsdGeom.Mesh):
            continue
        img = UsdGeom.Imageable(p)
        if img.ComputeVisibility(t) == UsdGeom.Tokens.invisible:
            continue
        if img.ComputePurpose() in (UsdGeom.Tokens.guide, UsdGeom.Tokens.proxy):
            continue
        m = UsdGeom.Mesh(p)
        points = m.GetPointsAttr().Get(t) or []
        counts = m.GetFaceVertexCountsAttr().Get(t) or []
        idx = list(m.GetFaceVertexIndicesAttr().Get(t) or [])
        holes = set(m.GetHoleIndicesAttr().Get(t) or [])
        world = xc.GetLocalToWorldTransform(p)
        wp = [to_gltf(world.Transform(Gf.Vec3d(*q)), z_up, mpu) for q in points]
        c = 0
        for f, n in enumerate(counts):
            corners = list(idx[c:c + n])
            c += n
            if n < 3 or f in holes or len(corners) < n or any(i < 0 or i >= len(wp) for i in corners):
                continue
            poly = [wp[i] for i in corners]
            tris += n - 2
            area += polygon_area(poly)
            pts += poly
    lo = [min(q[k] for q in pts) for k in range(3)]
    hi = [max(q[k] for q in pts) for k in range(3)]
    return {"triangles": tris, "area": r(area, 5),
            "bounds": {"min": [r(c) for c in lo], "max": [r(c) for c in hi]}}, \
        [[r(c) for c in q] for q in dict.fromkeys(pts)]


