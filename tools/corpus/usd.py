def cube(name="Cube", size=1.0, at=(0, 0, 0), *extra, normals=True, meta=None, sub="none"):
    ex = []
    if normals:
        ex.append(f"normal3f[] normals = {v(CUBE_NORMALS_FV)} (\n    interpolation = \"faceVarying\"\n)")
    return mesh(name, cube_points(size, at), CUBE_COUNTS, CUBE_INDICES, *ex, *extra, meta=meta, sub=sub)


def st_primvar(name="st", typ="texCoord2f"):
    return (f"{typ}[] primvars:{name} = {v(CUBE_ST)} (\n    interpolation = \"faceVarying\"\n)\n"
            f"int[] primvars:{name}:indices = {ints(CUBE_ST_IDX)}")


def xform(name, *body, ops=(), meta=None, typ="Xform"):
    """`ops` are (op name, type, value) and become the xformOpOrder in that order."""
    lines, order = [], []
    for op, typ_, val in ops:
        if op.startswith("!"):
            order.append(op)
            continue
        lines.append(f"{typ_} {op} = {val}")
        order.append(op)
    if order:
        lines.append("uniform token[] xformOpOrder = [" + ", ".join(f'"{o}"' for o in order) + "]")
    return prim(typ, name, *lines, *body, meta=meta)


def preview_material(name, *inputs, textures=(), extra=()):
    """A UsdPreviewSurface material; `inputs` are lines in the shader; `textures` are (input, file, output, type),
    optionally followed by more lines for the texture and a UsdTransform2d's lines for its coordinates."""
    shader = ['uniform token info:id = "UsdPreviewSurface"', *inputs, "token outputs:surface"]
    nodes = []
    if textures:
        nodes.append(prim("Shader", "uv", 'uniform token info:id = "UsdPrimvarReader_float2"',
                          'string inputs:varname = "st"', "float2 outputs:result"))
    for i, (inp, file, out, typ, *more) in enumerate(textures):
        tname = f"tex{i}"
        st = f"</Root/{name}/uv.outputs:result>"
        if len(more) > 1:
            nodes.append(prim("Shader", f"xf{i}", 'uniform token info:id = "UsdTransform2d"',
                              f"float2 inputs:in.connect = {st}", *more[1], "float2 outputs:result"))
            st = f"</Root/{name}/xf{i}.outputs:result>"
        lines = ['uniform token info:id = "UsdUVTexture"', f"asset inputs:file = @{file}@",
                 f"float2 inputs:st.connect = {st}", *(more[0] if more else ()),
                 f"{'float3' if out == 'rgb' else 'float'} outputs:{out}"]
        if inp == "normal":
            lines += ['token inputs:sourceColorSpace = "raw"', "float4 inputs:scale = (2, 2, 2, 1)",
                      "float4 inputs:bias = (-1, -1, -1, 0)"]
        nodes.append(prim("Shader", tname, *lines))
        shader.append(f"{typ} inputs:{inp}.connect = </Root/{name}/{tname}.outputs:{out}>")
    return prim("Material", name, f"token outputs:surface.connect = </Root/{name}/Surface.outputs:surface>",
                prim("Shader", "Surface", *shader), *nodes, *extra)


