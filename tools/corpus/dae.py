# Writing documents


def num(v):
    """A number as a file writes it."""
    if float(v).is_integer():
        return str(int(v))
    return repr(round(float(v), 9))


def nums(values):
    return " ".join(num(v) for v in values)


def flat(rows):
    return [x for row in rows for x in row]


def fsrc(sid, values, params=("X", "Y", "Z"), stride=None, offset=0, count=None):
    """A float <source>: `params` are names (an empty name is an unnamed, skipped param) or (name, type) pairs."""
    ps = []
    width = 0
    for p in params:
        name, ty = (p, "float") if isinstance(p, str) else p
        width += 16 if ty == "float4x4" else 1
        ps.append(f'<param name="{name}" type="{ty}"/>' if name else f'<param type="{ty}"/>')
    stride = stride or width
    if count is None:
        count = (len(values) - offset) // stride
    off = f' offset="{offset}"' if offset else ""
    return (f'<source id="{sid}"><float_array id="{sid}-array" count="{len(values)}">{nums(values)}</float_array>'
            f'<technique_common><accessor source="#{sid}-array" count="{count}" stride="{stride}"{off}>'
            f'{"".join(ps)}</accessor></technique_common></source>')


def name_src(sid, names, param, kind="Name"):
    return (f'<source id="{sid}"><{kind}_array id="{sid}-array" count="{len(names)}">{" ".join(names)}</{kind}_array>'
            f'<technique_common><accessor source="#{sid}-array" count="{len(names)}">'
            f'<param name="{param}" type="{"IDREF" if kind == "IDREF" else "name"}"/></accessor></technique_common>'
            f'</source>')


SOURCE_OF = {"VERTEX": "vtx", "NORMAL": "nrm", "TEXCOORD": "uv", "COLOR": "col"}


def inputs(gid, sems):
    """<input>s: `sems` are (semantic, offset) or (semantic, offset, set)."""
    out = []
    for s in sems:
        sem, off = s[0], s[1]
        suffix = SOURCE_OF[sem] if len(s) < 3 or sem != "TEXCOORD" else f"uv{s[2]}"
        set_ = f' set="{s[2]}"' if len(s) > 2 else ""
        out.append(f'<input semantic="{sem}" source="#{gid}-{suffix}" offset="{off}"{set_}/>')
    return "".join(out)


def geometry(gid, prims, positions, normals=None, uvs=None, colors=None, uv_sets=None, name=None):
    srcs = fsrc(f"{gid}-pos", flat(positions))
    if normals:
        srcs += fsrc(f"{gid}-nrm", flat(normals))
    if uvs:
        srcs += fsrc(f"{gid}-uv", flat(uvs), ("S", "T"))
    for k, s in enumerate(uv_sets or []):
        srcs += fsrc(f"{gid}-uv{k}", flat(s), ("S", "T"))
    if colors:
        srcs += fsrc(f"{gid}-col", flat(colors), ("R", "G", "B", "A")[:len(colors[0])])
    nm = f' name="{name}"' if name else ""
    return (f'<geometry id="{gid}"{nm}><mesh>{srcs}<vertices id="{gid}-vtx">'
            f'<input semantic="POSITION" source="#{gid}-pos"/></vertices>{prims}</mesh></geometry>')


def lib(kind, *items):
    return f"<library_{kind}>{''.join(items)}</library_{kind}>"


def node(body, nid=None, name=None, sid=None, kind=None):
    attrs = "".join(f' {k}="{v}"' for k, v in (("id", nid), ("name", name), ("sid", sid), ("type", kind)) if v)
    return f"<node{attrs}>{body}</node>"


def inst_geom(gid, binds=(), tag="instance_geometry", extra=""):
    """An instance; `binds` are (symbol, material id) or (symbol, material id, [(semantic, input set)])."""
    if not binds:
        return f'<{tag} url="#{gid}">{extra}</{tag}>'
    ims = []
    for b in binds:
        bvi = "".join(f'<bind_vertex_input semantic="{s}" input_semantic="TEXCOORD" input_set="{k}"/>'
                      for s, k in (b[2] if len(b) > 2 else []))
        ims.append(f'<instance_material symbol="{b[0]}" target="#{b[1]}">{bvi}</instance_material>')
    return (f'<{tag} url="#{gid}">{extra}<bind_material><technique_common>{"".join(ims)}</technique_common>'
            f'</bind_material></{tag}>')


def collada(libs, scene="", unit=None, up=None, version="1.4.1", asset_extra="", has_scene=True, decl=True):
    ns = NS14 if version.startswith("1.4") else NS15
    asset = asset_extra
    if unit:
        asset += f'<unit meter="{unit[0]}" name="{unit[1]}"/>'
    if up:
        asset += f"<up_axis>{up}</up_axis>"
    body = "".join(libs)
    if has_scene:
        body += (f'<library_visual_scenes><visual_scene id="Scene" name="Scene">{scene}</visual_scene>'
                 '</library_visual_scenes><scene><instance_visual_scene url="#Scene"/></scene>')
    head = '<?xml version="1.0" encoding="utf-8"?>\n' if decl else ""
    return f'{head}<COLLADA xmlns="{ns}" version="{version}">\n<asset>{asset}</asset>\n{body}\n</COLLADA>\n'


def effect(eid, shader="phong", channels="", newparams="", technique_extra="", effect_extra=""):
    return (f'<effect id="{eid}"><profile_COMMON>{newparams}<technique sid="common"><{shader}>{channels}</{shader}>'
            f'{technique_extra}</technique></profile_COMMON>{effect_extra}</effect>')


def material(mid, eid, name=None):
    nm = f' name="{name}"' if name else ""
    return f'<material id="{mid}"{nm}><instance_effect url="#{eid}"/></material>'


def color(tag, rgba):
    return f"<{tag}><color>{nums(rgba)}</color></{tag}>"


def flt(tag, v):
    return f"<{tag}><float>{num(v)}</float></{tag}>"


def tex(tag, sampler, texcoord="UVMap"):
    return f'<{tag}><texture texture="{sampler}" texcoord="{texcoord}"/></{tag}>'


def image(iid, path):
    return f'<image id="{iid}"><init_from>{path}</init_from></image>'


def sampler14(surface, sampler, image_id):
    """A 1.4 sampler2D reading a surface initialized from an image."""
    return (f'<newparam sid="{surface}"><surface type="2D"><init_from>{image_id}</init_from></surface></newparam>'
            f'<newparam sid="{sampler}"><sampler2D><source>{surface}</source></sampler2D></newparam>')


