def bspline(b, p0, p1, a, s):
    return ((1 - s) ** 3 * b + (3 * s ** 3 - 6 * s ** 2 + 4) * p0 + (-3 * s ** 3 + 3 * s ** 2 + 3 * s + 1) * p1
            + s ** 3 * a) / 6


def cardinal(b, p0, p1, a, s):
    t0, t1 = (p1 - b) / 2, (a - p0) / 2
    return ((2 * s ** 3 - 3 * s ** 2 + 1) * p0 + (s ** 3 - 2 * s ** 2 + s) * t0 + (-2 * s ** 3 + 3 * s ** 2) * p1
            + (s ** 3 - s ** 2) * t1)


def spline_at(f, values, t):
    """A uniform spline over keys one second apart, the first and last keys standing in past the ends."""
    k = int(t)
    v = lambda i: values[max(0, min(i, len(values) - 1))]
    return f(v(k - 1), v(k), v(k + 1), v(k + 2), t - k)


