# The cube, and math for the expectations


def cube_tris():
    """The unit cube's triangles as (corner indices, face index)."""
    out = []
    for f, (q, _) in enumerate(CUBE_QUADS):
        out += [((q[0], q[1], q[2]), f), ((q[0], q[2], q[3]), f)]
    return out


CUBE_N = [n for _, n in CUBE_QUADS]
QUAD_UV = [(0, 0), (1, 0), (1, 1), (0, 1)]


def cube_triangles_prim(gid, material=None):
    p = []
    for (a, b, c), f in cube_tris():
        p += [a, f, b, f, c, f]
    mat = f' material="{material}"' if material else ""
    return (f'<triangles count="12"{mat}>{inputs(gid, [("VERTEX", 0), ("NORMAL", 1)])}<p>{nums(p)}</p>'
            "</triangles>")


def cube_polylist_prim(gid, material=None):
    p = []
    for f, (q, _) in enumerate(CUBE_QUADS):
        for k, v in enumerate(q):
            p += [v, f, k]
    mat = f' material="{material}"' if material else ""
    sems = [("VERTEX", 0), ("NORMAL", 1), ("TEXCOORD", 2, 0)]
    return (f'<polylist count="6"{mat}>{inputs(gid, sems)}<vcount>{nums([4] * 6)}</vcount><p>{nums(p)}</p>'
            "</polylist>")


def cube(gid="Cube", scale=(1, 1, 1), material=None, uvs=False, name=None):
    pos = [tuple(c * s for c, s in zip(v, scale)) for v in CUBE_V]
    if uvs:
        prim = cube_polylist_prim(gid, material)
        return geometry(gid, prim, pos, CUBE_N, uv_sets=[QUAD_UV], name=name)
    return geometry(gid, cube_triangles_prim(gid, material), pos, CUBE_N, name=name)


def mat_mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)] for i in range(4)]


def ident():
    return [[float(i == j) for j in range(4)] for i in range(4)]


def translate(x, y, z):
    m = ident()
    m[0][3], m[1][3], m[2][3] = x, y, z
    return m


def scale(x, y, z):
    m = ident()
    m[0][0], m[1][1], m[2][2] = x, y, z
    return m


def rotate(axis, deg):
    """Rodrigues' rotation about a unit axis, for column vectors."""
    x, y, z = axis
    n = math.sqrt(x * x + y * y + z * z)
    x, y, z = x / n, y / n, z / n
    a = math.radians(deg)
    c, s, t = math.cos(a), math.sin(a), 1 - math.cos(a)
    return [[t * x * x + c, t * x * y - s * z, t * x * z + s * y, 0],
            [t * x * y + s * z, t * y * y + c, t * y * z - s * x, 0],
            [t * x * z - s * y, t * y * z + s * x, t * z * z + c, 0],
            [0, 0, 0, 1]]


def apply(m, p):
    return [sum(m[i][k] * (p[k] if k < 3 else 1) for k in range(4)) for i in range(3)]


def bounds(points):
    return {"min": [r(min(p[k] for p in points)) for k in range(3)],
            "max": [r(max(p[k] for p in points)) for k in range(3)]}


def quat(axis, deg):
    x, y, z = axis
    n = math.sqrt(x * x + y * y + z * z)
    h = math.radians(deg) / 2
    return [r(x / n * math.sin(h)), r(y / n * math.sin(h)), r(z / n * math.sin(h)), r(math.cos(h))]


def row_major(m):
    return flat(m)


def z_up(p):
    return [p[0], p[2], -p[1]]


def x_up(p):
    return [-p[1], p[0], p[2]]


def lin(c):
    return [r(srgb_to_linear(c[0])), r(srgb_to_linear(c[1])), r(srgb_to_linear(c[2]))] + list(c[3:])


def cube_expect(**more):
    e = {"triangles": 12, "bounds": CUBE_BOUNDS, "area": 6, "normals_in": AXES,
         "winding_matches_normals": True, "faces_outward": True}
    e.update(more)
    return e


def one_cube_doc(geom=None, inst=None, **kw):
    return collada([lib("geometries", geom or cube())], node(inst or inst_geom("Cube"), "Box", "Box"), **kw)


def write(name, files, spec, **expect):
    e = {"spec": spec, "source": SRC}
    e.update(expect)
    case(FMT, name, files, e)


