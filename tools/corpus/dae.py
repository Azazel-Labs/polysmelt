def bez(p0, c0, c1, p1, s):
    u = 1 - s
    return u * u * u * p0 + 3 * u * u * s * c0 + 3 * u * s * s * c1 + s * s * s * p1


def bezier_at(t, k0, out, inn, k1):
    """The value of a 2D Bezier segment at time t: solve the time curve for s, then evaluate the value curve."""
    lo, hi = 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if bez(k0[0], out[0], inn[0], k1[0], mid) < t:
            lo = mid
        else:
            hi = mid
    s = (lo + hi) / 2
    return bez(k0[1], out[1], inn[1], k1[1], s)


