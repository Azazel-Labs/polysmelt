def sampler(sid, times, values, interp, out_params=("X",), tangents=None):
    """A <source> set and <sampler>; `interp` is one name or a list; `tangents` are (in, out) value lists of
    (time, value) pairs."""
    names = interp if isinstance(interp, list) else [interp] * len(times)
    xml = (fsrc(f"{sid}-input", times, ("TIME",)) + fsrc(f"{sid}-output", values, out_params)
           + name_src(f"{sid}-interp", names, "INTERPOLATION"))
    ins = (f'<input semantic="INPUT" source="#{sid}-input"/><input semantic="OUTPUT" source="#{sid}-output"/>'
           f'<input semantic="INTERPOLATION" source="#{sid}-interp"/>')
    if tangents:
        xml += fsrc(f"{sid}-in", flat(tangents[0]), ("X", "Y")) + fsrc(f"{sid}-out", flat(tangents[1]), ("X", "Y"))
        ins += (f'<input semantic="IN_TANGENT" source="#{sid}-in"/>'
                f'<input semantic="OUT_TANGENT" source="#{sid}-out"/>')
    return xml + f'<sampler id="{sid}">{ins}</sampler>'


