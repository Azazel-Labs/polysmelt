def write_text(m, fmt="%.16g", dimension_line=False, comments=False, end=True, hexaedra=False):
    out = "MeshVersionFormatted %d\n" % m.version
    if comments:
        out = "# a comment before anything\n" + out + "# and one after the version\n"
    out += ("Dimension\n%d\n" if dimension_line else "\nDimension %d\n") % m.dim
    out += "\nVertices\n%d\n" % len(m.points)
    for p, ref in zip(m.points, m.refs):
        out += " ".join(fmt % c for c in p) + " %d\n" % ref
    for keyword, rows, refs in m.blocks:
        if hexaedra and keyword == "Hexahedra":
            keyword = "Hexaedra"
        out += "\n%s\n%d\n" % (keyword, len(rows))
        for nodes, ref in zip(rows, refs):
            out += " ".join(str(n) for n in nodes) + " %d\n" % ref
    for keyword, vectors, pairs_keyword, pairs in [("Normals", m.normals, "NormalAtVertices", m.normal_at),
                                                   ("Tangents", m.tangents, "TangentAtVertices", m.tangent_at)]:
        if vectors:
            out += "\n%s\n%d\n" % (keyword, len(vectors))
            for v in vectors:
                out += " ".join(fmt % c for c in v) + "\n"
        if pairs is not None:
            out += "\n%s\n%d\n" % (pairs_keyword, len(pairs))
            for pair in pairs:
                out += "%d %d\n" % pair
    for keyword, _, lines in m.others:
        out += "\n%s\n%d\n" % (keyword, len(lines))
        for line in lines:
            out += " ".join(str(v) for v in line) + "\n"
    return (out + ("\nEnd\n" if end else "")).encode()


def write_binary(m, version=2, big=False, end=True, positions=True):
    """A binary file: each keyword's code, where the next keyword starts, and for all but the
    dimension its count and its lines. A float is 4 bytes in version 1, a position 8 from
    version 3, and a whole number 8 in version 4."""
    e = ">" if big else "<"
    real = "f" if version == 1 else "d"
    position = "q" if version >= 3 else "i"
    whole = "q" if version == 4 else "i"
    out = struct.pack(e + "ii", 1, version)

    def keyword(code, body):
        nonlocal out
        start = len(out) + 4 + struct.calcsize(position)
        out += struct.pack(e + "i" + position, code, start + len(body) if positions else 0) + body

    keyword(3, struct.pack(e + "i", m.dim))
    body = struct.pack(e + whole, len(m.points))
    for p, ref in zip(m.points, m.refs):
        body += struct.pack("%s%d%s%s" % (e, m.dim, real, whole), *p, ref)
    keyword(4, body)
    for name, rows, refs in m.blocks:
        body = struct.pack(e + whole, len(rows))
        for nodes, ref in zip(rows, refs):
            body += struct.pack("%s%d%s" % (e, len(nodes) + 1, whole), *nodes, ref)
        keyword(KEYWORDS[name][0], body)
    for code, vectors, pairs_code, pairs in [(60, m.normals, 20, m.normal_at), (59, m.tangents, 61, m.tangent_at)]:
        if vectors:
            body = struct.pack(e + whole, len(vectors))
            for v in vectors:
                body += struct.pack("%s%d%s" % (e, m.dim, real), *v)
            keyword(code, body)
        if pairs is not None:
            body = struct.pack(e + whole, len(pairs))
            for pair in pairs:
                body += struct.pack(e + "2" + whole, *pair)
            keyword(pairs_code, body)
    for _, code, lines in m.others:
        body = struct.pack(e + whole, len(lines))
        for line in lines:
            body += struct.pack("%s%d%s" % (e, len(line), whole), *line)
        keyword(code, body)
    if end:
        out += struct.pack(e + "i" + position, 54, 0)
    return out


