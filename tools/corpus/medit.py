"""Medit conformance cases: .mesh (text) and .meshb (binary, versions 1 to 4) files, the INRIA
mesh format as the libMeshb documentation and the Medit technical report define it.

The files are written by Gmsh (which writes the text form), by meshio (text, and binary versions
3 and 4), and by the writers here for what neither writes: binary versions 1 and 2, big-endian
files, a two-dimensional mesh, the higher-order keywords, normals and tangents.

The expectations never come from Polysmelt. A file Gmsh or meshio wrote is read back with meshio.
A file written here is expected to hold what was written, and where meshio reads it, meshio must
agree. What's drawn is then worked out with VTK (cellmesh.py): the elements of each reference and
dimension are a mesh, volume elements draw as the faces only one of the group's elements has, and
that count is held against vtkDataSetSurfaceFilter's. Beside each expect.json, reference.json
holds hashes of the exact points and of every triangle, line and point drawn with its attributes,
which tests/fem.rs compares with what Polysmelt reads.

Three real files from meshio's test meshes (MIT, LICENSE-meshio) are kept in their case folders.

Run from the repository root with a Python that has gmsh, meshio and vtk installed:

    python tools/corpus/medit.py [folder holding the real files]
"""

