KINDS = ["Point", "Curve", "Surface", "Volume"]


class Mesh:
    """A mesh as a file lists it: `points` (each of `dim` coordinates) with a reference each,
    `blocks` of (keyword, elements as rows of nodes from 1, a reference each), and normals and
    tangents with the (vertex, vector) pairs that assign them, from 1."""

    def __init__(self, dim=3, version=2):
        self.dim = dim
        self.version = version
        self.points = []
        self.refs = []
        self.blocks = []
        self.normals = []
        self.normal_at = None
        self.tangents = []
        self.tangent_at = None
        # Keywords written as they are, which aren't read: (name, code, lines of whole numbers).
        self.others = []


def read_meshio(path):
    """What meshio reads from the file."""
    got = meshio.read(path)
    m = Mesh(got.points.shape[1])
    m.points = [tuple(float(c) for c in p) for p in got.points]
    m.refs = [int(v) for v in got.point_data["medit:ref"]]
    for block, refs in zip(got.cells, got.cell_data["medit:ref"]):
        m.blocks.append((FROM_MESHIO[block.type], [[int(n) + 1 for n in row] for row in block.data],
                         [int(v) for v in refs]))
    return m


def at_vertices(values, at, n):
    """The vector each of `n` vertices has, and whether every vertex has one."""
    if not values:
        return None, False
    if at is None:
        return (np.asarray(values, dtype=np.float64), True) if len(values) == n else (None, False)
    out = np.zeros((n, 3))
    given = [False] * n
    for vertex, value in at:
        out[vertex - 1] = values[value - 1]
        given[vertex - 1] = True
    return out, all(given)


def expectations(m):
    points = np.zeros((len(m.points), 3))
    points[:, :m.dim] = np.asarray(m.points, dtype=np.float64).reshape(len(m.points), m.dim)
    groups = {}
    for keyword, rows, refs in m.blocks:
        _, _, corners, shape, dim = KEYWORDS[keyword]
        for nodes, ref in zip(rows, refs):
            key = (dim, ref) if ref else None
            if key not in groups:
                groups[key] = Group("%s %d" % (KINDS[dim], ref) if key else None,
                                    {"reference": ref, "dimension": dim} if key else None)
            groups[key].elements.append((shape, [n - 1 for n in nodes[:corners]]))
    if not groups:
        groups[None] = Group()
        groups[None].elements = [("vertex", [i]) for i in range(len(m.points))]
    point_data = {}
    if any(m.refs):
        point_data["ref"] = np.asarray(m.refs, dtype=np.float64)
    pad = lambda vectors: [tuple(v) + (0.0,) * (3 - len(v)) for v in vectors]
    normals, every = at_vertices(pad(m.normals), m.normal_at, len(m.points))
    if normals is not None and not every:
        point_data["normal"] = normals
        normals = None
    tangents, _ = at_vertices(pad(m.tangents), m.tangent_at, len(m.points))
    if tangents is not None:
        point_data["tangent"] = tangents
    return measure(points, list(groups.values()), point_data, normals=normals)


def add(name, fname, data, spec, source, m, **more):
    expect, ref = expectations(m)
    expect["document"].update(more.pop("document", {}))
    expect.update(more)
    case(FMT, name, {fname: data, "reference.json": json.dumps(ref) + "\n"},
         {"spec": SPEC + ": " + spec, "source": source, **expect})


def fails(name, fname, data, spec, source, error, kind):
    case(FMT, name, {fname: data}, {"spec": SPEC + ": " + spec, "source": source, "error": error, "error_kind": kind})


def stored(data, fname):
    path = os.path.join(TMP, fname)
    with open(path, "wb") as f:
        f.write(data if isinstance(data, bytes) else data.encode())
    return path


def agrees(data, fname, m):
    """meshio reads the file written here as the mesh it was written from (what it reads of it:
    the vertices and the first-order elements)."""
    got = read_meshio(stored(data, fname))
    width = np.float32 if m.version == 1 and fname.endswith("b") else np.float64
    assert np.array_equal(np.asarray(got.points, dtype=width), np.asarray(m.points, dtype=width)), "other points"
    assert got.refs == m.refs
    known = [b for b in m.blocks if b[0] in FROM_MESHIO.values()]
    assert got.blocks == [(k, [list(r) for r in rows], list(refs)) for k, rows, refs in known], "other elements"
    return data


