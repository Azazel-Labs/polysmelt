def chunk(cid, *parts, length=None):
    body = b"".join(parts)
    return struct.pack("<HI", cid, len(body) + 6 if length is None else length) + body


def cstr(s):
    return s.encode("latin-1") + b"\0"


def u16s(xs):
    return b"".join(struct.pack("<H", x) for x in xs)


def f32s(xs):
    return b"".join(struct.pack("<f", x) for x in xs)


def color24(rgb, cid=COLOR_24):
    return chunk(cid, bytes(rgb))


def colorf(rgb, cid=COLOR_F):
    return chunk(cid, f32s(rgb))


def pct(v, cid=PERCENT_I):
    return chunk(cid, struct.pack("<H", v) if cid == PERCENT_I else struct.pack("<f", v))


def material(name, diffuse=None, *extra):
    parts = [chunk(MAT_NAME, cstr(name)),
             chunk(MAT_AMBIENT, color24((30, 30, 30))),
             chunk(MAT_SPECULAR, color24((230, 230, 230)))]
    if diffuse is not None:
        parts.append(chunk(MAT_DIFFUSE, diffuse))
    return chunk(MATERIAL, *parts, *extra)


def texmap(filename, *extra, cid=MAT_TEXMAP):
    return chunk(cid, pct(100), chunk(MAP_FILE, cstr(filename)), *extra)


def tiling(flags):
    return chunk(MAP_TILING, u16s([flags]))


def mapf(cid, v):
    return chunk(cid, f32s([v]))


def trimesh(verts, faces, uvs=None, mats=(), smoothing=None, matrix=None, flags=7):
    """`faces` are vertex index triples; `mats` is [(material name, [face indices])]."""
    body = chunk(VERTICES, struct.pack("<H", len(verts)), f32s([c for v in verts for c in v]))
    if uvs is not None:
        body += chunk(UVS, struct.pack("<H", len(uvs)), f32s([c for t in uvs for c in t]))
    if matrix is not None:
        body += chunk(MESH_MATRIX, f32s(matrix))
    fb = struct.pack("<H", len(faces)) + b"".join(u16s([*f, flags]) for f in faces)
    for name, fs in mats:
        fb += chunk(FACE_MATERIAL, cstr(name), struct.pack("<H", len(fs)), u16s(fs))
    if smoothing is not None:
        fb += chunk(SMOOTHING, b"".join(struct.pack("<I", s) for s in smoothing))
    body += chunk(FACES, fb)
    return chunk(TRIMESH, body)


def obj(name, *parts):
    return chunk(OBJECT, cstr(name), *parts)


def model(*editor, before=b"", after=b""):
    return chunk(MAIN, chunk(VERSION, struct.pack("<I", 3)), before,
                 chunk(EDITOR, chunk(MESH_VERSION, struct.pack("<I", 3)),
                       chunk(MASTER_SCALE, f32s([1.0])), *editor), after)


def track(cid, keys):
    """A keyframer track of `keys`, (frame, [values]), with no spline parameters."""
    body = struct.pack("<HIII", 0, 0, 0, len(keys))
    for frame, values in keys:
        body += struct.pack("<IH", frame, 0) + f32s(values)
    return chunk(cid, body)


def node(nid, name, parent=-1, pivot=(0, 0, 0), pos=None, rot=None, scl=None, instance=None):
    """An object node: `name` is the object it places (or $$$DUMMY), `parent` a node id."""
    parts = [chunk(NODE_ID, struct.pack("<H", nid)),
             chunk(NODE_HDR, cstr(name), struct.pack("<HHH", 0, 0, parent & 0xFFFF))]
    if instance is not None:
        parts.append(chunk(INSTANCE_NAME, cstr(instance)))
    parts.append(chunk(PIVOT, f32s(pivot)))
    for cid, keys in ((POS_TRACK, pos), (ROT_TRACK, rot), (SCL_TRACK, scl)):
        if keys is not None:
            parts.append(track(cid, keys))
    return chunk(OBJECT_NODE_TAG, *parts)


def keyframer(*nodes, frames=(0, 30)):
    return chunk(KEYFRAMER, chunk(KFHDR, struct.pack("<H", 5), cstr("MAXSCENE"), struct.pack("<I", frames[1])),
                 chunk(KFSEG, struct.pack("<II", *frames)), *nodes)


def y_up(p):
    return [p[0], p[2], -p[1]]


def bounds(points):
    pts = [y_up(p) for p in points]
    return {"min": [min(p[k] for p in pts) for k in range(3)],
            "max": [max(p[k] for p in pts) for k in range(3)]}


def lin(rgb, alpha=1.0):
    return [r(srgb_to_linear(c / 255), 4) for c in rgb] + [alpha]


def linf(rgb):
    return [r(srgb_to_linear(c), 4) for c in rgb]


