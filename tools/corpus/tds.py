# Groups are bit masks: faces smooth together when their masks share a bit, not only when they
# are equal. The four walls each carry two bits, one shared with each neighbor; the top and
# bottom have bits of their own.
walls = [4, 2, 5, 3]  # -x, -y, +x, +y: each next to the one after it
mask = [0] * 6
for j, side in enumerate(walls):
    mask[side] = (1 << j) | (1 << ((j + 1) % 4))
mask[0], mask[1] = 16, 32
h = 1 / math.sqrt(2)
