def read(path):
    """The dataset VTK reads from the file."""
    with open(path, "rb") as f:
        xml = f.read(64).lstrip().startswith(b"<")
    reader = vtk.vtkXMLGenericDataObjectReader() if xml else vtk.vtkGenericDataObjectReader()
    reader.SetFileName(path)
    reader.Update()
    out = reader.GetOutput()
    assert out is not None and out.GetNumberOfPoints() > 0, path
    return out


def fnv(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return "%016x" % h


def f32(values):
    return np.asarray(values, dtype="<f4").tobytes()


def rotate(t):
    """A triangle's corners turned so the least comes first, its winding kept."""
    k = t.index(min(t))
    return t[k:] + t[:k]


def convex(points):
    """Whether a polygon's corners all turn the same way about its normal."""
    p = np.asarray(points, dtype=np.float64)
    n = np.zeros(3)
    for i in range(len(p)):
        a, b = p[i], p[(i + 1) % len(p)]
        n += np.cross(a, b)
    turns = [np.dot(np.cross(p[(i + 1) % len(p)] - p[i], p[(i + 2) % len(p)] - p[(i + 1) % len(p)]), n)
             for i in range(len(p))]
    return all(t >= 0 for t in turns)


UNDRAWN = (vtk.VTK_POLYHEDRON, vtk.VTK_CONVEX_POINT_SET)


def drawn(ds, points):
    """What a dataset draws: triangles, line segments and points as point ids, each with its cell,
    and whether the triangles are the only way to cut its polygons."""
    tris, lines, verts, exact = [], [], [], True
    faces = {}
    skipped = 0

    def polygon(ids, cell):
        nonlocal exact
        if len(ids) > 3 and not convex([points[i] for i in ids]):
            exact = False
        for k in range(1, len(ids) - 1):
            tris.append(((ids[0], ids[k], ids[k + 1]), cell))

    def corners(cell):
        ids = [cell.GetPointId(i) for i in range(cell.GetNumberOfEdges())]
        if cell.GetCellType() == vtk.VTK_PIXEL:
            ids = [ids[0], ids[1], ids[3], ids[2]]
        return ids

    for c in range(ds.GetNumberOfCells()):
        cell = ds.GetCell(c)
        kind = cell.GetCellType()
        ids = [cell.GetPointId(i) for i in range(cell.GetNumberOfPoints())]
        if kind in UNDRAWN:
            skipped += 1
        elif cell.GetCellDimension() == 0:
            verts.extend((i, c) for i in ids)
        elif cell.GetCellDimension() == 1:
            if kind not in (vtk.VTK_LINE, vtk.VTK_POLY_LINE):
                ids = ids[:2]
            lines.extend(((a, b), c) for a, b in zip(ids, ids[1:]))
        elif kind == vtk.VTK_TRIANGLE_STRIP:
            for k in range(len(ids) - 2):
                a, b, d = ids[k:k + 3]
                tris.append(((a, b, d) if k % 2 == 0 else (b, a, d), c))
        elif cell.GetCellDimension() == 2:
            polygon(corners(cell), c)
        else:
            for j in range(cell.GetNumberOfFaces()):
                face = corners(cell.GetFace(j))
                # A corner repeated, where a cell is collapsed, is taken once.
                face = [p for k, p in enumerate(face) if p not in face[:k]]
                if len(face) >= 3:
                    faces.setdefault(frozenset(face), []).append((face, c))
    boundary = [found[0] for found in faces.values() if len(found) == 1]
    for face, c in boundary:
        for k in range(1, len(face) - 1):
            tris.append(((face[0], face[k], face[k + 1]), c))
    return {"tris": tris, "lines": lines, "verts": verts, "exact": exact, "skipped": skipped,
            "boundary": len(boundary)}


def check_surface(ds, d):
    """vtkDataSetSurfaceFilter draws as many triangles (it cuts curved cells finer, so it's asked
    only of linear ones)."""
    if any(not ds.GetCell(c).IsLinear() or ds.GetCellType(c) in UNDRAWN for c in range(ds.GetNumberOfCells())):
        return None
    surface = vtk.vtkDataSetSurfaceFilter()
    surface.SetInputData(ds)
    tri = vtk.vtkTriangleFilter()
    tri.SetInputConnection(surface.GetOutputPort())
    tri.PassLinesOff()
    tri.PassVertsOff()
    tri.Update()
    n = tri.GetOutput().GetNumberOfPolys()
    assert n == len(d["tris"]), (n, len(d["tris"]))
    return n


def attribute_name(name):
    return "_" + "".join(c.upper() if c.isascii() and c.isalnum() else "_" for c in name.strip())


def linear_colors(values, scale):
    out = np.ones((len(values), 4), dtype=np.float64)
    v = np.clip(np.asarray(values, dtype=np.float64) * scale, 0.0, 1.0)
    out[:, :3] = np.vectorize(srgb_to_linear)(v[:, :3])
    if v.shape[1] == 4:
        out[:, 3] = v[:, 3]
    return out


def attributes(data):
    """A point or cell data's arrays as the glTF attributes they become: (values, exact) by name."""
    out = {}
    taken = set()
    arrays = [data.GetArray(i) for i in range(data.GetNumberOfArrays())]
    arrays = [a for a in arrays if a is not None]
    for a in arrays:
        v = vtk_to_numpy(a).astype(np.float64).reshape(a.GetNumberOfTuples(), -1)
        name, comps = a.GetName(), v.shape[1]
        normals, tcoords = data.GetNormals(), data.GetTCoords()
        if normals is not None and a.GetName() == normals.GetName() and comps == 3 and "NORMAL" not in taken:
            length = np.linalg.norm(v, axis=1, keepdims=True)
            out["NORMAL"] = (np.where(length > 1e-12, v / np.maximum(length, 1e-30), [0.0, 1.0, 0.0]), False)
            taken.add("NORMAL")
        elif tcoords is not None and a.GetName() == tcoords.GetName() and comps == 2 and "TEXCOORD_0" not in taken:
            out["TEXCOORD_0"] = (np.stack([v[:, 0], 1.0 - v[:, 1]], axis=1), False)
            taken.add("TEXCOORD_0")
        elif a.GetDataType() == vtk.VTK_UNSIGNED_CHAR and comps in (3, 4) and "COLOR_0" not in taken:
            out["COLOR_0"] = (linear_colors(v, 1 / 255), False)
            taken.add("COLOR_0")
        else:
            key = attribute_name(name)
            v = np.where(np.isfinite(v), v, 0.0)
            if comps <= 4:
                out[key] = (v, True)
            elif comps <= 9:
                for k in range(comps):
                    out["%s_%d" % (key, k)] = (v[:, k:k + 1], True)
    return out


def table_colors(data):
    """The colors VTK's lookup table gives the first scalars that have one of their own, across
    their range: `None` without one."""
    for a in (data.GetArray(i) for i in range(data.GetNumberOfArrays())):
        table = a.GetLookupTable() if a is not None and a.GetNumberOfComponents() == 1 else None
        if table is not None and table.GetNumberOfTableValues() > 0:
            table.SetTableRange(a.GetRange())
            mapped = []
            for k in range(a.GetNumberOfTuples()):
                rgb = [0.0, 0.0, 0.0]
                table.GetColor(a.GetTuple1(k), rgb)
                mapped.append([*rgb, table.GetOpacity(a.GetTuple1(k))])
            return linear_colors(np.asarray(mapped, dtype=np.float64), 1.0)
    return None


def measure(path, points_only=False, area=None):
    """The expectations and the reference hashes for the file at `path`. `points_only` is for a
    file with no cells, whose points are drawn; `area` is the area a concave polygon has, however
    it's cut."""
    ds = read(path)
    n = ds.GetNumberOfPoints()
    points = np.array([ds.GetPoint(i) for i in range(n)], dtype=np.float32)
    d = drawn(ds, points)
    surface = check_surface(ds, d)
    if points_only:
        d["verts"] = [(i, 0) for i in range(n)]
    cell_attrs = attributes(ds.GetCellData()) if ds.GetNumberOfCells() else {}
    point_attrs = attributes(ds.GetPointData())
    if "COLOR_0" not in point_attrs and "COLOR_0" not in cell_attrs:
        for data, attrs in [(ds.GetPointData(), point_attrs), (ds.GetCellData(), cell_attrs)]:
            colors = table_colors(data)
            if colors is not None:
                attrs["COLOR_0"] = (colors, False)
                break
    used = sorted({i for t, _ in d["tris"] for i in t} | {i for l, _ in d["lines"] for i in l}
                  | {i for i, _ in d["verts"]})
    drawn_points = points[used]
    expect = {"triangles": len(d["tris"])}
    if d["lines"]:
        expect["lines"] = len(d["lines"])
    if d["verts"]:
        expect["points"] = len(d["verts"])
    ref = {"points": None, "triangles": None, "lines": None, "verts": None, "attributes": None,
           "soup": None, "soup_attributes": sorted(k for k in cell_attrs if k.startswith("_")),
           "boundary_faces": d["boundary"], "surface_filter_triangles": surface}
    if not used:
        return expect, ref
    expect["bounds"] = {"min": [float(v) for v in drawn_points.min(axis=0)],
                        "max": [float(v) for v in drawn_points.max(axis=0)]}
    total = 0.0
    for t, _ in d["tris"]:
        a, b, c = (points[i].astype(np.float64) for i in t)
        total += 0.5 * float(np.linalg.norm(np.cross(b - a, c - a)))
    if d["tris"] and (d["exact"] or area is not None):
        expect["area"] = r(total) if d["exact"] else area
    expect["facts"] = {"triangles": len(d["tris"])}
    names = sorted(set(point_attrs) | set(cell_attrs))
    if names:
        expect["document"] = {"attributes": names}
    expect["colors"] = "COLOR_0" in names
    expect["uvs"] = "TEXCOORD_0" in names
    if not cell_attrs:
        # No cell data: the vertices are the points used, in order.
        expect["vertices"] = len(used)
        at = {p: k for k, p in enumerate(used)}
        ref["points"] = fnv(f32(drawn_points))
        if d["exact"]:
            tris = sorted(rotate(tuple(at[i] for i in t)) for t, _ in d["tris"])
            ref["triangles"] = fnv(np.asarray(tris, dtype="<u4").tobytes())
        ref["lines"] = fnv(np.asarray(sorted(tuple(at[i] for i in l) for l, _ in d["lines"]), dtype="<u4").tobytes())
        ref["verts"] = fnv(np.asarray(sorted(at[i] for i, _ in d["verts"]), dtype="<u4").tobytes())
        ref["attributes"] = {}
        for key, (values, exact) in point_attrs.items():
            values = values[used]
            if exact:
                ref["attributes"][key] = {"width": values.shape[1], "hash": fnv(f32(values))}
            elif values.size <= 256:
                # Worked out in floating point both here and in the reader: listed, to compare closely.
                ref["attributes"][key] = {"width": values.shape[1], "values": [r(float(v), 7) for v in values.flat]}
            else:
                # Too many to list: each component's sum and sum of squares.
                ref["attributes"][key] = {"width": values.shape[1],
                                          "sums": [float(v) for v in values.sum(axis=0)],
                                          "squares": [float(v) for v in (values * values).sum(axis=0)]}
    if d["exact"] and d["tris"]:
        # The triangles as corner positions, each with its cell's values: what a vertex split by cell holds.
        records = []
        for t, c in d["tris"]:
            corners = [tuple(float(v) for v in points[i]) for i in t]
            k = corners.index(min(corners))
            corners = corners[k:] + corners[:k]
            record = f32(corners)
            for key in ref["soup_attributes"]:
                record += f32(cell_attrs[key][0][c])
            records.append(record)
        ref["soup"] = fnv(b"".join(sorted(records)))
    return expect, ref


def add(name, files, spec, source, expect=None, ref=None, model=None, **more):
    """Writes a case from `files` (name to bytes), measuring `model` (its first file by default)."""
    d = os.path.join(TMP, name)
    os.makedirs(d, exist_ok=True)
    for fname, data in files.items():
        with open(os.path.join(d, fname), "wb") as f:
            f.write(data if isinstance(data, bytes) else data.encode())
    if expect is None:
        expect, ref = measure(os.path.join(d, model or next(iter(files))), **more)
    out = {"spec": SPEC + ": " + spec, "source": source, **expect}
    files = dict(files)
    if ref is not None:
        files["reference.json"] = json.dumps(ref, indent=2) + "\n"
    case(FMT, name, files, out)


# --- writing with VTK ---------------------------------------------------------------------------

def array(name, values, kind=vtk.vtkFloatArray):
    a = kind()
    a.SetName(name)
    values = np.asarray(values)
    a.SetNumberOfComponents(1 if values.ndim == 1 else values.shape[1])
    for v in values:
        if values.ndim == 1:
            a.InsertNextValue(v.item())
        else:
            a.InsertNextTuple([x.item() for x in v])
    return a


def grid(points, cells, double=False):
    g = vtk.vtkUnstructuredGrid()
    pts = vtk.vtkPoints()
    pts.SetDataType(vtk.VTK_DOUBLE if double else vtk.VTK_FLOAT)
    for p in points:
        pts.InsertNextPoint(*p)
    g.SetPoints(pts)
    for kind, ids in cells:
        g.InsertNextCell(kind, len(ids), list(ids))
    return g


def legacy(ds, version=42, binary=False):
    w = vtk.vtkGenericDataObjectWriter()
    w.SetFileVersion(version)
    w.SetInputData(ds)
    if binary:
        w.SetFileTypeToBinary()
    path = os.path.join(TMP, "out.vtk")
    w.SetFileName(path)
    assert w.Write() == 1
    with open(path, "rb") as f:
        data = f.read()
    # VTK on Windows ends a text file's lines with CRLF; the cases are the same wherever they're made.
    return data if binary else data.replace(b"\r\n", b"\n")


def xml(ds, mode="ascii", compressor=None, header=64, big=False, encode=True):
    w = vtk.vtkXMLPolyDataWriter() if ds.IsA("vtkPolyData") else vtk.vtkXMLUnstructuredGridWriter()
    w.SetInputData(ds)
    {"ascii": w.SetDataModeToAscii, "binary": w.SetDataModeToBinary, "appended": w.SetDataModeToAppended}[mode]()
    {None: w.SetCompressorTypeToNone, "zlib": w.SetCompressorTypeToZLib, "lz4": w.SetCompressorTypeToLZ4,
     "lzma": w.SetCompressorTypeToLZMA}[compressor]()
    (w.SetHeaderTypeToUInt64 if header == 64 else w.SetHeaderTypeToUInt32)()
    (w.SetByteOrderToBigEndian if big else w.SetByteOrderToLittleEndian)()
    w.SetEncodeAppendedData(1 if encode else 0)
    path = os.path.join(TMP, "out.xml")
    w.SetFileName(path)
    assert w.Write() == 1
    with open(path, "rb") as f:
        return f.read()


