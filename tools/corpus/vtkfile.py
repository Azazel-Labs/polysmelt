"""VTK conformance cases: legacy .vtk files and XML .vtp and .vtu files, as the "VTK File Formats"
document (docs.vtk.org) defines them.

The files are written by VTK's own writers and by meshio, in every encoding each has: legacy
ASCII and binary in the 4.2 and 5.1 layouts, and XML as text, inline base64, appended raw and
base64, with zlib, both header types and both byte orders. A few are written by hand here, for
what the writers don't write (a lookup table, COLOR_SCALARS, two pieces, a version 2.0 header).

The expectations come from VTK, never from Polysmelt: each file is read back with VTK's readers,
and what's drawn is worked out here from VTK's cells. A cell's faces are the ones vtkCell.GetFace
gives, and the boundary is the faces only one cell has; `check_surface` holds that count against
vtkDataSetSurfaceFilter's. Beside each expect.json, reference.json holds hashes (64-bit FNV-1a)
of the exact points, triangles, lines and attributes (normals, texture coordinates and colors,
which take arithmetic, as values or sums instead), which tests/vtk.rs compares with what
Polysmelt reads.

Real files from VTK's test data (BSD, LICENSE-VTK) and meshio's (MIT, LICENSE-meshio) are kept in
their case folders; their expectations are computed the same way.

Run from the repository root with a Python that has vtk and meshio installed (this file can't be
called vtk.py, which would hide the module):

    python tools/corpus/vtkfile.py [folder holding the real files]
"""

