def quadratic(kind, linear, corners):
    """A quadratic cell of the VTK class `kind` on `corners`: its other nodes are where the class's
    parametric coordinates put them, between the corners."""
    cell = kind()
    shape = linear()
    for k, p in enumerate(corners):
        shape.GetPoints().SetPoint(k, *p)
    coords = cell.GetParametricCoords()
    out = []
    weights = [0.0] * shape.GetNumberOfPoints()
    for k in range(cell.GetNumberOfPoints()):
        x = [0.0, 0.0, 0.0]
        sub = vtk.reference(0)
        shape.EvaluateLocation(sub, [coords[3 * k], coords[3 * k + 1], coords[3 * k + 2]], x, weights)
        out.append(tuple(x))
    return cell.GetCellType(), out


