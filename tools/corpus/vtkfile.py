def text_piece(points, cells):
    """One <Piece> of an ascii UnstructuredGrid."""
    ends, total = [], 0
    for _, ids in cells:
        total += len(ids)
        ends.append(total)
    return """    <Piece NumberOfPoints="%d" NumberOfCells="%d">
      <PointData Scalars="height">
        <DataArray type="Float32" Name="height" format="ascii">%s</DataArray>
      </PointData>
      <Points>
        <DataArray type="Float32" NumberOfComponents="3" format="ascii">
          %s
        </DataArray>
      </Points>
      <Cells>
        <DataArray type="Int64" Name="connectivity" format="ascii">%s</DataArray>
        <DataArray type="Int64" Name="offsets" format="ascii">%s</DataArray>
        <DataArray type="UInt8" Name="types" format="ascii">%s</DataArray>
      </Cells>
    </Piece>
""" % (len(points), len(cells), " ".join("%g" % p[2] for p in points),
       "\n          ".join("%g %g %g" % tuple(p) for p in points),
       " ".join(str(i) for _, ids in cells for i in ids), " ".join(str(e) for e in ends),
       " ".join(str(kind) for kind, _ in cells))


