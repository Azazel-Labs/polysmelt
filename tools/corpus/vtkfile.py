def poly(points, verts=(), lines=(), polys=(), strips=()):
    p = vtk.vtkPolyData()
    pts = vtk.vtkPoints()
    for q in points:
        pts.InsertNextPoint(*q)
    p.SetPoints(pts)
    for cells, setter in [(verts, p.SetVerts), (lines, p.SetLines), (polys, p.SetPolys), (strips, p.SetStrips)]:
        ca = vtk.vtkCellArray()
        for ids in cells:
            ca.InsertNextCell(len(ids), list(ids))
        setter(ca)
    return p


def cube():
    extra = [(2, 0, 0), (3, 0, 0), (2, 1, 0), (3, 1, 0), (2, 2, 0), (3, 2, 0), (4, 0, 0), (4, 1, 0), (5, 0, 0)]
    p = poly(CUBE + extra, verts=[(16,), (14, 15)], lines=[(8, 14), (14, 15, 16)], polys=CUBE_FACES,
             strips=[(8, 9, 10, 11, 12, 13)])
    n = p.GetNumberOfPoints()
    pts = np.asarray(CUBE + extra, dtype=np.float64)
    normals = pts - np.asarray([0.5, 0.5, 0.5])
    p.GetPointData().SetNormals(array("Normals", normals.astype(np.float32)))
    p.GetPointData().SetTCoords(array("TCoords", np.asarray([(0.125 * k, 1.0 - 0.0625 * k) for k in range(n)],
                                                           dtype=np.float32)))
    colors = np.asarray([(255 - 15 * k, 15 * k, (40 * k) % 256) for k in range(n)], dtype=np.uint8)
    p.GetPointData().SetScalars(array("Colors", colors, vtk.vtkUnsignedCharArray))
    p.GetPointData().AddArray(array("height", pts[:, 2].astype(np.float32)))
    return p


