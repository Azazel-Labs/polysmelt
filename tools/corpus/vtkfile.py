def image(dims, cell_data=False):
    g = vtk.vtkImageData()
    g.SetDimensions(*dims)
    g.SetOrigin(1.0, -2.0, 0.5)
    g.SetSpacing(0.5, 1.0, 0.25)
    n = dims[0] * dims[1] * dims[2]
    g.GetPointData().SetScalars(array("density", np.asarray([0.5 * k for k in range(n)], dtype=np.float32)))
    if cell_data:
        g.GetCellData().SetScalars(array("zone", np.asarray([k % 3 for k in range(g.GetNumberOfCells())],
                                                           dtype=np.int32), vtk.vtkIntArray))
    return g


def rectilinear(dims):
    g = vtk.vtkRectilinearGrid()
    g.SetDimensions(*dims)
    for n, setter in zip(dims, (g.SetXCoordinates, g.SetYCoordinates, g.SetZCoordinates)):
        setter(array("", np.asarray([0.25 * k * k + k for k in range(n)], dtype=np.float32)))
    n = dims[0] * dims[1] * dims[2]
    g.GetPointData().SetScalars(array("density", np.asarray([0.5 * k for k in range(n)], dtype=np.float32)))
    return g


def structured(dims):
    g = vtk.vtkStructuredGrid()
    g.SetDimensions(*dims)
    pts = vtk.vtkPoints()
    for k in range(dims[2]):
        for j in range(dims[1]):
            for i in range(dims[0]):
                pts.InsertNextPoint(i + 0.125 * j, j + 0.25 * k, k + 0.0625 * i * i)
    g.SetPoints(pts)
    n = dims[0] * dims[1] * dims[2]
    g.GetPointData().SetScalars(array("density", np.asarray([0.5 * k for k in range(n)], dtype=np.float32)))
    return g


