"""DirectX .x conformance cases: the file format Microsoft's DirectX 9 SDK documents ("X File Format
Reference": the header, text and binary encodings, MSZIP compression, and the standard templates).

The scene is written here in glTF's terms and converted to the file's: .x is left-handed, so each case's
positions, normals and translations have Z negated, faces are written clockwise seen from the front (as Direct3D
draws them), and matrices are Direct3D's row-vector ones, written row after row. Rotation keys are stored w
first, as the conjugate of the quaternion of the frame matrix they stand for (as exporters write them: a frame's
bind pose key against its FrameTransformMatrix). The expectations are the glTF values the generator started
from.

Real files: three cubes from the Open Asset Import Library's test models (test/models/X, BSD-3-Clause, its
notice in LICENSE-assimp) in text, binary and compressed binary, two malformed files from the same set, and a
cube exported by kW Xport (MIT, its license in kwxport_cube/LICENSE.txt). Their expectations come from what the files hold, read by hand and
checked against the reference importer's output.

Run from the repository root:

    python tools/corpus/x.py <folder holding the sample .x files>

Without the folder, the sample files already in tests/corpus/x are reused.
"""

