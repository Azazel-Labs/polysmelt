# --- Objects ---------------------------------------------------------------------------------------------------------

class Obj:
    """A data object: its template, name, values and children. Values are groups: ("i", [ints]), ("f", [floats]),
    ("vi", [rows of ints]), ("vf", [rows of floats]), ("s", text), and ("ref", name) for a reference."""

    def __init__(self, kind, name="", values=(), kids=()):
        self.kind, self.name, self.values, self.kids = kind, name, list(values), list(kids)


def ref(name):
    return Obj("", name)


def num(x):
    return f"{x:.6f}" if isinstance(x, float) else str(x)


def text_obj(o, depth=0):
    pad = " " * depth
    if not o.kind:
        return f"{pad}{{ {o.name} }}\n"
    out = f"{pad}{o.kind}{' ' + o.name if o.name else ''} {{\n"
    for kind, v in o.values:
        if kind in ("i", "f"):
            out += f"{pad} " + ";".join(num(x) for x in v) + ";\n"
        elif kind in ("vi", "vf"):
            # A row's members end with `;`, rows are separated by `,` and the array ends with `;`.
            rows = [";".join(num(x) for x in row) for row in v]
            out += "".join(f"{pad} {row};{',' if i + 1 < len(rows) else ';'}\n" for i, row in enumerate(rows))
        elif kind == "s":
            out += f'{pad} "{v}";\n'
    for k in o.kids:
        out += text_obj(k, depth + 1)
    return out + f"{pad}}}\n"


TEXT_TEMPLATES = """template Header {
 <3D82AB43-62DA-11cf-AB39-0020AF71E433>
 WORD major;
 WORD minor;
 DWORD flags;
}

template Vector {
 <3D82AB5E-62DA-11cf-AB39-0020AF71E433>
 FLOAT x;
 FLOAT y;
 FLOAT z;
}

"""


def text_file(objects, templates=True, float_size="0032"):
    body = (TEXT_TEMPLATES if templates else "") + "".join(text_obj(o) + "\n" for o in objects)
    return f"xof 0303txt {float_size}\n" + body


# Binary tokens.
T_NAME, T_STRING, T_INTEGER, T_GUID, T_INT_LIST, T_FLOAT_LIST = 1, 2, 3, 5, 6, 7
T_OBRACE, T_CBRACE, T_SEMICOLON, T_TEMPLATE, T_WORD, T_DWORD, T_FLOAT = 10, 11, 20, 31, 40, 41, 42


def tok(t):
    return struct.pack("<H", t)


def name_tok(s):
    b = s.encode()
    return tok(T_NAME) + struct.pack("<I", len(b)) + b


def bin_obj(o, double):
    if not o.kind:
        return tok(T_OBRACE) + name_tok(o.name) + tok(T_CBRACE)
    out = name_tok(o.kind) + (name_tok(o.name) if o.name else b"") + tok(T_OBRACE)
    fmt = "<d" if double else "<f"
    for kind, v in o.values:
        if kind == "s":
            b = v.encode()
            out += tok(T_STRING) + struct.pack("<I", len(b)) + b + tok(T_SEMICOLON)
            continue
        flat = [x for row in v for x in row] if kind.startswith("v") else list(v)
        if kind in ("i", "vi"):
            out += tok(T_INT_LIST) + struct.pack("<I", len(flat)) + b"".join(struct.pack("<I", x) for x in flat)
        else:
            out += tok(T_FLOAT_LIST) + struct.pack("<I", len(flat)) + b"".join(struct.pack(fmt, x) for x in flat)
    for k in o.kids:
        out += bin_obj(k, double)
    return out + tok(T_CBRACE)


def bin_template():
    """`template Vector { <GUID> FLOAT x; FLOAT y; FLOAT z; }` as tokens."""
    out = tok(T_TEMPLATE) + name_tok("Vector") + tok(T_OBRACE) + tok(T_GUID) + bytes(range(16))
    for axis in "xyz":
        out += tok(T_FLOAT) + name_tok(axis) + tok(T_SEMICOLON)
    return out + tok(T_CBRACE)


def bin_body(objects, double=False):
    return bin_template() + b"".join(bin_obj(o, double) for o in objects)


def bin_file(objects, double=False):
    return f"xof 0303bin {'0064' if double else '0032'}".encode() + bin_body(objects, double)


def mszip(header, body, block=32768, level=9, strategy=zlib.Z_DEFAULT_STRATEGY):
    """MSZIP: the total size (header counted), then blocks of the uncompressed size, the compressed size (`CK`
    counted), `CK` and a raw deflate stream that may refer back into the block before it."""
    out = header + struct.pack("<I", 16 + len(body))
    prev = b""
    for at in range(0, len(body), block):
        chunk = body[at:at + block]
        c = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy, zdict=prev) if prev else \
            zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
        packed = c.compress(chunk) + c.flush()
        out += struct.pack("<HH", len(chunk), len(packed) + 2) + b"CK" + packed
        prev = chunk
    return out


# --- The scene in the file's terms -------------------------------------------------------------------------------------

def lh(p):
    """A glTF position or direction in the file's left-handed space."""
    return [p[0], p[1], -p[2]]


def matrix(t=(0, 0, 0), q=(0, 0, 0, 1), s=(1, 1, 1)):
    """The file's frame matrix (row-vector, left-handed, written row after row) for a glTF node's translation,
    rotation (x, y, z, w) and scale."""
    x, y, z, w = q
    # The glTF rotation as a column-vector matrix.
    rot = [[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
           [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
           [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]]
    m = [[rot[i][j] * s[j] for j in range(3)] for i in range(3)]
    # Mirrored through the XY plane: S M S, S = diag(1, 1, -1).
    sign = [1, 1, -1]
    m = [[m[i][j] * sign[i] * sign[j] for j in range(3)] for i in range(3)]
    tl = lh(t)
    # Row-vector form is the transpose, translation in the last row.
    rows = [[m[j][i] for j in range(3)] + [0.0] for i in range(3)] + [[float(tl[0]), float(tl[1]), float(tl[2]), 1.0]]
    return [float(r(v, 9)) for row in rows for v in row]


def rotation_key(q):
    """A rotation key's four values for a glTF rotation (x, y, z, w): the quaternion of the left-handed frame
    matrix, conjugated, w first."""
    x, y, z, w = q
    # Mirrored: (-x, -y, z, w) is the left-handed quaternion; conjugated: (x, y, -z, w).
    return [w, x, y, -z]


def axis_angle(axis, degrees):
    h = math.radians(degrees) / 2
    return [axis[0] * math.sin(h), axis[1] * math.sin(h), axis[2] * math.sin(h), math.cos(h)]


def frame(name, kids=(), t=(0, 0, 0), q=(0, 0, 0, 1), s=(1, 1, 1)):
    return Obj("Frame", name, [], [Obj("FrameTransformMatrix", "", [("f", matrix(t, q, s))]), *kids])


def mesh(name, verts, faces, kids=(), offset=(0, 0, 0)):
    """A mesh of glTF positions and counter-clockwise faces, written left-handed and clockwise."""
    vs = [lh([p[k] + offset[k] for k in range(3)]) for p in verts]
    fs = [[len(f), *reversed(f)] for f in faces]
    return Obj("Mesh", name, [("i", [len(vs)]), ("vf", [[float(c) for c in v] for v in vs]), ("i", [len(fs)]),
                              ("vi", fs)], kids)


def normals(dirs, faces):
    """MeshNormals: glTF directions and each face's normal indices, in the faces' corner order."""
    return Obj("MeshNormals", "", [("i", [len(dirs)]), ("vf", [[float(c) for c in lh(d)] for d in dirs]),
                                   ("i", [len(faces)]), ("vi", [[len(f), *reversed(f)] for f in faces])])


def material(name, color, power=0.0, specular=(0.0, 0.0, 0.0), emissive=(0.0, 0.0, 0.0), kids=()):
    return Obj("Material", name, [("f", [float(c) for c in color]), ("f", [float(power)]),
                                  ("f", [float(c) for c in specular]), ("f", [float(c) for c in emissive])], kids)


def material_list(count, indices, kids):
    return Obj("MeshMaterialList", "", [("i", [count, len(indices)]), ("i", list(indices))], kids)


def lin(c):
    return [r(srgb_to_linear(x)) for x in c]


