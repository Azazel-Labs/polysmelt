"""MD3 conformance cases: Quake III Arena models as the format's published structures (qfiles.h, version 15) lay
them out, little-endian and packed.

A file is a 108-byte header ("IDP3", version, a 64-byte name, flags, the counts of frames, tags, surfaces and
skins, and the offsets of frames, tags, surfaces and the end), frames (bounds, origin, radius, a 16-byte name),
tags frame by frame (a 64-byte name, an origin, and three axes that are a rotation's columns), and surfaces one
after another. A surface has its own 108-byte header ("IDP3", name, flags, the counts of frames, shaders, vertices
and triangles, the offsets of triangles, shaders, texture coordinates, vertices and the surface's end, all from
the surface's start), shaders (a 64-byte name and an index), triangles (three 32-bit indices), texture
coordinates (two floats per vertex) and vertices frame by frame (x, y, z as 16-bit 64ths, and a normal packed as
latitude in the high byte and longitude in the low byte, each in 256ths of a turn).

The document has a node and mesh per surface, its first frame the geometry and every later frame that moves it a
morph target, with one linear animation, thirty frames a second (the format has no rate: the readers' shared
assumption), of the surfaces' weights and the tags' places. Tags
are nodes. A surface's shader names its texture; one with no shader takes it from `<model>_default.skin`
("surface,texture" lines) beside the model; a texture with no extension is a `.tga`. Triangles wind clockwise seen
from the front, so the reader turns them around; texture coordinates run down the image, as glTF's do. Quake is Z
up: the surfaces and tags stay as the file has them, under the `RootNode` every reader makes, which is the quarter
turn about x that lands a point (x, y, z) at (x, z, -y).
"""

