"""AC3D conformance cases: the AC3D file format (`.ac`) as AC3D's own file format page describes it.

A header line (AC3Db), MATERIAL lines (rgb, amb, emis, spec colors, shi, trans), then a tree of
OBJECT blocks: name, loc and the 3x3 rot placing it in its parent, texture, texrep and texoff,
crease, numvert and its vertices, numsurf and its SURF blocks (flags: the low four bits the
kind, 0 a polygon, 1 a closed line, 2 an open line, 4 a triangle strip; 0x10 shaded, 0x20 two
sided), each with its mat and refs (a vertex and its texture coordinates), and kids, the count
of children that follow. rot's three triples are the images of the x, y and z axes, so a
point's place in its parent is x * rot[0] + y * rot[1] + z * rot[2] + loc. AC3D is OpenGL's
space, Y up, right-handed, polygons counterclockwise from the front, as glTF is; colors are
sRGB; texture coordinates run up from the image's bottom, so glTF's v is 1 - v, after texrep
scales and texoff moves them.

Also real files from assimp's test models (test/models/AC; BSD license, see LICENSE-assimp
beside the cases), kept in their case folders (or read from the folder given as the first
argument). Their expectations come from reading them here, by the rules above.
"""

