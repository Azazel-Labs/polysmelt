def material(name="", rgb=(1, 1, 1), emis=(0, 0, 0), shi=10, trans=0.0, spec=(0.5, 0.5, 0.5)):
    return (f'MATERIAL "{name}" rgb {rgb[0]:g} {rgb[1]:g} {rgb[2]:g}  amb 0.2 0.2 0.2  '
            f"emis {emis[0]:g} {emis[1]:g} {emis[2]:g}  spec {spec[0]:g} {spec[1]:g} {spec[2]:g}  "
            f"shi {shi} trans {trans:g}\n")


def obj(name, verts, surfs, kids=0, kind="poly", extra=""):
    """`surfs` are (flags, mat, [(vertex, u, v)...])."""
    out = f'OBJECT {kind}\nname "{name}"\n{extra}'
    if verts:
        out += f"numvert {len(verts)}\n" + "".join(" ".join(f"{c:g}" for c in v) + "\n" for v in verts)
    if surfs:
        out += f"numsurf {len(surfs)}\n"
        for flags, mat, refs in surfs:
            out += f"SURF 0x{flags:x}\nmat {mat}\nrefs {len(refs)}\n"
            out += "".join(f"{i} {u:g} {v:g}\n" for i, u, v in refs)
    return out + f"kids {kids}\n"


def world(*children, mats=None):
    return "AC3Db\n" + "".join(mats or [material()]) + f"OBJECT world\nkids {len(children)}\n" + "".join(children)


def lin(c, a=1.0):
    return [r(srgb_to_linear(x)) for x in c] + [a]


