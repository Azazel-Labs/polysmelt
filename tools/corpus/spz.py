"""SPZ conformance cases: gaussian splats as a gzip stream of a 16-byte header (magic "NGSP",
version, splat count, spherical-harmonic degree, fractional bits, flags) and the splats a
property at a time: positions (half floats in version 1, 24-bit fixed point after), opacity,
base color, scale, rotation (three bytes in versions 1 and 2, the smallest three of four in a
32-bit word after) and spherical harmonics. Extension records follow when flag 2 is set; the
coordinate system record (0xADBE0003) names the axes the data is stored in. Without it the axes
are right, up and back, glTF's own.

Values are written already quantized, so the expectations are the format's own decoding:
color (c / 255 - 0.5) / 0.15 and drawn as 0.5 + SH_C0 times that, opacity a / 255, scale
exp(s / 16 - 10).
"""

import gzip
import math
import os
import struct
import sys

# The shared modules are beside this script, which `python -I` leaves off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import case, fresh, r, srgb_to_linear  # noqa: E402

FMT = "spz"
SRC = "generated by tools/corpus/spz.py"
SPEC = "SPZ (gzip streams, versions 1 to 3)"
SH_C0 = 0.28209479177387814
EXT = "KHR_gaussian_splatting"
DIM = [0, 3, 8, 15, 24]
FRACTIONAL = 12

fresh(FMT)


def half(x):
    return struct.pack("<e", x)


def fixed(x):
    v = round(x * (1 << FRACTIONAL))
    return struct.pack("<i", v)[:3]


def smallest_three(q):
    """A rotation (x, y, z, w) packed as its three smallest components."""
    largest = max(range(4), key=lambda i: abs(q[i]))
    if q[largest] < 0:
        q = [-c for c in q]
    packed = largest
    for i in range(4):
        if i == largest:
            continue
        mag = round(abs(q[i]) / math.sqrt(0.5) * 511)
        packed = (packed << 10) | (mag | (512 if q[i] < 0 else 0))
    return struct.pack("<I", packed)


def spz(version, splats, degree=0, flags=0, records=b"", count=None, cut=None, raw=False):
    """`splats`: dicts with pos, alpha, rgb, scale (bytes), rot (three bytes for versions 1 and
    2, a quaternion after) and sh (degree's coefficients times three bytes)."""
    n = len(splats) if count is None else count
    out = struct.pack("<IIIBBBB", 0x5053474E, version, n, degree, FRACTIONAL, flags, 0)
    for s in splats:
        out += b"".join((half if version == 1 else fixed)(c) for c in s["pos"])
    out += bytes(s["alpha"] for s in splats)
    out += b"".join(bytes(s["rgb"]) for s in splats)
    out += b"".join(bytes(s["scale"]) for s in splats)
    out += b"".join(bytes(s["rot"]) if version < 3 else smallest_three(s["rot"]) for s in splats)
    out += b"".join(bytes(s.get("sh", [128] * DIM[degree] * 3)) for s in splats)
    out += records
    if cut is not None:
        out = out[:cut]
    return out if raw else gzip.compress(out, mtime=0)


def color(s):
    """The flat color a splat is drawn in."""
    rgb = [min(max(0.5 + SH_C0 * (c / 255 - 0.5) / 0.15, 0.0), 1.0) for c in s["rgb"]]
    return [r(srgb_to_linear(c), 4) for c in rgb] + [r(s["alpha"] / 255, 4)]


def bounds(points):
    return {"min": [min(p[k] for p in points) for k in range(3)],
            "max": [max(p[k] for p in points) for k in range(3)]}


def splats(version, degree=0):
    out = []
    for i, (pos, rgb) in enumerate([
        ([0.0, 0.0, 0.0], [255, 128, 0]),
        ([1.5, -0.25, 2.0], [128, 128, 128]),
        ([-3.0, 4.0, 0.5], [40, 90, 200]),
        ([0.125, 0.5, -1.0], [0, 255, 77]),
    ]):
        s = {"pos": pos, "alpha": 255 - 60 * i, "rgb": rgb, "scale": [100 + i, 110, 120]}
        s["rot"] = [128, 128, 128] if version < 3 else [0.0, 0.0, 0.0, 1.0]
        s["sh"] = [(128 + 7 * k + i) % 256 for k in range(DIM[degree] * 3)]
        out.append(s)
    return out


def attributes(degree):
    names = ["POSITION", "COLOR_0", f"{EXT}:ROTATION", f"{EXT}:SCALE", f"{EXT}:OPACITY",
             f"{EXT}:SH_DEGREE_0_COEF_0"]
    for l in range(1, degree + 1):
        names += [f"{EXT}:SH_DEGREE_{l}_COEF_{k}" for k in range(2 * l + 1)]
    return names


def expect(spec, ss, degree=0, axes=lambda p: p, **more):
    points = [axes(s["pos"]) for s in ss]
    return {"spec": spec, "source": SRC, "triangles": 0, "points": len(ss), "vertices": len(ss),
            "colors": True, "tolerance": 1e-3, "facts": {"points": len(ss), "splats": len(ss)},
            "bounds": bounds(points), "positions_include": points,
            "colors_include": [color(s) for s in ss],
            "document": {"attributes": attributes(degree)}, **more}


# --- versions and degrees ---------------------------------------------------------------------

for version in (1, 2, 3):
    ss = splats(version)
    case(FMT, f"version_{version}", {"scene.spz": spz(version, ss)},
         expect(f"{SPEC}: version {version}", ss,
                document={"attributes": attributes(0),
                          "source": {"format": "SPZ", "version": str(version), "shDegree": 0, "antialiased": False}}))

for degree in (1, 2, 3):
    ss = splats(3, degree)
    case(FMT, f"sh_degree_{degree}", {"scene.spz": spz(3, ss, degree=degree)},
         expect(f"{SPEC}: spherical harmonics of degree {degree}", ss, degree,
                json={f"/meshes/0/primitives/0/attributes/{EXT}:SH_DEGREE_{degree + 1}_COEF_0": None}))

ss = splats(2, 1)
case(FMT, "version_2_sh_degree_1_antialiased", {"scene.spz": spz(2, ss, degree=1, flags=1)},
     expect(f"{SPEC}: version 2, degree 1, the antialiased flag", ss, 1,
            document={"attributes": attributes(1), "source": {"antialiased": True, "shDegree": 1}}))

ss = splats(3, 4)
case(FMT, "sh_degree_4", {"scene.spz": spz(3, ss, degree=4)},
     expect(f"{SPEC}: degree 4's coefficients are dropped, KHR_gaussian_splatting stops at 3", ss, 3,
            document={"attributes": attributes(3), "source": {"shDegree": 3, "droppedShDegree": 4}},
            json={f"/meshes/0/primitives/0/attributes/{EXT}:SH_DEGREE_4_COEF_0": None}))

# --- coordinate systems -----------------------------------------------------------------------


def record(system):
    return struct.pack("<III", 0xADBE0003, 4, system)


ss = splats(3)
case(FMT, "coordinates_rdf", {"scene.spz": spz(3, ss, flags=2, records=record(6))},
     expect(f"{SPEC}: the coordinate system record names right, down, forward; y and z flip", ss,
            axes=lambda p: [p[0], -p[1], -p[2]],
            document={"attributes": attributes(0), "source": {"coordinateSystem": 6}}))

case(FMT, "coordinates_luf", {"scene.spz": spz(3, ss, flags=2, records=record(7))},
     expect(f"{SPEC}: left, up, forward; x and z flip", ss, axes=lambda p: [-p[0], p[1], -p[2]]))

case(FMT, "coordinates_rfu", {"scene.spz": spz(3, ss, flags=2, records=record(12))},
     expect(f"{SPEC}: right, forward, up; the node stands z up", ss, axes=lambda p: [p[0], p[2], -p[1]],
            json={"/nodes/0/rotation": [math.sqrt(0.5), 0, 0, math.sqrt(0.5)]}))

other = struct.pack("<II", 0xADBE0002, 12) + bytes(12)
case(FMT, "records_skipped", {"scene.spz": spz(3, ss, flags=2, records=other + record(6))},
     expect(f"{SPEC}: records of other types are skipped to the coordinate system's", ss,
            axes=lambda p: [p[0], -p[1], -p[2]]))

case(FMT, "records_without_flag", {"scene.spz": spz(3, ss, records=record(6))},
     expect(f"{SPEC}: without flag 2, bytes past the splats aren't records", ss))

# --- errors -----------------------------------------------------------------------------------

case(FMT, "truncated", {"cut.spz": spz(3, ss, cut=16 + 30)},
     {"spec": SPEC + ": a stream shorter than the header's count", "source": SRC, "error": "SPZ data is cut short",
      "error_kind": "Truncated"})

case(FMT, "count_too_large", {"big.spz": spz(3, ss, count=0xFFFFFFFF)},
     {"spec": SPEC + ": a count past Keep::max_points is refused before anything is read", "source": SRC,
      "error": "max_points", "error_kind": "LimitExceeded"})

case(FMT, "version_4", {"new.spz": b"NGSP" + struct.pack("<I", 4) + bytes(24)},
     {"spec": "SPZ version 4: zstd streams in a container of their own, not read", "source": SRC,
      "error": "version 4", "error_kind": "Unsupported"})

case(FMT, "unknown_version", {"odd.spz": spz(9, ss)},
     {"spec": SPEC + ": a version past 3", "source": SRC, "error": "version 9", "error_kind": "Unsupported"})

case(FMT, "not_gzip", {"raw.spz": spz(3, ss, raw=True)},
     {"spec": SPEC + ": data that isn't a gzip stream", "source": SRC, "error": "not an SPZ file",
      "error_kind": "UnknownFormat"})

case(FMT, "empty", {"none.spz": spz(3, [])},
     {"spec": SPEC + ": a file of no splats", "source": SRC, "error": "nothing to convert", "error_kind": "Empty"})
