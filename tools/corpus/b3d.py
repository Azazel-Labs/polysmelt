def chunk(tag, body):
    return tag + struct.pack("<i", len(body)) + body


def cstr(s):
    return s.encode("latin-1") + b"\0"


def texs(files):
    out = b""
    for f in files:
        out += cstr(f) + struct.pack("<ii2f2ff", 1, 2, 0, 0, 1, 1, 0)
    return chunk(b"TEXS", out)


def brus(brushes, n=1):
    """`brushes` are (name, rgba, shininess, fx, texture ids)."""
    out = struct.pack("<i", n)
    for name, rgba, shiny, fx, tex in brushes:
        tex = (list(tex) + [-1] * n)[:n]
        out += cstr(name) + struct.pack("<4ffii", *rgba, shiny, 1, fx) + struct.pack("<%di" % n, *tex)
    return chunk(b"BRUS", out)


def vrts(verts, normals=None, colors=None, uvs=(), size=2):
    flags = (1 if normals else 0) | (2 if colors else 0)
    out = struct.pack("<iii", flags, len(uvs), size)
    for i, p in enumerate(verts):
        out += struct.pack("<3f", *p)
        if normals:
            out += struct.pack("<3f", *normals[i])
        if colors:
            out += struct.pack("<4f", *colors[i])
        for s in uvs:
            out += struct.pack("<%df" % size, *(list(s[i]) + [0.0] * size)[:size])
    return chunk(b"VRTS", out)


def tris(brush, faces):
    return chunk(b"TRIS", struct.pack("<i", brush) + b"".join(struct.pack("<3i", *f) for f in faces))


def mesh(brush, *parts):
    return chunk(b"MESH", struct.pack("<i", brush) + b"".join(parts))


def node(name, t=(0, 0, 0), s=(1, 1, 1), q=(1, 0, 0, 0), *kids):
    return chunk(b"NODE", cstr(name) + struct.pack("<3f3f4f", *t, *s, *q) + b"".join(kids))


def bone(weights):
    return chunk(b"BONE", b"".join(struct.pack("<if", v, w) for v, w in weights))


def keys(flags, frames):
    """`frames` are (frame, position, scale, rotation w-first), each value used when `flags` has it."""
    out = struct.pack("<i", flags)
    for frame, p, s, q in frames:
        out += struct.pack("<i", frame)
        if flags & 1:
            out += struct.pack("<3f", *p)
        if flags & 2:
            out += struct.pack("<3f", *s)
        if flags & 4:
            out += struct.pack("<4f", *q)
    return chunk(b"KEYS", out)


def anim(frames, fps):
    return chunk(b"ANIM", struct.pack("<iif", 0, frames, fps))


def b3d(*parts):
    return chunk(b"BB3D", struct.pack("<i", 1) + b"".join(parts))


def mirror(p):
    return [float(p[0]), float(p[1]), -float(p[2])]


def gltf_quat(q):
    """A file quaternion (w, x, y, z) as the document's [x, y, z, w]."""
    w, x, y, z = q
    return [r(x), r(y), r(-z), r(w)]


def quat_matrix(q):
    x, y, z, w = q
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])


def trs(t, q, s=(1, 1, 1)):
    m = np.eye(4)
    m[:3, :3] = quat_matrix(q) @ np.diag(s)
    m[:3, 3] = t
    return m


def bounds(points):
    pts = np.array(points, float)
    return {"min": [r(float(c)) for c in pts.min(0)], "max": [r(float(c)) for c in pts.max(0)]}


def about_y(deg):
    """A file quaternion (w, x, y, z) turning `deg` about Y."""
    a = math.radians(deg) / 2
    return (math.cos(a), 0.0, math.sin(a), 0.0)


