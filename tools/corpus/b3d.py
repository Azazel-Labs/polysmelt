"""B3D conformance cases: Blitz3D models as the format's published file structure (version 1) lays them out,
little-endian.

A file is a tree of chunks, each a four-letter tag and a 32-bit size. BB3D holds the version, then TEXS (per
texture: file, flags, blend, position, scale, rotation), BRUS (a texture count, then per brush: name, RGBA color,
shininess, blend, effects, texture ids) and NODE: a name, position, scale and rotation (a quaternion, w first), then
MESH (a brush, then VRTS: flags 1 for normals, 2 for RGBA colors, the texture coordinate sets and their size, then
the vertices; and TRIS: a brush and triangles), BONE (vertex index and weight pairs on the nearest mesh at or above
the node), KEYS (flags 1 position, 2 scale, 4 rotation, then per key a frame and the values it has), ANIM (flags,
frame count, frames per second) and child NODEs.

Blitz3D is Y up and left-handed, and its quaternions turn row vectors: the document mirrors Z, so a position
(x, y, z) becomes (x, y, -z) and a quaternion stored (w, x, y, z) becomes [x, y, -z, w] in glTF's order. Brushes
are materials (the color as linear, alpha, shininess as roughness, effect 1 unlit, 2 vertex colors, 16 two-sided),
a triangle list on brush -1 takes the mesh's brush, and key times are frames over the animation's rate. The t
coordinate runs down the image, as glTF's does. Expected poses come from numpy matrices in the mirrored space.
"""

