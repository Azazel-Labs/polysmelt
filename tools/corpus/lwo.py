    src = sys.argv[1] if len(sys.argv) > 1 else None
    out = {}
    for name, folder in [*REAL.items(), (LICENSE, None)]:
        p = os.path.join(src or os.path.join(ROOT, FMT, *([folder] if folder else [])), name)
        with open(p, "rb") as f:
            out[name] = f.read()
    return out


