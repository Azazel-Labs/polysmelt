# LWOB: points, surface names (SRFS), polygons each ending in its surface number (from 1), and
# surfaces with 8-bit colors and fixed-point (n / 256) levels.
def lwob_pols(polys, surfs):
    out = b""
    for p, s in zip(polys, surfs):
        out += u2(len(p)) + b"".join(u2(v) for v in reversed(p)) + struct.pack(">h", s)
    return ck(b"POLS", out)


