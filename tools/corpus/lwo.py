# --- real files ---------------------------------------------------------------------------------

def chunks(b, at, end, short=False):
    while at + (6 if short else 8) <= end:
        cid = b[at:at + 4]
        n = struct.unpack_from(">H" if short else ">I", b, at + 4)[0]
        at += 6 if short else 8
        yield cid, at, n
        at += n + (n & 1)


def read_lwo(b):
    """Each layer's faces (point lists in glTF's axes, placed at their pivots)."""
    kind = b[8:12]
    faces, points, pivot = [], [], (0.0, 0.0, 0.0)
    pivots = {}
    for cid, at, n in chunks(b, 12, len(b)):
        if cid == b"LAYR":
            num = struct.unpack_from(">H", b, at)[0]
            pivot = struct.unpack_from(">3f", b, at + 4)
            pivots[num] = pivot
        elif cid == b"PNTS":
            points = [struct.unpack_from(">3f", b, at + 12 * k) for k in range(n // 12)]
        elif cid == b"POLS":
            p, end = at, at + n
            if kind != b"LWOB":
                if b[p:p + 4] != b"FACE":
                    continue
                p += 4
            while p < end:
                count = struct.unpack_from(">H", b, p)[0] & 0x3FF
                p += 2
                idx = []
                for _ in range(count):
                    if kind != b"LWOB" and b[p] == 0xFF:
                        idx.append(struct.unpack_from(">I", b, p)[0] & 0xFFFFFF)
                        p += 4
                    else:
                        idx.append(struct.unpack_from(">H", b, p)[0])
                        p += 2
                if kind == b"LWOB":
                    s = struct.unpack_from(">h", b, p)[0]
                    p += 2
                    assert s > 0, "detail polygons, which the cases don't have"
                if count >= 3:
                    # Points are where they are in the object; the pivot only places the layer's node.
                    faces.append([(q[0], q[1], -q[2]) for q in (points[i] for i in idx)])
    return faces


