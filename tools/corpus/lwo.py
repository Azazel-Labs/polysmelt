# --- writing ------------------------------------------------------------------------------------

def ck(cid, data):
    """A chunk, padded to an even length."""
    return cid + struct.pack(">I", len(data)) + data + (b"\0" if len(data) % 2 else b"")


def sub(cid, data):
    """A subchunk (16-bit length)."""
    return cid + struct.pack(">H", len(data)) + data + (b"\0" if len(data) % 2 else b"")


def s0(s):
    b = s.encode() + b"\0"
    return b + (b"\0" if len(b) % 2 else b"")


def u2(v):
    return struct.pack(">H", v)


def vx(v):
    return struct.pack(">H", v) if v < 0xFF00 else struct.pack(">I", v | 0xFF000000)


def f4(*v):
    return struct.pack(f">{len(v)}f", *v)


def form(kind, chunks):
    body = kind + b"".join(chunks)
    return b"FORM" + struct.pack(">I", len(body)) + body


def gltf_to_lw(p):
    return (p[0], p[1], -p[2])


def pnts(pts):
    """Points given in glTF's axes, written in LightWave's."""
    return ck(b"PNTS", b"".join(f4(*gltf_to_lw(p)) for p in pts))


def pols(polys, kind=b"FACE"):
    """Polygons given counterclockwise (glTF's way), written clockwise (LightWave's)."""
    return ck(b"POLS", kind + b"".join(u2(len(p)) + b"".join(vx(v) for v in reversed(p)) for p in polys))


def ptag(surfs):
    return ck(b"PTAG", b"SURF" + b"".join(vx(i) + u2(s) for i, s in enumerate(surfs)))


def layr(n, pivot=(0, 0, 0), name="", parent=None):
    return ck(b"LAYR", u2(n) + u2(0) + f4(*gltf_to_lw(pivot)) + s0(name) + (u2(parent) if parent is not None else b""))


def surf(name, color=(0.8, 0.8, 0.8), diff=1.0, extra=b""):
    return ck(b"SURF", s0(name) + s0("") + sub(b"COLR", f4(*color) + vx(0)) + sub(b"DIFF", f4(diff) + vx(0)) + extra)


def lin(c, k=1.0, a=1.0):
    return [r(srgb_to_linear(x) * k) for x in c] + [a]


