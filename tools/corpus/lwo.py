"""LightWave object conformance cases: LWO2 (the LightWave 6 object file format, as LightWave's SDK
documents it) and LWOB (LightWave 5's).

An object is an IFF FORM of chunks, big-endian: layers (LAYR) with their points (PNTS), polygons
(POLS), polygon tags (PTAG, naming each polygon's surface from TAGS) and vertex maps (VMAP: UVs,
colors, morphs), then the surfaces (SURF) and image clips (CLIP) they use. LightWave is Y up, in
meters, but left-handed, and a polygon's points run clockwise seen from its front, so glTF's
position is (x, y, -z) and each polygon's order turns around. A surface's color (sRGB) times its
diffuse level is the base color, 1 - transparency the alpha, luminosity times the color the
emission, and two sides when SIDE is 3. UV maps' v runs up, so glTF's is 1 - v.

Also three real files from assimp's test models (test/models/LWO; BSD license, see
LICENSE-assimp beside the cases), kept in their case folders (or read from the folder given as
the first argument). Their expectations come from reading them here: the triangles each face
makes (n - 2 for n points), and the bounds of their points placed at their layers' pivots.
"""

