"""LAS and LAZ conformance cases: the ASPRS LAS specification, versions 1.0 to 1.4 (R15).

A LAS file is a public header block, variable-length records and point records. Each point's
coordinates are integers; the position is integer * scale + offset, in the axes x (east),
y (north) and z (up), so glTF's Y-up position is (x, z, -y). Point formats 0 to 5 hold their
return number and count in one byte, 6 to 10 in two; formats 2, 3, 5, 7, 8 and 10 add RGB,
8 and 10 near infrared. A GeoKeyDirectoryTag record (GeoTIFF keys) may say the coordinates are
in feet.

Also two real files from PDAL's test data (test/data/las; BSD license, see LICENSE-PDAL beside
the cases): simple.las and simple.laz, its compressed copy. They are kept in their case folders
(or read from the folder given as the first argument), and their expectations come from reading
simple.las here.
"""

import os
import struct
import sys

# The shared modules are beside this script, which `python -I` leaves off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, case, fresh, r, srgb_to_linear  # noqa: E402

FMT = "las"
SRC = "generated by tools/corpus/las.py"
SPEC = "LAS 1.4 R15 (ASPRS)"
REAL = {"simple.las": "pdal_simple_las", "simple.laz": "pdal_simple_laz"}


def keep_real():
    """The real files and their license, read before the folder is emptied."""
    src = sys.argv[1] if len(sys.argv) > 1 else None
    out = {}
    for name, folder in [*REAL.items(), ("LICENSE-PDAL", None)]:
        p = os.path.join(src or os.path.join(ROOT, FMT, *([folder] if folder else [])), name)
        with open(p, "rb") as f:
            out[name] = f.read()
    return out


real = keep_real()
os.remove(os.path.join(ROOT, FMT, "LICENSE-PDAL")) if os.path.exists(os.path.join(ROOT, FMT, "LICENSE-PDAL")) else None
fresh(FMT)
with open(os.path.join(ROOT, FMT, "LICENSE-PDAL"), "wb") as f:
    f.write(real["LICENSE-PDAL"])

# Point record sizes by format.
SIZES = {0: 20, 1: 28, 2: 26, 3: 34, 6: 30, 7: 36, 8: 38}


def header(version, fmt, count, scale, offset, lo, hi, vlrs=b"", nvlrs=0):
    """The public header block for `version` (minor), with `vlrs` following it."""
    size = {0: 227, 1: 227, 2: 227, 3: 235, 4: 375}[version]
    legacy = 0 if (version == 4 and fmt >= 6) else count
    h = b"LASF" + struct.pack("<HH", 0, 0) + bytes(16) + bytes([1, version])
    h += b"tools/corpus".ljust(32, b"\0") + b"las.py".ljust(32, b"\0")
    h += struct.pack("<HHHIIBHI", 1, 2026, size, size + len(vlrs), nvlrs, fmt, SIZES[fmt], legacy)
    h += struct.pack("<5I", legacy, 0, 0, 0, 0)
    h += struct.pack("<3d", *scale) + struct.pack("<3d", *offset)
    h += struct.pack("<6d", hi[0], lo[0], hi[1], lo[1], hi[2], lo[2])
    if version >= 3:
        h += struct.pack("<Q", 0)
    if version >= 4:
        h += struct.pack("<QIQ", 0, 0, count) + struct.pack("<15Q", count, *([0] * 14))
    assert len(h) == size, (len(h), size)
    return h + vlrs


def vlr(user, rid, data, desc=b""):
    return struct.pack("<H", 0) + user.ljust(16, b"\0") + struct.pack("<HH", rid, len(data)) + desc.ljust(32, b"\0") + data


def geokeys(keys):
    """A GeoKeyDirectoryTag record of (key, value) pairs, each stored in place."""
    words = [1, 1, 0, len(keys)]
    for k, v in keys:
        words += [k, 0, 1, v]
    return vlr(b"LASF_Projection", 34735, struct.pack(f"<{len(words)}H", *words))


def point(fmt, xyz, i, rgb=None, ret=(1, 1), cls=2, t=0.0, nir=0):
    x, y, z = xyz
    if fmt < 6:
        p = struct.pack("<3iHBBbBH", x, y, z, i, ret[0] | (ret[1] << 3), cls, -5, 7, cls * 3)
        if fmt in (1, 3):
            p += struct.pack("<d", t)
    else:
        p = struct.pack("<3iHBBBBhH", x, y, z, i, ret[0] | (ret[1] << 4), 0, cls, 7, -500, cls * 3)
        p += struct.pack("<d", t)
    if rgb is not None:
        p += struct.pack("<3H", *rgb)
    if fmt == 8:
        p += struct.pack("<H", nir)
    assert len(p) == SIZES[fmt], (fmt, len(p))
    return p


# Four points, in integer coordinates at a scale of 0.01.
INTS = [(0, 0, 0), (100, 0, 50), (100, 200, 0), (0, 200, 300)]
RGB8 = [(255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 255, 255)]


def las(version, fmt, scale=(0.01, 0.01, 0.01), offset=(0.0, 0.0, 0.0), ints=INTS, rgb=None, keys=None):
    pos = [[c * scale[k] + offset[k] for k, c in enumerate(p)] for p in ints]
    lo = [min(p[k] for p in pos) for k in range(3)]
    hi = [max(p[k] for p in pos) for k in range(3)]
    v = geokeys(keys) if keys else b""
    out = header(version, fmt, len(ints), scale, offset, lo, hi, v, 1 if keys else 0)
    for n, p in enumerate(ints):
        out += point(fmt, p, 100 * (n + 1), rgb[n] if rgb else None, ret=(1 + n % 2, 2), cls=n + 1, t=n * 0.5,
                     nir=n * 1000)
    return out, pos


def y_up(p, unit=(1, 1, 1)):
    return [p[0] * unit[0], p[2] * unit[2], -p[1] * unit[1]]


def bounds(pos, unit=(1, 1, 1)):
    g = [y_up(p, unit) for p in pos]
    return {"min": [r(min(q[k] for q in g)) for k in range(3)], "max": [r(max(q[k] for q in g)) for k in range(3)]}


def lin(c):
    return [r(srgb_to_linear(x / 255)) for x in c] + [1.0]


ATTRS = ["POSITION", "_INTENSITY", "_RETURN_NUMBER", "_CLASSIFICATION", "_POINT_SOURCE_ID"]

for version, fmt in [(0, 0), (2, 1), (4, 6)]:
    data, pos = las(version, fmt)
    attrs = ATTRS + (["_GPS_TIME"] if fmt in (1, 6) else [])
    case(FMT, f"v1{version}_format{fmt}", {"points.las": data},
         {"spec": f"{SPEC}: version 1.{version}, point format {fmt}; x east, y north, z up", "source": SRC,
          "points": 4, "triangles": 0, "colors": False, "bounds": bounds(pos),
          "positions_include": [y_up(p) for p in pos], "document": {"attributes": attrs}})

for version, fmt in [(2, 2), (2, 3), (4, 7), (4, 8)]:
    data, pos = las(version, fmt, rgb=[[c * 257 for c in col] for col in RGB8])
    attrs = ATTRS + (["_NIR"] if fmt == 8 else [])
    case(FMT, f"v1{version}_format{fmt}_colors", {"points.las": data},
         {"spec": f"{SPEC}: point format {fmt}, 16-bit RGB (sRGB)", "source": SRC, "points": 4, "colors": True,
          "colors_include": [lin(c) for c in RGB8], "bounds": bounds(pos), "document": {"attributes": attrs}})

data, pos = las(2, 2, rgb=RGB8)
case(FMT, "colors_stored_as_8_bit", {"points.las": data},
     {"spec": f"{SPEC}: RGB fields holding 8-bit values, as some writers store them", "source": SRC,
      "points": 4, "colors": True, "colors_include": [lin(c) for c in RGB8]})

# Far from the origin: UTM-like offsets. The flat mesh is single precision, so the tolerance is
# loose enough for its rounding near 4 million.
data, pos = las(2, 0, scale=(0.001, 0.001, 0.001), offset=(500000.0, 4000000.0, 100.0))
case(FMT, "offset_far_from_origin", {"points.las": data},
     {"spec": f"{SPEC}: X = Xrecord * scale + offset, far from the origin", "source": SRC, "points": 4,
      "bounds": bounds(pos), "tolerance": 1e-6})

data, pos = las(2, 0, scale=(0.5, 0.25, 2.0), ints=[(-10, 4, 1), (10, -4, -1), (3, 3, 3)])
case(FMT, "scale_per_axis", {"points.las": data},
     {"spec": f"{SPEC}: a scale factor per axis, negative coordinates", "source": SRC, "points": 3,
      "bounds": bounds(pos), "positions_include": [y_up(p) for p in pos]})

FOOT = 0.3048
data, pos = las(2, 0, keys=[(1024, 1), (3072, 2263), (3076, 9002)])
case(FMT, "feet", {"points.las": data},
     {"spec": f"{SPEC}: GeoKeyDirectoryTag with ProjLinearUnitsGeoKey 9002, feet", "source": SRC, "points": 4,
      "bounds": bounds(pos, (FOOT, FOOT, FOOT))})

data, pos = las(2, 0, keys=[(1024, 1), (3076, 9001), (4099, 9002)])
case(FMT, "meters_across_feet_up", {"points.las": data},
     {"spec": f"{SPEC}: meters across (ProjLinearUnitsGeoKey 9001), feet up (VerticalUnitsGeoKey 9002)",
      "source": SRC, "points": 4, "bounds": bounds(pos, (1, 1, FOOT))})

data, _ = las(2, 0)
case(FMT, "truncated", {"cut.las": data[:-5]},
     {"spec": f"{SPEC}: point records cut short", "source": SRC, "error": "LAS data is cut short",
      "error_kind": "Truncated"})
case(FMT, "not_las", {"model.las": b"PK\x03\x04" + bytes(400)},
     {"spec": f"{SPEC}: a file without the LASF signature", "source": SRC, "error": "not a LAS file",
      "error_kind": "UnknownFormat"})
bad = bytearray(data)
bad[104] = 42
case(FMT, "unknown_point_format", {"points.las": bytes(bad)},
     {"spec": f"{SPEC}: a point format past 10", "source": SRC, "error": "point format", "error_kind": "Unsupported"})


