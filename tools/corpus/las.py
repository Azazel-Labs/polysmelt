def read_las(b):
    """The points of an uncompressed LAS file: positions (Z up) and 16-bit colors."""
    off, = struct.unpack_from("<I", b, 96)
    fmt = b[104] & 0x3F
    rec, count = struct.unpack_from("<HI", b, 105)
    scale = struct.unpack_from("<3d", b, 131)
    offset = struct.unpack_from("<3d", b, 155)
    rgb_at = {2: 20, 3: 28, 5: 28, 7: 30, 8: 30, 10: 30}.get(fmt)
    pts, cols = [], []
    for n in range(count):
        at = off + n * rec
        xyz = struct.unpack_from("<3i", b, at)
        pts.append([xyz[k] * scale[k] + offset[k] for k in range(3)])
        if rgb_at is not None:
            cols.append(struct.unpack_from("<3H", b, at + rgb_at))
    return fmt, pts, cols


fmt, pts, cols = read_las(real["simple.las"])
eight = max(max(c) for c in cols) <= 255
some = [cols[k] for k in (0, len(cols) // 2, len(cols) - 1)]
# Colors are 16-bit in the flat mesh, so the tolerance is a little looser than the positions need.
expect = {"points": len(pts), "triangles": 0, "bounds": bounds(pts), "tolerance": 2e-5,
          "positions_include": [y_up(pts[k]) for k in (0, len(pts) // 2, len(pts) - 1)],
          "colors": True, "colors_include": [lin(c if eight else [x / 257 for x in c]) for c in some]}
for name, folder in REAL.items():
    case(FMT, folder, {name: real[name]},
         {"spec": f"{SPEC}: a real file, point format {fmt}" + (", LAZ-compressed" if name.endswith("z") else ""),
          "source": "PDAL test data (test/data/las), BSD license, see ../LICENSE-PDAL", **expect})
