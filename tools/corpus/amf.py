# Constellations. Turn by rx, ry, rz degrees: R = Rz * Ry * Rx, then move by the delta.
def rot(rx, ry, rz):
    def m(axis, deg):
        c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
        return {"x": [[1, 0, 0], [0, c, -s], [0, s, c]], "y": [[c, 0, s], [0, 1, 0], [-s, 0, c]],
                "z": [[c, -s, 0], [s, c, 0], [0, 0, 1]]}[axis]

    def mm(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    return mm(mm(m("z", rz), m("y", ry)), m("x", rx))


def place(p, turn, delta):
    m = rot(*turn)
    return [sum(m[i][k] * p[k] for k in range(3)) + delta[i] for i in range(3)]


def instance(oid, delta=(0, 0, 0), turn=(0, 0, 0)):
    return (f'<instance objectid="{oid}"><deltax>{delta[0]}</deltax><deltay>{delta[1]}</deltay>'
            f"<deltaz>{delta[2]}</deltaz><rx>{turn[0]}</rx><ry>{turn[1]}</ry><rz>{turn[2]}</rz></instance>")


