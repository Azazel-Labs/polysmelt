"""AMF conformance cases: ISO/ASTM 52915, the additive manufacturing file format.

An AMF is XML, as it is or zipped. Objects hold vertices and volumes of triangles; the amf
element's unit (millimeters when unsaid) applies to every coordinate, and Z is up, so glTF's
Y-up position is (x, z, -y) times the unit in meters. Colors are sRGB 0-1 values; a triangle's
color comes first, then its vertices', its volume's, its object's and its material's, and a
composite material's color is its parts' mixed by their proportions. Constellations place
objects and other constellations by an instance's delta and its rotations about x, then y,
then z, in degrees.

Also two real files from assimp's test models (test/models/AMF; BSD license, see
LICENSE-assimp beside the cases), kept in their case folders (or read from the folder given as
the first argument). Their expectations come from reading them here, by the rules above.
"""

