def color(c):
    if c is None:
        return ""
    a = f"<a>{c[3]}</a>" if len(c) > 3 else ""
    return f"<color><r>{c[0]}</r><g>{c[1]}</g><b>{c[2]}</b>{a}</color>"


def vertex(v, c=None):
    return f"<vertex>{color(c)}<coordinates><x>{v[0]}</x><y>{v[1]}</y><z>{v[2]}</z></coordinates></vertex>"


def triangle(t, c=None, extra=""):
    return f"<triangle>{color(c)}<v1>{t[0]}</v1><v2>{t[1]}</v2><v3>{t[2]}</v3>{extra}</triangle>"


def volume(tris, attrs="", c=None, tri_colors=None, meta=""):
    body = "".join(triangle(t, (tri_colors or {}).get(k)) for k, t in enumerate(tris))
    return f"<volume{attrs}>{meta}{color(c)}{body}</volume>"


def obj(oid, verts, volumes, c=None, vcolors=None):
    vs = "".join(vertex(v, (vcolors or {}).get(k)) for k, v in enumerate(verts))
    return f'<object id="{oid}">{color(c)}<mesh><vertices>{vs}</vertices>{"".join(volumes)}</mesh></object>'


def amf(body, unit=None):
    u = f' unit="{unit}"' if unit else ""
    return f'<?xml version="1.0" encoding="utf-8"?>\n<amf{u} version="1.1">{body}</amf>\n'


def y_up(p, scale):
    return [r(p[0] * scale), r(p[2] * scale), r(-p[1] * scale)]


def bounds(pts, scale):
    g = [y_up(p, scale) for p in pts]
    return {"min": [min(q[k] for q in g) for k in range(3)], "max": [max(q[k] for q in g) for k in range(3)]}


def lin(c):
    return [r(srgb_to_linear(x)) for x in c[:3]] + [c[3] if len(c) > 3 else 1.0]


