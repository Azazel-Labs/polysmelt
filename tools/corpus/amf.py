def read_amf(text):
    """Each placed triangle's corners (Z up, in the file's unit), the unit's meters and the
    materials' names and colors."""
    root = ET.fromstring(text)
    scale = {"inch": 0.0254, "meter": 1.0, "feet": 0.3048, "micron": 1e-6, "centimeter": 0.01}.get(
        root.get("unit", "millimeter"), 1e-3)
    objects = {}
    for o in root.findall("object"):
        vs = [[float(v.find("coordinates").find(a).text) for a in "xyz"] for v in o.find("mesh/vertices")]
        objects[o.get("id")] = [[vs[int(t.find(k).text)] for k in ("v1", "v2", "v3")]
                                for t in o.iter("triangle")]
    cons = {c.get("id"): c for c in root.findall("constellation")}

    def tris(oid):
        if oid in objects:
            return objects[oid]
        out = []
        for inst in cons[oid].findall("instance"):
            def num(tag):
                e = inst.find(tag)
                return float(e.text) if e is not None else 0.0
            d = [num(t) for t in ("deltax", "deltay", "deltaz")]
            t = [num(t) for t in ("rx", "ry", "rz")]
            out += [[place(p, t, d) for p in tri] for tri in tris(inst.get("objectid"))]
        return out

    used = {i.get("objectid") for c in cons.values() for i in c.findall("instance")}
    placed = [t for k in [*cons, *objects] if k not in used for t in tris(k)]
    mats = []
    for m in root.findall("material"):
        name = m.find("metadata[@type='name']")
        c = [float(m.find("color").find(a).text) if m.find("color").find(a) is not None else 1.0 for a in "rgba"]
        mats.append({"name": name.text if name is not None else f"material_{m.get('id')}", "color": lin(c)})
    return placed, scale, mats


for name, folder in REAL.items():
    tris, scale, mats = read_amf(real[name])
    pts = [p for t in tris for p in t]
    expect = {"triangles": len(tris), "bounds": bounds(pts, scale), "tolerance": 1e-5}
    if mats:
        expect["materials"] = mats
    what = "materials, metadata and inches" if mats else "colors and a constellation turning two copies"
