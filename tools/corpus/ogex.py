"""OpenGEX conformance cases: the Open Game Engine Exchange format, version 3.0, as its specification
defines it, written in OpenDDL (the Open Data Description Language specification).

The scene is a tree of nodes (Node, BoneNode, GeometryNode, LightNode, CameraNode) placed by their
transforms (Transform, Translation, Rotation and Scale, multiplied in the order they appear); a
transform with object = true moves only the node's own object. Matrices are written column after
column. Geometry objects hold meshes of vertex arrays and index arrays; each index array names the
material index whose MaterialRef it takes. Faces wind counterclockwise from the front unless an
index array says front = "cw". Texture coordinates run up from the image's bottom, so glTF's v is
1 - v. Colors are linear. The Metric structures give the distance, angle and time units and the up
axis (z by default): glTF is Y up and in meters, so a point (x, y, z) of a Z-up file is (x, z, -y)
there, times the distance metric.

Skinned vertices are sum(w_i * M_i * inverse(B_i) * S * v): M_i a bone's transform, B_i its bind
pose, S the skin's own transform; the geometry node's transform doesn't apply. Morphed vertices are
sum(w_i * p_i) over the morph targets' positions. Animation tracks drive transforms and morph
weights, by linear, constant or Bezier curves.

Also real files from assimp's test models (test/models/OpenGEX; BSD license, see LICENSE-assimp
beside the cases), kept in their case folders (or read from the folder given as the first
argument). Their expectations come from reading them here with a small OpenDDL reader, by the
rules above.
"""

