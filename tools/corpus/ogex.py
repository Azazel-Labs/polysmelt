def parse_ddl(text):
    """A small OpenDDL reader: a list of (identifier, name, properties, children) structures, where
    a primitive structure is ("$data", type, size, values)."""
    toks = re.findall(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|[$%][A-Za-z_][\w%]*|0[xX][0-9A-Fa-f_]+|'
                      r'[-+]?[0-9.][\w.+-]*|[A-Za-z_]\w*|[{}()\[\],=]', text, re.S)
    toks = [t for t in toks if not t.startswith("//") and not t.startswith("/*")]
    pos = 0

    def value(t, kind):
        if t.startswith('"'):
            return t[1:-1]
        if t[0] in "$%" or kind == "ref":
            return t
        if t in ("true", "false"):
            return t == "true"
        neg = t.startswith("-")
        body = t.lstrip("+-").replace("_", "")
        if body[:2].lower() == "0x":
            n = int(body, 16)
            if kind.startswith("float") or kind == "double":
                v = struct.unpack(">f", struct.pack(">I", n))[0]
                return -v if neg else v
            return -n if neg else n
        v = float(body) if kind.startswith("float") or kind == "double" else int(body)
        return -v if neg else v

    def structures(end):
        nonlocal pos
        out = []
        while pos < len(toks) and toks[pos] != end:
            ident = toks[pos]
            pos += 1
            if ident in ("float", "double", "string", "ref", "bool") or re.fullmatch(r"u?int\d+|unsigned_int\d+|"
                                                                                       r"float\d+", ident):
                size = 1
                if toks[pos] == "[":
                    size = int(toks[pos + 1])
                    pos += 3
                if toks[pos][0] in "$%":
                    pos += 1
                pos += 1  # {
                vals = []
                while toks[pos] != "}":
                    if toks[pos] == "{":
                        pos += 1
                        row = []
                        while toks[pos] != "}":
                            if toks[pos] != ",":
                                row.append(value(toks[pos], ident))
                            pos += 1
                        vals.append(row)
                    elif toks[pos] != ",":
                        vals.append(value(toks[pos], ident))
                    pos += 1
                pos += 1
                out.append(("$data", ident, size, vals))
                continue
            name = None
            if toks[pos][0] in "$%":
                name = toks[pos]
                pos += 1
            props = {}
            if toks[pos] == "(":
                pos += 1
                while toks[pos] != ")":
                    if toks[pos] == ",":
                        pos += 1
                        continue
                    key = toks[pos]
                    props[key] = value(toks[pos + 2], "string") if toks[pos + 2].startswith('"') else toks[pos + 2]
                    pos += 3
                pos += 1
            pos += 1  # {
            kids = structures("}")
            pos += 1
            out.append((ident, name, props, kids))
        return out

    return structures(None)


def data(s):
    return next(k for k in s[3] if k[0] == "$data")[3]


def read_ogex(text):
    """What a real file draws: its triangles (in glTF's space), lights, cameras and nodes (the root among them).
    A file with no nodes has each of its objects placed under the root by itself."""
    top = parse_ddl(text)
    up, meters = "z", 1.0
    named = {}

    def index(items):
        for s in items:
            if s[0] != "$data":
                if s[1]:
                    named[s[1]] = s
                index(s[3])

    index(top)
    for s in top:
        if s[0] == "Metric" and s[2].get("key") == "up":
            up = data(s)[0]
        if s[0] == "Metric" and s[2].get("key") == "distance":
            meters = float(data(s)[0])
    tris, lights, cameras = [], 0, 0

    def walk(items, parent):
        nonlocal lights, cameras
        for s in items:
            if s[0] not in ("Node", "BoneNode", "GeometryNode", "LightNode", "CameraNode"):
                continue
            m = parent
            for t in s[3]:
                if t[0] == "Transform":
                    m = mul(m, data(t)[0])
            refs = [data(t)[0] for t in s[3] if t[0] == "ObjectRef"]
            if s[0] == "LightNode" and refs:
                lights += 1
            if s[0] == "CameraNode" and refs:
                cameras += 1
            if s[0] == "GeometryNode" and refs:
                draw(named[refs[0]], m)
            walk(s[3], m)

    def draw(obj, m):
        for msh in [t for t in obj[3] if t[0] == "Mesh"][:1]:
            pos = next(data(t) for t in msh[3] if t[0] == "VertexArray" and t[2].get("attrib") == "position")
            for ia in [t for t in msh[3] if t[0] == "IndexArray"]:
                for f in data(ia):
                    pts = [apply(m, pos[i]) for i in f]
                    tris.append([z_up(p, meters) if up == "z" else [c * meters for c in p] for p in pts])

    kinds = ("Node", "BoneNode", "GeometryNode", "LightNode", "CameraNode")
    nodes = 1 + sum(1 for s in top if s[0] in kinds)
    walk(top, IDENTITY)
    if nodes == 1:
        for s in top:
            if s[0] == "LightObject":
                lights += 1
            elif s[0] == "CameraObject":
                cameras += 1
            elif s[0] == "GeometryObject":
                draw(s, IDENTITY)
            else:
                continue
            nodes += 1
    return tris, lights, cameras, nodes


