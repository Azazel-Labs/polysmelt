"""IQM conformance cases: Inter-Quake Models as the format's published structures (iqm.h, version 2) lay them out,
little-endian and packed.

A file is a 124-byte header ("INTERQUAKEMODEL\\0", version, file size, flags, then the counts and offsets of the
text block, meshes, vertex arrays, triangles, adjacency, joints, poses, animations, frames, bounds, comments and
extensions), a text block every name is an offset into, vertex arrays (type, flags, number format, component count,
offset: positions, texture coordinates, normals, tangents, blend indices, blend weights, colors, and custom types
from 16), triangles (three 32-bit vertex indices), meshes (name, material, first vertex and count, first triangle
and count), joints (name, parent, translation, rotation x y z w, scale, relative to the parent), poses (parent, a
channel mask, and ten channel offsets and scales), animations (name, first frame, frame count, frame rate, flags
with bit 1 for looping) and frames (a 16-bit number per masked channel per pose: value = offset + number · scale).

Each mesh is a node and mesh of one primitive: every texture coordinate array a set and every color array a color
set (integers as fractions of their range; integer colors sRGB, made linear, float colors linear), blend index and
weight arrays the joints and weights. Joints are nodes with a skin over them; each animation is a linear one with
the channels whose values leave the joint's rest. A material name is the texture's file, as written or as a .png.
Triangles wind clockwise seen from the front, so the reader turns them around; texture coordinates run down the
image, as glTF's do. The format is Z up, so a point (x, y, z) lands at (x, z, -y) and a root's rotation q becomes
r·q for r the quarter turn about x. Expected poses are worked out here with plain matrices.
"""

