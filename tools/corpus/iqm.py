POSITION, TEXCOORD, NORMAL, TANGENT, BLENDINDEXES, BLENDWEIGHTS, COLOR, CUSTOM = 0, 1, 2, 3, 4, 5, 6, 16
BYTE, UBYTE, SHORT, USHORT, INT, UINT, HALF, FLOAT, DOUBLE = range(9)
PACK = {BYTE: "b", UBYTE: "B", SHORT: "h", USHORT: "H", INT: "i", UINT: "I", HALF: "e", FLOAT: "f", DOUBLE: "d"}

S = math.sqrt(0.5)
Z_UP = [-S, 0.0, 0.0, S]


class Text:
    """The text block: offset 0 is the empty name."""

    def __init__(self):
        self.data = b"\0"

    def __call__(self, s):
        if not s:
            return 0
        at = len(self.data)
        self.data += s.encode("latin-1") + b"\0"
        return at


def build(text, arrays, n_verts, triangles, meshes, joints=(), poses=(), anims=(), frames=(), n_channels=None,
          header=None, array_format=None):
    """The bytes of a file. `arrays` are (type, format, size, values); `meshes` (name, material, first vertex,
    count, first triangle, count) with names already in `text`; `joints` (name, parent, t, r, s); `poses` (mask,
    offsets, scales); `anims` (name, first, count, rate, flags); `frames` lists of 16-bit numbers. `header`
    overrides header fields by index (0 is the version)."""
    body = b""
    off = 124

    def place(b):
        nonlocal body
        at = off + len(body)
        body += b
        while len(body) % 4:
            body += b"\0"
        return at

    heads = []
    for kind, fmt, size, values in arrays:
        assert len(values) == n_verts * size, kind
        heads.append((kind, fmt, size, place(struct.pack("<%d%s" % (len(values), PACK[fmt]), *values))))
    ofs_va = place(b"".join(struct.pack("<5I", k, 0, array_format if array_format is not None else f, s, o)
                            for k, f, s, o in heads))
    ofs_tris = place(b"".join(struct.pack("<3I", *t) for t in triangles))
    ofs_meshes = place(b"".join(struct.pack("<6I", *m) for m in meshes))
    ofs_joints = place(b"".join(struct.pack("<Ii3f4f3f", text(n), p, *t, *q, *s) for n, p, t, q, s in joints))
    ofs_poses = place(b"".join(struct.pack("<iI10f10f", -1, m, *o, *sc) for m, o, sc in poses))
    ofs_anims = place(b"".join(struct.pack("<IIIfI", text(n), a, c, rt, fl) for n, a, c, rt, fl in anims))
    # The anims and joints added names; the text block goes last so they're in it.
    flat = [v for f in frames for v in f]
    ofs_frames = place(struct.pack("<%dH" % len(flat), *flat))
    ofs_text = place(text.data)
    if n_channels is None:
        n_channels = sum(bin(m & 0x3FF).count("1") for m, _, _ in poses)
    h = [2, 124 + len(body), 0, len(text.data), ofs_text, len(meshes), ofs_meshes, len(arrays), n_verts, ofs_va,
         len(triangles), ofs_tris, 0, len(joints), ofs_joints, len(poses), ofs_poses, len(anims), ofs_anims,
         len(frames), n_channels, ofs_frames, 0, 0, 0, 0, 0]
    for k, v in (header or {}).items():
        h[k] = v
    return b"INTERQUAKEMODEL\0" + struct.pack("<27I", *h) + body


def yup(p):
    return [p[0], p[2], -p[1]]


def flat(rows):
    return [c for row in rows for c in row]


def bounds_of(points):
    pts = [yup(p) for p in points]
    return {"min": [min(p[k] for p in pts) for k in range(3)], "max": [max(p[k] for p in pts) for k in range(3)]}


