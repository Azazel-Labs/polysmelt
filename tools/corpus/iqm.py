# Errors start from the skinned file and change one thing.
HEADER = 16


def patch(data, at, fmt, *values):
    b = bytearray(data)
    struct.pack_into(fmt, b, at, *values)
    return bytes(b)


def field(k):
    """The offset of header field k (0 is the version)."""
    return HEADER + 4 * k


def header_value(data, k):
    return struct.unpack_from("<I", data, field(k))[0]


def errors(name, data, text_, what):
    case(FMT, name, {name + ".iqm": data}, {"spec": SPEC + ": " + what, "source": SRC, "error": text_})


