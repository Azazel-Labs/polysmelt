def posed(f):
    """The corners at frame f, Z up: the root scales x, the arm moves and turns its two corners."""
    sx = 1 + f / 2
    a = math.radians(90 * f)
    arm_t = (0, 1 + f, 0)
    out = []
    for i, p in enumerate(QUAD):
        if i < 2:
            q = p
        else:
            local = (p[0], p[1] - 1, p[2])  # in the arm's rest frame
            q = (math.cos(a) * local[0] - math.sin(a) * local[1] + arm_t[0],
                 math.sin(a) * local[0] + math.cos(a) * local[1] + arm_t[1], local[2] + arm_t[2])
        out.append((q[0] * sx, q[1], q[2]))
    return out


def turned(deg):
    a = math.radians(deg) / 2
    return [0, 0, r(math.sin(a)), r(math.cos(a))]


