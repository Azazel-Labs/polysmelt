# The skinned case. Corners 0 and 1 follow "root", 2 and 3 "arm", which rests at (0, 1, 0). Frames: the root's
# scale x is 1 + f/2; the arm rises to y = 1 + f and turns 90° · f about z (its rotation's z and w channels
# animated; at 90° they're equal, so the 16-bit steps still make an exact quarter turn once normalized).
U16 = 65535


def arm_frame(f):
    a = math.radians(90 * f) / 2
    return [f, round(math.sin(a) * U16), round(math.cos(a) * U16)]


