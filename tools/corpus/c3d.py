BLOCK = 512
PROC = {"Intel": 84, "DEC": 85, "MIPS": 86}


def quaternion(m):
    """The unit quaternion [x, y, z, w] of rotation matrix `m` (Shepperd's method)."""
    m = np.array(m, dtype=float)
    t = np.trace(m)
    if t > 0:
        s = math.sqrt(t + 1.0) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, 0.25 * s]
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = [0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s]
    elif m[1, 1] > m[2, 2]:
        s = math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = [(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s]
    else:
        s = math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = [(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s]
    return [r(float(c)) for c in q]


AXES = {"X": [1, 0, 0], "Y": [0, 1, 0], "Z": [0, 0, 1]}


def axis(s):
    v = np.array(AXES[s[-1].upper()], dtype=float)
    return -v if s.startswith("-") else v


def turn(x_screen, y_screen):
    """The root's rotation: the matrix whose rows are the file's directions for glTF's X, Y and Z."""
    x, y = axis(x_screen), axis(y_screen)
    return quaternion([x, y, np.cross(x, y)])


Z_UP = turn("+X", "+Z")
assert np.allclose(Z_UP, [-math.sqrt(0.5), 0, 0, math.sqrt(0.5)])


class Writer:
    """Numbers in a processor's byte order."""

    def __init__(self, proc):
        self.proc = proc
        self.e = ">" if proc == "MIPS" else "<"

    def u16(self, v):
        return struct.pack(self.e + "H", v & 0xFFFF)

    def i16(self, v):
        return struct.pack(self.e + "h", v)

    def f32(self, v):
        if self.proc == "DEC":
            a = struct.pack("<f", v * 4.0)
            return a[2:4] + a[0:2]
        return struct.pack(self.e + "f", v)


def chars(strings):
    """A character parameter's type, dimensions and data: each string padded to the longest."""
    n = max([len(s) for s in strings] + [1])
    return -1, [n, len(strings)], b"".join(s.encode("latin-1").ljust(n) for s in strings)


def text(s):
    return -1, [len(s)], s.encode("latin-1")


def ints(w, values, dims=None):
    return 2, (dims if dims is not None else ([len(values)] if len(values) != 1 else [])), b"".join(
        w.u16(v) for v in values)


def floats(w, values):
    return 4, ([len(values)] if len(values) != 1 else []), b"".join(w.f32(v) for v in values)


def build(proc="Intel", labels=(), frames=(), scale=0.1, rate=100.0, params=None, header=None, analog=None,
          descriptions=None, param_block=2, groups_only=False):
    """A C3D file. `frames[f][m]` is a marker sample (x, y, z) or None for missing; `params` maps "GROUP:NAME" to a
    (type, dims, data) triple, added after POINT:USED, LABELS and DESCRIPTIONS; `header` overrides header words;
    `analog` is a list per frame of 16-bit analog values stored after the markers."""
    w = Writer(proc)
    points = len(frames[0]) if frames else len(labels)
    p = {"POINT:USED": ints(w, [points])}
    if labels:
        p["POINT:LABELS"] = chars(list(labels))
    if descriptions:
        p["POINT:DESCRIPTIONS"] = chars(list(descriptions))
    p.update(params or {})
    group_ids = {}
    for key in p:
        g = key.split(":")[0]
        group_ids.setdefault(g, len(group_ids) + 1)
    body = bytearray([1, 0x50, 0, PROC.get(proc, proc if isinstance(proc, int) else 84)])
    records = []
    for g, gid in group_ids.items():
        records.append((-gid, g, bytes([0])))
    for key, (kind, dims, data) in p.items():
        g, name = key.split(":")
        rec = struct.pack("bB", kind, len(dims)) + bytes(dims) + data + bytes([0])
        records.append((group_ids[g], name, rec))
    for k, (rid, name, rec) in enumerate(records):
        last = k == len(records) - 1
        body += struct.pack("bb", len(name), rid) + name.encode() + w.u16(0 if last else len(rec) + 2) + rec
    blocks = -(-len(body) // BLOCK)
    body[2] = blocks
    body += bytes(blocks * BLOCK - len(body))
    data_block = param_block + blocks
    analog_words = len(analog[0]) if analog else 0
    words = {2: points, 3: analog_words, 4: 1, 5: len(frames), 9: data_block}
    words.update({k: v for k, v in (header or {}).items() if isinstance(k, int)})
    head = bytearray(BLOCK)
    head[0], head[1] = param_block, 0x50
    for k, v in words.items():
        head[(k - 1) * 2:k * 2] = w.u16(v)
    sc = (header or {}).get("scale", scale)
    head[12:16] = w.f32(sc)
    head[20:24] = w.f32((header or {}).get("rate", rate))
    data = bytearray()
    for f, frame in enumerate(frames):
        for s in frame:
            if scale < 0:
                v = [0.0, 0.0, 0.0, -1.0] if s is None else [s[0], s[1], s[2], 0.0]
                data += b"".join(w.f32(c) for c in v)
            else:
                v = [0, 0, 0, -1] if s is None else [round(c / scale) for c in s] + [0]
                data += b"".join(w.i16(c) for c in v)
        if analog:
            data += b"".join(w.i16(c) for c in analog[f])
    data += bytes(-len(data) % BLOCK or (BLOCK if not data else 0))
    pad = bytes((param_block - 2) * BLOCK)
    gap = bytes(max(0, (data_block - 1) * BLOCK - (BLOCK + len(pad) + len(body))))
    return bytes(head) + pad + bytes(body) + gap + bytes(data)


def stored(s, scale):
    """A sample as the file holds it, read back: integers times the scale, floats as single precision."""
    if s is None:
        return None
    if scale < 0:
        return [struct.unpack("<f", struct.pack("<f", c))[0] for c in s]
    return [round(c / scale) * struct.unpack("<f", struct.pack("<f", scale))[0] for c in s]


def expect(spec, labels, frames, scale=0.1, rate=100.0, meters=0.001, root=Z_UP, extra=(), facts=None,
           rate_given=True, names=None, **more):
    points = len(frames[0]) if frames else len(labels)
    names = names or [labels[m] if m < len(labels) and labels[m] else f"marker{m + 1}" for m in range(points)]
    rig = [{"node": "markers", "parent": None, "translation": [0, 0, 0], "rotation": root}]
    channels = 0
    missing = never = 0
    for m in range(points):
        samples = [stored(f[m], scale) for f in frames]
        seen = [(k, s) for k, s in enumerate(samples) if s is not None]
        missing += len(samples) - len(seen)
        entry = {"node": names[m], "parent": "markers", "rotation": [0, 0, 0, 1]}
        if seen:
            channels += 1
            entry["translation"] = [r(c * meters) for c in seen[0][1]]
            rig.append(entry)
            rig.append({"node": names[m], "keys": {"translation": [r(k / rate, 9) for k, _ in seen]}})
            for k, s in seen:
                rig.append({"node": names[m], "time": r(k / rate, 9), "translation": [r(c * meters) for c in s]})
        else:
            never += 1
            entry["translation"] = [0, 0, 0]
            rig.append(entry)
            rig.append({"node": names[m], "keys": {"translation": None}})
    f = {"markers": points, "frames": len(frames)}
    if missing:
        f["missing_samples"] = missing
    if never:
        f["markers_never_seen"] = never
    f.update(facts or {})
    f = {k: v for k, v in f.items() if v is not None}
    e = {
        "spec": SPEC + ": " + spec,
        "source": SRC,
        "no_mesh": True,
        "facts": f,
        "document": {"nodes": points + 1, "animations": 1 if channels else 0, "channels": channels,
                     "node_names": ["markers"] + names},
        "json": {"/asset/extras/source/format": "C3D", "/asset/extras/source/frameRate": rate,
                 "/asset/extras/source/metersPerUnit": meters, "/scenes/0/nodes": [0]},
        "rig": rig + list(extra),
    }
    if channels:
        e["json"]["/animations/0/name"] = "motion"
        e["json"]["/animations/0/samplers/0/interpolation"] = "LINEAR"
    else:
        e["json"]["/animations"] = None
    for k, v in more.items():
        if isinstance(v, dict) and isinstance(e.get(k), dict):
            e[k].update(v)
        else:
            e[k] = v
    return e


