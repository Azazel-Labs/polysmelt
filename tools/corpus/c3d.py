"""C3D conformance cases: biomechanics motion capture as the C3D file format user guide (c3d.org) defines it. A file
is 512-byte blocks: a header (its first byte the parameter block, its second 0x50; then the marker count, analog
values per frame, first and last frame, scale, data block and frame rate as 16-bit words and floats), a parameter
section (groups and parameters, each record a name, an id, an offset to the next record, and a type, dimensions and
values), then the frames: X, Y, Z and a residual per marker, 16-bit integers times the scale, or floats when the scale
is negative. The parameter section's fourth byte names the processor: 84 Intel (little-endian IEEE), 85 DEC (DEC
floats: 16-bit halves swapped, four times too big) or 86 MIPS (big-endian IEEE). A negative residual marks a sample
missing.

The document is a `markers` root and a node per marker, named from `POINT:LABELS`, each at its first sample, its
track a linear translation channel keyed at the frames where it isn't missing. Lengths become meters by
`POINT:UNITS`. The root turns `POINT:Y_SCREEN` to glTF's +Y and `POINT:X_SCREEN` to +X; without them the capture is
taken to be Z up. The expected root quaternions come from the rotation matrix whose rows are the screen axes,
converted with numpy, not from the reader's code.
"""

