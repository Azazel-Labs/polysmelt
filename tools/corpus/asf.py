def bad(name, spec, text, error, files=None, file=None, kind=None):
    e = {"spec": SPEC + ": " + spec, "source": SRC, "error": error, "error_kind": kind}
    if file:
        e["file"] = file
    case(FMT, name, files or {f"{name}.asf": text}, e)


