def matrix(axis, degrees):
    """The rotation by `degrees` about axis 0, 1 or 2, for column vectors."""
    a = math.radians(degrees)
    c, s = math.cos(a), math.sin(a)
    if axis == 0:
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    if axis == 1:
        return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def quaternion(m):
    """The unit quaternion [x, y, z, w] of rotation matrix `m` (Shepperd's method)."""
    t = np.trace(m)
    if t > 0:
        s = math.sqrt(t + 1.0) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, 0.25 * s]
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = [0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s]
    elif m[1, 1] > m[2, 2]:
        s = math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = [(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s]
    else:
        s = math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = [(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s]
    return [r(float(c)) for c in q]


def euler(angles, order):
    """Rotations about the axes in `order` (indices), each by angles[axis] degrees, the first listed applied first."""
    m = np.eye(3)
    for a in order:
        m = matrix(a, angles[a]) @ m
    return m


def num(v):
    return f"{v:.6f}".rstrip("0").rstrip(".") if v != int(v) else str(int(v))


class Bone:
    def __init__(self, name, direction, length, axis=(0, 0, 0), order="XYZ", dof=(), limits=None, id=None):
        self.name, self.length, self.axis, self.order = name, length, list(axis), order
        d = np.array(direction, dtype=float)
        self.raw = list(direction)
        self.direction = d / np.linalg.norm(d)
        self.dof, self.limits, self.id = list(dof), limits, id


class Skeleton:
    def __init__(self, bones, hierarchy, length=1.0, angle="deg", order="TX TY TZ RX RY RZ", root_axis="XYZ",
                 position=(0, 0, 0), orientation=(0, 0, 0), mass=1.0, name="test"):
        self.bones, self.hierarchy = bones, hierarchy
        self.length, self.angle, self.order, self.root_axis = length, angle, order.split(), root_axis
        self.position, self.orientation, self.mass, self.name = list(position), list(orientation), mass, name
        self.by_name = {b.name: b for b in bones}

    @property
    def scale(self):
        return 0.0254 / self.length

    def deg(self, v):
        """An angle as the skeleton writes it, in degrees."""
        return math.degrees(v) if self.angle == "rad" else v

    def text(self, nl="\n"):
        lines = [":version 1.10", f":name {self.name}", ":units", f"  mass {num(self.mass)}",
                 f"  length {num(self.length)}", f"  angle {self.angle}", ":documentation", "  made for a test", ":root",
                 f"  order {' '.join(self.order)}", f"  axis {self.root_axis}",
                 f"  position {' '.join(num(v) for v in self.position)}",
                 f"  orientation {' '.join(num(v) for v in self.orientation)}", ":bonedata"]
        for i, b in enumerate(self.bones):
            lines.append("  begin")
            lines.append(f"     id {b.id if b.id is not None else i + 1}")
            lines.append(f"     name {b.name}")
            lines.append(f"     direction {' '.join(num(v) for v in b.raw)}")
            lines.append(f"     length {num(b.length)}")
            lines.append(f"     axis {' '.join(num(v) for v in b.axis)} {b.order}")
            if b.dof:
                lines.append(f"    dof {' '.join(b.dof)}")
                pairs = b.limits or [(-180, 180)] * len(b.dof)
                for k, (lo, hi) in enumerate(pairs):
                    lines.append(("    limits " if k == 0 else "           ") + f"({lo} {hi})")
            lines.append("  end")
        lines.append(":hierarchy")
        lines.append("  begin")
        for parent, kids in self.hierarchy:
            lines.append(f"    {parent} {' '.join(kids)}")
        lines.append("  end")
        return nl.join(lines) + nl

    def nodes(self):
        """(name, parent, translation in the file's units, bone or None) in the order a walk from the root meets them."""
        parent, children, top = {}, {b.name: [] for b in self.bones}, []
        for p, kids in self.hierarchy:
            for k in kids:
                if k in parent or k not in self.by_name or (p != "root" and p not in self.by_name) or k == p:
                    continue
                parent[k] = p
                (top if p == "root" else children[p]).append(k)
        out = [("root", None, self.position, None)]
        seen = set()
        unattached = 0

        def walk(name, under, at):
            if name in seen:
                return
            seen.add(name)
            b = self.by_name[name]
            out.append((name, under, at, b))
            tip = list(b.direction * b.length)
            if not children[name]:
                out.append((name + "_end", name, tip, None))
            for c in children[name]:
                walk(c, name, tip)

        for c in top:
            walk(c, "root", [0, 0, 0])
        for b in self.bones:
            if b.name not in seen:
                unattached += 1
                walk(b.name, "root", [0, 0, 0])
        return out, unattached


def frame_of(sk, b):
    """C: the rotation a bone's (or the root's) axes make with the world's."""
    if b is None:
        return euler([sk.deg(v) for v in sk.orientation], [AXIS[c] for c in sk.root_axis.lower()])
    return euler([sk.deg(v) for v in b.axis], [AXIS[c] for c in b.order.lower()])


def pose(sk, name, values, motion_deg=True):
    """The (translation in the file's unit, quaternion) a motion line's values give a bone, or None for a path it
    doesn't move."""
    nodes, _ = sk.nodes()
    rest = next(n for n in nodes if n[0] == name)[2]
    b = None if name == "root" else sk.by_name[name]
    dofs = sk.order if b is None else b.dof
    c = frame_of(sk, b)
    m = np.eye(3)
    t = [0.0, 0.0, 0.0] if b else list(rest)
    rotates = translates = False
    for d, v in zip(dofs, values):
        d = d.lower()
        if d[0] == "r":
            m = matrix(AXIS[d[1]], v if motion_deg else math.degrees(v)) @ m
            rotates = True
        elif d[0] == "t":
            t[AXIS[d[1]]] = v
            translates = True
    q = quaternion(c @ m @ c.T) if rotates else None
    if translates and b is not None:
        t = list(np.array(rest) + c @ np.array(t))
    return ([r(v) for v in t] if translates else None), q


def amc(frames, header=(":FULLY-SPECIFIED", ":DEGREES"), oml=None, nl="\n"):
    """An AMC file: `frames` is a list of [(bone, values)] lines."""
    lines = []
    if oml:
        lines.append(f"#!OML:ASF {oml}")
    lines.append("#!made for a test")
    lines.extend(header)
    for k, frame in enumerate(frames):
        lines.append(str(k + 1))
        for name, values in frame:
            lines.append(name + " " + " ".join(num(v) for v in values))
    return nl.join(lines) + nl


def expect(spec, sk, extra=(), motion=None, frame_time=None, amc_file=None, facts=None, **more):
    nodes, unattached = sk.nodes()
    f = {"bones": len(sk.bones), "channels": len(sk.order) + sum(len(b.dof) for b in sk.bones)}
    lengths = sum(1 for b in sk.bones if "l" in [d.lower() for d in b.dof])
    if lengths:
        f["length_dofs_dropped"] = lengths
    if unattached:
        f["unattached_bones"] = unattached
    if motion is not None:
        f["frames"] = len(motion)
    f.update(facts or {})
    e = {
        "spec": SPEC + ": " + spec,
        "source": SRC,
        "no_mesh": True,
        "facts": f,
        "document": {"nodes": len(nodes) + 1, "node_names": [n[0] for n in nodes] + [ROOT_NODE]},
        "json": {"/asset/extras/source/format": "AMC" if amc_file else "ASF", "/asset/extras/source/upAxis": "+Y",
                 # The root node is the last node, and the only one the scene lists; it scales the unit to meters.
                 "/asset/extras/source/metersPerUnit": sk.scale, "/scenes/0/nodes": [len(nodes)],
                 f"/nodes/{len(nodes)}/children": [0],
                 "/asset/extras/source/converted": None if abs(sk.scale - 1) < 1e-12 else ["units"]},
        "rig": [{"node": ROOT_NODE, "parent": None, "translation": [0, 0, 0], "rotation": [0, 0, 0, 1],
                 "scale": [r(sk.scale, 9)] * 3},
                {"node": "root", "world": [r(v * sk.scale) for v in nodes[0][2]]}]
        + [{"node": n, "parent": p or ROOT_NODE, "translation": [r(v) for v in t], "rotation": [0, 0, 0, 1],
            "scale": [1, 1, 1]} for n, p, t, _ in nodes],
    }
    if amc_file:
        e["file"] = amc_file
    if motion is None:
        e["json"]["/animations"] = None
        e["json"]["/asset/extras/source/frameRate"] = None
        e["document"]["animations"] = 0
    else:
        e["json"]["/asset/extras/source/frameRate"] = 1 / frame_time if frame_time else 120.0
        e["json"]["/asset/extras/source/assumed"] = ["upAxis"] if frame_time else ["upAxis", "frameRate"]
    e["rig"] += list(extra)
    for k, v in more.items():
        if isinstance(v, dict) and isinstance(e.get(k), dict):
            e[k].update(v)
        else:
            e[k] = v
    return e


def posed(sk, frames, k, name, frame_time=1 / 120, motion_deg=True):
    values = next(v for n, v in frames[k] if n == name)
    t, q = pose(sk, name, values, motion_deg)
    e = {"node": name, "time": r(k * frame_time, 9)}
    if t is not None:
        e["translation"] = t
    if q is not None:
        e["rotation"] = q
    return e


