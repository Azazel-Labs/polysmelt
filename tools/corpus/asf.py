def body(length=0.45, angle="deg"):
    a = (lambda v: math.radians(v)) if angle == "rad" else (lambda v: v)
    bones = [
        Bone("lhipjoint", [0.6, -0.8, 0], 2.5, [0, 0, a(53.13)], "XYZ", []),
        Bone("lfemur", [0.34, -0.94, 0], 7.0, [0, 0, a(20)], "XYZ", ["rx", "ry", "rz"],
             [(-160, 20), (-70, 70), (-60, 70)]),
        Bone("ltibia", [0.34, -0.94, 0], 7.2, [0, 0, a(20)], "XYZ", ["rx"], [(-10, 170)]),
        Bone("lowerback", [0, 1, 0], 2.0, [0, 0, 0], "XYZ", ["rx", "ry", "rz"]),
        Bone("head", [0, 1, 0.1], 3.0, [a(10), a(-20), a(30)], "ZYX", ["rz", "rx"]),
    ]
    hier = [("root", ["lhipjoint", "lowerback"]), ("lhipjoint", ["lfemur"]), ("lfemur", ["ltibia"]),
            ("lowerback", ["head"])]
    return Skeleton(bones, hier, length=length, angle=angle, position=(0, 0, 0), orientation=(0, 0, 0))


