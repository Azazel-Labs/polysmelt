"""ASF/AMC conformance cases: Acclaim motion capture as the format's description (Acclaim's "ASF/AMC File Format"
notes, and Lander's "Working with Motion Capture File Formats") and the CMU motion capture collection write it. An
ASF file is the skeleton: `:units`, `:root`, `:bonedata` (a begin … end block per bone with its direction, length,
axis and dofs) and `:hierarchy`. An AMC file is a motion for one ASF: a frame number, then a line per bone with a
value per dof.

The document is the skeleton as nodes: `root`, then each bone where it starts (its parent's direction times length),
a `<bone>_end` node closing each chain, every rotation the identity at rest. A bone's rotation at a frame is
C·M·C⁻¹, where C is the rotation its `axis` angles make in their listed order and M the product of its dof rotations
in theirs (`rx ry rz` is Rz·Ry·Rx on column vectors). Lengths stay in the file's unit, which is an inch divided by
`:units length`: the `RootNode` every reader makes, over `root`, scales them to meters. The expected quaternions here come from multiplying 3×3 rotation matrices with numpy and converting the
product, not from the quaternion products the reader uses.
"""

