def ply(fmt, elements, comments=(), nl="\n"):
    """`elements`: list of (name, props, rows). A prop is (type, name) or ("list", count_type,
    item_type, name); a row is a list of values, a list prop's value being a list."""
    h = ["ply", f"format {fmt} 1.0", *comments]
    for name, props, rows in elements:
        h.append(f"element {name} {len(rows)}")
        for p in props:
            h.append("property " + " ".join(p))
    h.append("end_header")
    out = (nl.join(h) + nl).encode("latin-1")
    if fmt == "ascii":
        lines = []
        for _, props, rows in elements:
            for row in rows:
                words = []
                for p, v in zip(props, row):
                    if p[0] == "list":
                        words += [str(len(v))] + [str(x) for x in v]
                    else:
                        words.append(str(v))
                lines.append(" ".join(words))
        return out + (nl.join(lines) + nl).encode()
    e = "<" if fmt == "binary_little_endian" else ">"
    for _, props, rows in elements:
        for row in rows:
            for p, v in zip(props, row):
                if p[0] == "list":
                    out += struct.pack(e + PACK[p[1]], len(v))
                    out += b"".join(struct.pack(e + PACK[p[2]], x) for x in v)
                else:
                    out += struct.pack(e + PACK[p[0]], v)
    return out


