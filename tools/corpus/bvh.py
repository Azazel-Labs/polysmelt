"""BVH conformance cases: Biovision Hierarchy motion capture as the format's description (Meredith and Maddock,
"Motion Capture File Formats Explained") and real exporters write it. The HIERARCHY section nests ROOT and JOINT
blocks with an OFFSET and CHANNELS each, End Sites closing the chains; the MOTION section gives the frame count, the
frame time and a row of channel values per frame.

The document is the skeleton as nodes (an End Site named `<joint>_end`) and the motion as one linear animation. The
rest pose is the hierarchy's: OFFSET translations, identity rotations. A joint's rotation at a frame is the product of
its axis rotations in the order CHANNELS lists them, applied to column vectors (ZXY is Rz·Rx·Ry), and position
channels replace the OFFSET's components, and scale channels set a scale whose other axes stay 1. The expected
quaternions here come from multiplying 3×3 rotation matrices
with numpy and converting the product, not from the quaternion product the reader uses.
"""

