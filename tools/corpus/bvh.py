def matrix(axis, degrees):
    """The rotation by `degrees` about `axis`, for column vectors."""
    a = math.radians(degrees)
    c, s = math.cos(a), math.sin(a)
    if axis == "X":
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    if axis == "Y":
        return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def quaternion(m):
    """The unit quaternion [x, y, z, w] of rotation matrix `m` (Shepperd's method)."""
    t = np.trace(m)
    if t > 0:
        s = math.sqrt(t + 1.0) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, 0.25 * s]
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = [0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s]
    elif m[1, 1] > m[2, 2]:
        s = math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = [(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s]
    else:
        s = math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = [(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s]
    return [float(c) for c in q]


def slerp(a, b, s):
    """Spherical interpolation from unit quaternion `a` to `b`, the short way."""
    a, b = np.array(a), np.array(b)
    d = float(np.dot(a, b))
    if d < 0:
        b, d = -b, -d
    if d > 0.9995:
        q = a + (b - a) * s
    else:
        th = math.acos(d)
        q = (math.sin((1 - s) * th) * a + math.sin(s * th) * b) / math.sin(th)
    return [float(c) for c in q / np.linalg.norm(q)]


def num(v):
    """A channel value as a file writes it."""
    return f"{v:.4f}".rstrip("0").rstrip(".") if v != int(v) else str(int(v))


class Joint:
    """A ROOT or JOINT: `children` holds Joints and End Site offsets (3-tuples)."""

    def __init__(self, name, offset, channels, children=()):
        self.name, self.offset, self.channels, self.children = name, list(offset), list(channels), list(children)


def nodes_of(roots):
    """(name, parent name, offset, joint or None) for each node in file order: a joint, then what it holds."""
    out = []
    stack = [(j, None) for j in reversed(roots)]
    while stack:
        j, parent = stack.pop()
        if isinstance(j, Joint):
            out.append((j.name, parent, j.offset, j))
            stack.extend((c, j.name) for c in reversed(j.children))
        else:
            out.append((parent + "_end", parent, list(j), None))
    return out


def hierarchy(roots, end="End Site", indent="  ", nl="\n"):
    lines = ["HIERARCHY"]

    def emit(j, depth, keyword):
        pad = indent * depth
        if isinstance(j, Joint):
            lines.append(f"{pad}{keyword} {j.name}")
        else:
            lines.append(f"{pad}{end}")
        lines.append(pad + "{")
        off = j.offset if isinstance(j, Joint) else j
        lines.append(f"{pad}{indent}OFFSET {' '.join(num(v) for v in off)}")
        if isinstance(j, Joint):
            if j.channels:
                lines.append(f"{pad}{indent}CHANNELS {len(j.channels)} {' '.join(j.channels)}")
            for c in j.children:
                emit(c, depth + 1, "JOINT")
        lines.append(pad + "}")

    for root in roots:
        emit(root, 0, "ROOT")
    return nl.join(lines) + nl


def columns(roots):
    """(joint, channel) for each motion column, in hierarchy order."""
    return [(j, c) for _, _, _, j in nodes_of(roots) if j for c in j.channels]


def motion(rows, frame_time, nl="\n"):
    text = f"MOTION{nl}Frames: {len(rows)}{nl}Frame Time: {frame_time}{nl}"
    return text + "".join(" ".join(num(v) for v in row) + nl for row in rows)


def kind(channel):
    """What a channel name sets, in any case: position (or translation), rotation, scale (or scaling), or None."""
    rest = channel[1:].lower()
    kinds = {"position": "position", "translation": "position", "rotation": "rotation", "scale": "scale",
             "scaling": "scale"}
    return kinds.get(rest) if channel[:1].upper() in AXIS else None


def pose(roots, row):
    """Each joint's (translation, quaternion, scale) at a row, by name, from the values as written."""
    out = {}
    cols = columns(roots)
    for _, _, offset, j in nodes_of(roots):
        if not j:
            continue
        t = list(offset)
        s = [1.0, 1.0, 1.0]
        m = np.eye(3)
        for (jj, c), v in zip(cols, row):
            if jj is not j:
                continue
            v = float(num(v))
            k, axis = kind(c), c[:1].upper()
            if k == "position":
                t[AXIS[axis]] = v
            elif k == "rotation":
                m = m @ matrix(axis, v)
            elif k == "scale":
                s[AXIS[axis]] = v
        out[j.name] = (t, quaternion(m), s)
    return out


def rq(q):
    return [r(c) for c in q]


def rest(name, parent, offset):
    """A rig entry for a node at rest: its offset, unrotated."""
    return {"node": name, "parent": parent, "translation": [r(v) for v in offset], "rotation": [0, 0, 0, 1],
            "scale": [1, 1, 1]}


def posed(roots, rows, frame, frame_time, name, *, rotation=True, translation=True, scale=False):
    t, q, s = pose(roots, rows[frame])[name]
    e = {"node": name, "time": frame * frame_time}
    if translation:
        e["translation"] = [r(v) for v in t]
    if rotation:
        e["rotation"] = rq(q)
    if scale:
        e["scale"] = [r(v) for v in s]
    return e


def expect(spec, roots, rows, frame_time, extra=None, **more):
    """The usual expectations of a case that reads: node and channel counts, facts, the rest pose."""
    nodes = nodes_of(roots)
    joints = [n for n in nodes if n[3]]
    channels = sum(len(j.channels) for *_, j in joints)
    anim = 0
    if rows:
        for *_, j in joints:
            anim += len({kind(c) for c in j.channels} - {None})
    facts = {"joints": len(joints), "channels": channels}
    if rows is not None:
        facts["frames"] = len(rows)
    e = {
        "spec": SPEC + ": " + spec,
        "source": SRC,
        "no_mesh": True,
        "facts": facts,
        "document": {"nodes": len(nodes), "animations": 1 if anim else 0, "channels": anim,
                     "node_names": [n[0] for n in nodes]},
        "json": {"/asset/extras/source/format": "BVH", "/scenes/0/nodes": [i for i, n in enumerate(nodes) if n[1] is None]},
        "rig": [rest(n, p, o) for n, p, o, _ in nodes],
    }
    if rows is not None:
        e["json"]["/asset/extras/source/frameRate"] = 1 / frame_time
        e["json"]["/asset/extras/source/assumed"] = ["upAxis"]
    if anim:
        e["json"]["/animations/0/name"] = "motion"
        e["json"]["/animations/0/samplers/0/interpolation"] = "LINEAR"
    if extra:
        e["rig"] += extra
    e.update(more)
    return e


def write(name, spec, roots, rows, frame_time=0.04, extra=None, text=None, **more):
    body = text if text is not None else hierarchy(roots) + (motion(rows, frame_time) if rows is not None else "")
    case(FMT, name, {f"{name}.bvh": body}, expect(spec, roots, rows, frame_time, extra, **more))


