def polyface(extra=""):
    s = f"0 POLYLINE 8 Box 66 1 70 64 71 8 72 6 {extra} "
    for p in CUBE_V:
        s += f"0 VERTEX 8 Box 10 {p[0]} 20 {p[1]} 30 {p[2]} 70 192 "
    for i, q in enumerate(QUADS):
        sign = "-" if i % 2 else ""  # a negative corner hides its edge
        s += f"0 VERTEX 8 Box 10 0 20 0 30 0 70 128 71 {sign}{q[0] + 1} 72 {q[1] + 1} 73 {q[2] + 1} 74 {q[3] + 1} "
    return s + "0 SEQEND "


