def groups(s):
    """Groups written as space-separated codes and values."""
    w = s.split()
    return [(int(w[i]), w[i + 1]) for i in range(0, len(w), 2)]


def drawing(units, entities, tables="", blocks="", version="AC1027", eof=True):
    s = f"0 SECTION 2 HEADER 9 $ACADVER 1 {version} 9 $INSUNITS 70 {units} 0 ENDSEC "
    if tables:
        s += f"0 SECTION 2 TABLES 0 TABLE 2 LAYER {tables} 0 ENDTAB 0 ENDSEC "
    if blocks:
        s += f"0 SECTION 2 BLOCKS {blocks} 0 ENDSEC "
    s += f"0 SECTION 2 ENTITIES {entities} 0 ENDSEC "
    if eof:
        s += "0 EOF"
    return groups(s)


def text(gs, eol="\n"):
    return "".join(f"{c:>3}{eol}{v}{eol}" for c, v in gs)


def kind(code):
    if 10 <= code <= 59 or 110 <= code <= 149 or 210 <= code <= 239:
        return "<d"
    if 60 <= code <= 79 or 270 <= code <= 289 or 370 <= code <= 389:
        return "<h"
    if 90 <= code <= 99 or 420 <= code <= 429:
        return "<i"
    return None


def binary(gs):
    out = b"AutoCAD Binary DXF\r\n\x1a\0"
    for c, v in gs:
        out += struct.pack("<h", c)
        k = kind(c)
        out += struct.pack(k, float(v) if k == "<d" else int(v)) if k else v.encode() + b"\0"
    return out


def face(extra, pts):
    s = f"0 3DFACE {extra} "
    for k, p in enumerate(pts):
        s += f"1{k} {p[0]:g} 2{k} {p[1]:g} 3{k} {p[2]:g} "
    return s


def cube_faces(extra="8 0", size=1, at=(0, 0, 0)):
    return "".join(face(extra, [[c * size + o for c, o in zip(CUBE_V[i], at)] for i in q]) for q in QUADS)


def y_up(lo, hi, scale=1.0):
    """Z-up bounds to glTF's: (x, y, z) becomes (x, z, -y)."""
    return {"min": [r(lo[0] * scale), r(lo[2] * scale), r(-hi[1] * scale)],
            "max": [r(hi[0] * scale), r(hi[2] * scale), r(-lo[1] * scale)]}


def lin(rgb):
    return [r(srgb_to_linear(((rgb >> s) & 0xFF) / 255)) for s in (16, 8, 0)] + [1]


