def polygon_mesh(m, n, flags, point):
    s = f"0 POLYLINE 8 0 66 1 70 {16 | flags} 71 {m} 72 {n} "
    for i in range(m):
        for j in range(n):
            x, y, z = point(i, j)
            s += f"0 VERTEX 10 {x:g} 20 {y:g} 30 {z:g} 70 64 "
    return s + "0 SEQEND "


