# Objects and transforms.
def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def unit(a):
    n = math.sqrt(sum(c * c for c in a))
    return [c / n for c in a]


def xform(forward, up, position, scale):
    """The matrix of a <TRANSFORM>: columns up x forward, up, forward, times the scale, then the position."""
    z, y = unit(forward), unit(up)
    x = cross(y, z)
    return [[x[i] * scale, y[i] * scale, z[i] * scale, position[i]] for i in range(3)] + [[0, 0, 0, 1]]


def apply(m, p):
    return [m[i][0] * p[0] + m[i][1] * p[1] + m[i][2] * p[2] + m[i][3] for i in range(3)]


def matmul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)] for i in range(4)]


def transform(forward, up, position, scale):
    return (f"<TRANSFORM>\n<FORWARD>{v3(forward)}</FORWARD>\n<UP>{v3(up)}</UP>\n<POSITION>{v3(position)}</POSITION>\n"
            f"<SCALE>{g(scale)}</SCALE>\n</TRANSFORM>\n")


def obj(name, *parts):
    return f"<OBJECT>\n<NAME>{name}</NAME>\n" + "".join(parts) + "</OBJECT>\n"


