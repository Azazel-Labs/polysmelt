def read_xgl(text):
    """Every face's placed points: meshes by ID, placed by MESHREFs inside objects with their transforms."""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    tags = re.findall(r"<(/?)(\w+)([^>]*)>([^<]*)", text)
    # A tiny tree of (tag, id, text, children).
    root = ["root", None, "", []]
    stack = [root]
    for close, tag, attr, body in tags:
        tag = tag.lower()
        if close:
            stack.pop()
            continue
        m = re.search(r'id\s*=\s*"([^"]*)"', attr, re.I)
        el = [tag, m.group(1).strip() if m else None, body.strip(), []]
        stack[-1][3].append(el)
        if not attr.rstrip().endswith("/"):
            stack.append(el)

    def faces(mesh_el):
        pts = {c[1]: [float(x) for x in c[2].split(",")] for c in mesh_el[3] if c[0] == "p" and c[1] is not None}
        out = []

        def walk(e):
            for c in e[3]:
                if c[0] == "f":
                    out.append([pts[next(x[2] for x in fv[3] if x[0] == "pref")] for fv in c[3] if fv[0].startswith("fv")])
                elif c[0] == "patch":
                    walk(c)
        walk(mesh_el)
        return out

    world_el = root[3][0]
    defs = {}

    def collect(e):
        for c in e[3]:
            if c[0] == "mesh" and c[1] is not None:
                defs[c[1]] = faces(c)
            elif c[0] == "object":
                collect(c)
    collect(world_el)
    placed, used = [], set()

    def child(e, tag):
        return next((c for c in e[3] if c[0] == tag), None)

    def place(e, m):
        for c in e[3]:
            if c[0] == "transform":
                vec = {k: [float(x) for x in child(c, k)[2].split(",")] for k in ("forward", "up", "position")}
                s = float(child(c, "scale")[2]) if child(c, "scale") else 1.0
                m = matmul(m, xform(vec["forward"], vec["up"], vec["position"], s))
        for c in e[3]:
            if c[0] == "mesh" and c[1] is None:
                placed.extend([[apply(m, p) for p in f] for f in faces(c)])
            elif c[0] == "meshref":
                used.add(c[2])
                placed.extend([[apply(m, p) for p in f] for f in defs[c[2]]])
            elif c[0] == "object":
                place(c, m)
    identity = [[1 if i == j else 0 for j in range(4)] for i in range(4)]
    place(world_el, identity)
    for k, f in defs.items():
        if k not in used:
            placed.extend(f)
    return placed


