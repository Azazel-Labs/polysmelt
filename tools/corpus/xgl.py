def g(x):
    return f"{x:g}"


def v3(p):
    return ",".join(g(c) for c in p)


def lin(c, a=1.0):
    return [r(srgb_to_linear(x)) for x in c] + [a]


def bounds(points):
    return {"min": [r(min(p[k] for p in points)) for k in range(3)],
            "max": [r(max(p[k] for p in points)) for k in range(3)]}


def mat(id_, diff=(1, 1, 1), emiss=(0, 0, 0), spec=(0, 0, 0), shine=0, alpha=1.0):
    return (f'<MAT ID="{id_}">\n<AMB>0.2,0.2,0.2</AMB>\n<DIFF>{v3(diff)}</DIFF>\n<SPEC>{v3(spec)}</SPEC>\n'
            f"<EMISS>{v3(emiss)}</EMISS>\n<SHINE>{g(shine)}</SHINE>\n<ALPHA>{g(alpha)}</ALPHA>\n</MAT>\n")


def face(refs, matref=None):
    """`refs` are three dicts of tag -> value for <FV1> to <FV3>."""
    out = "<F>\n" + (f"<MATREF>{matref}</MATREF>\n" if matref is not None else "")
    for k, ref in enumerate(refs, 1):
        out += f"<FV{k}>" + "".join(f"<{t}>{val}</{t}>" for t, val in ref.items()) + f"</FV{k}>\n"
    return out + "</F>\n"


def cube_lists(scale=1.0):
    return ("".join(f'<P ID="{i}">{v3([c * scale for c in p])}</P>\n' for i, p in enumerate(CUBE_V))
            + "".join(f'<N ID="{i}">{v3(n)}</N>\n' for i, (_, n) in enumerate(CUBE_QUADS)))


def cube_faces(matref=lambda f: None, inline=False, scale=1.0):
    out = ""
    for f, (q, n) in enumerate(CUBE_QUADS):
        for tri in ((q[0], q[1], q[2]), (q[0], q[2], q[3])):
            if inline:
                refs = [{"P": v3([c * scale for c in CUBE_V[i]]), "N": v3(n)} for i in tri]
            else:
                refs = [{"PREF": i, "NREF": f} for i in tri]
            out += face(refs, matref(f))
    return out


def mesh(body, id_=None):
    return (f'<MESH ID="{id_}">\n' if id_ is not None else "<MESH>\n") + body + "</MESH>\n"


def world(*parts):
    return "<WORLD>\n" + "".join(parts) + "</WORLD>\n"


