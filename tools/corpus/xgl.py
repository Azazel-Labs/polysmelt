"""XGL conformance cases: the XGL file format (`.xgl`, and `.zgl`, the same XML zlib-compressed) as its
specification (XGL File Format Specification, version 1.0) defines it.

A <WORLD> holds <BACKGROUND> (<BACKCOLOR>), <LIGHTING> (<AMBIENT>, <DIRECTIONALLIGHT> with <DIRECTION>, <DIFFUSE>
and <SPECULAR>), materials (<MAT ID>: <AMB>, <DIFF>, <SPEC>, <EMISS>, <SHINE>, <ALPHA>), meshes (<MESH>) and
objects (<OBJECT>), which nest. A mesh lists points (<P ID>), normals (<N ID>) and texture coordinates (<TC ID>),
then triangles (<F>: <FV1> to <FV3>), line segments (<L>: <LV1>, <LV2>) and points (<P>: <PV1>); a vertex refers to
the lists (<PREF>, <NREF>, <TCREF>) or holds its own <P>, <N> and <TC>; a primitive takes its <MATREF> or own
<MAT>, or else its <PATCH>'s. A mesh with an ID is placed by each <MESHREF> to it. An object's <TRANSFORM> gives
<FORWARD> (its local +Z), <UP> (+Y), <POSITION> and a uniform <SCALE>; its +X is up x forward.

XGL is right-handed with Y up and triangles counterclockwise from the front, as glTF is, so nothing is converted.
Colors are sRGB. Texture coordinates run up from the image's bottom, so glTF's v is 1 - v. Shininess is a Phong
exponent (0 to 128) and SPEC the highlight's color: the classic material every reader reads one way (common.py's
`phong`). A material without them has no highlight; a face with no material takes the default one.

Also real files from assimp's test models (test/models/XGL; BSD license, see LICENSE-assimp beside the cases),
kept in their case folders (or read from the folder given as the first argument). Their expectations come from
reading them here, by the rules above.
"""

