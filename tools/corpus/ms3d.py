def weights_tail(per_vertex, sub=2, comments=False):
    """The optional parts: comments (subversion 1, empty unless `comments`), then extra weights."""
    out = struct.pack("<i", 1)
    if comments:
        text = b"a group comment"
        out += struct.pack("<iii", 1, 0, len(text)) + text
        out += struct.pack("<i", 0) + struct.pack("<i", 0)
        model = b"made by hand"
        out += struct.pack("<ii", 1, len(model)) + model
    else:
        out += struct.pack("<iiii", 0, 0, 0, 0)
    out += struct.pack("<i", sub)
    for ids, ws in per_vertex:
        out += struct.pack("<3b3B", *ids, *ws) + b"\0" * (4 * (sub - 1))
    return out


