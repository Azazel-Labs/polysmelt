"""MS3D conformance cases: MilkShape 3D binary models as the format's published structures (ms3dspec.h, version 4,
with the optional subversioned parts after the joints) lay them out, little-endian and packed.

A file is the header ("MS3D000000", version), vertices (flags, position, joint, reference count), triangles (flags,
three vertex indices, a normal per corner, s and t per corner, smoothing group, group), groups (flags, name,
triangle indices, material), materials (name, ambient, diffuse, specular, emissive, shininess 0-128, transparency,
mode, texture, alphamap), the animation's frame rate, current time and frame count, and joints (flags, name, parent
name, Euler rotation and position, then rotation and position keys of time in seconds and value). After the joints
may come comments (subversion 1) and extra weights (subversion 1-3: three more joints and three weights per vertex).

The document has one mesh, a primitive per group; materials take the diffuse color (as linear) with the
transparency as alpha; joints are nodes whose rest rotation is Rz·Ry·Rx of the Euler angles; vertices are in model
space, so each joint's inverse bind is the inverse of its rest world matrix. A rotation key is the rest rotation
followed by the key's Euler rotation (rest · key); a position key is added to the rest position. Expected poses here
come from numpy 4x4 matrices, not from the reader's quaternions. MilkShape is Y up, right-handed, as glTF is, and its
t coordinate runs down the image, as glTF's does.
"""

