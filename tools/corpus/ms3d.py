def pose(t):
    """The joints' world matrices at time t."""
    rr = euler(ROOT_ROT) @ euler(interp(ROOT_RK, t))
    rp = np.array(ROOT_POS) + interp(ROOT_PK, t)
    ar = euler(ARM_ROT) @ euler(interp(ARM_RK, t))
    root = trs(rr, rp)
    return [root, root @ trs(ar, ARM_POS)], rr, ar


def skinned(t, vertices, weights):
    worlds, _, _ = pose(t)
    out = []
    for (p, _), links in zip(vertices, weights):
        v = np.zeros(4)
        for j, w in links:
            if j is None:
                v += w * np.array([*p, 1.0])
            else:
                v += w * (worlds[j] @ np.linalg.inv(binds[j]) @ np.array([*p, 1.0]))
        out.append(v[:3])
    return out


