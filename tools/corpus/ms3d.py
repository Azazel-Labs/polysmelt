def name(s, n):
    b = s.encode("latin-1")
    assert len(b) < n
    return b + b"\0" * (n - len(b))


def build(vertices, triangles, groups, materials=None, joints=None, fps=24.0, frames=30, tail=b"", version=4):
    """The bytes of a file. `vertices` are (position, joint); `triangles` (indices, normals, uvs, group);
    `groups` (name, triangle indices, material); `materials` dicts; `joints` (name, parent, rotation, position,
    rotation keys, position keys). `materials=None` ends the file after the groups."""
    out = b"MS3D000000" + struct.pack("<i", version)
    out += struct.pack("<H", len(vertices))
    for p, j in vertices:
        out += struct.pack("<B3fbB", 0, *p, j, 1)
    out += struct.pack("<H", len(triangles))
    for idx, normals, uvs, group in triangles:
        out += struct.pack("<H3H", 0, *idx)
        for n in normals:
            out += struct.pack("<3f", *n)
        out += struct.pack("<3f", *[uv[0] for uv in uvs])
        out += struct.pack("<3f", *[uv[1] for uv in uvs])
        out += struct.pack("<BB", 1, group)
    out += struct.pack("<H", len(groups))
    for gname, tris, mat in groups:
        out += struct.pack("<B", 0) + name(gname, 32) + struct.pack("<H", len(tris))
        out += struct.pack("<%dH" % len(tris), *tris) + struct.pack("<b", mat)
    if materials is None:
        return out
    out += struct.pack("<H", len(materials))
    for m in materials:
        out += name(m["name"], 32)
        for key in ("ambient", "diffuse", "specular", "emissive"):
            out += struct.pack("<4f", *m.get(key, [0, 0, 0, 1]))
        out += struct.pack("<ffb", m.get("shininess", 0.0), m.get("transparency", 1.0), 0)
        out += name(m.get("texture", ""), 128) + name(m.get("alphamap", ""), 128)
    out += struct.pack("<ffi", fps, 0.0, frames)
    joints = joints or []
    out += struct.pack("<H", len(joints))
    for jname, parent, rot, pos, rkeys, pkeys in joints:
        out += struct.pack("<B", 0) + name(jname, 32) + name(parent, 32)
        out += struct.pack("<3f3fHH", *rot, *pos, len(rkeys), len(pkeys))
        for t, v in rkeys:
            out += struct.pack("<f3f", t, *v)
        for t, v in pkeys:
            out += struct.pack("<f3f", t, *v)
    return out + tail


def axis(a, angle):
    c, s = math.cos(angle), math.sin(angle)
    if a == 0:
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    if a == 1:
        return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def euler(e):
    """Rz·Ry·Rx: X first."""
    return axis(2, e[2]) @ axis(1, e[1]) @ axis(0, e[0])


def quaternion(m):
    """The unit quaternion [x, y, z, w] of a rotation matrix."""
    w = math.sqrt(max(0.0, 1 + m[0, 0] + m[1, 1] + m[2, 2])) / 2
    x = math.copysign(math.sqrt(max(0.0, 1 + m[0, 0] - m[1, 1] - m[2, 2])) / 2, m[2, 1] - m[1, 2])
    y = math.copysign(math.sqrt(max(0.0, 1 - m[0, 0] + m[1, 1] - m[2, 2])) / 2, m[0, 2] - m[2, 0])
    z = math.copysign(math.sqrt(max(0.0, 1 - m[0, 0] - m[1, 1] + m[2, 2])) / 2, m[1, 0] - m[0, 1])
    return [r(float(c)) for c in (x, y, z, w)]


def trs(rot, pos):
    m = np.eye(4)
    m[:3, :3] = rot
    m[:3, 3] = pos
    return m


def interp(keys, t):
    """Linear interpolation of (time, vector) keys, held past the ends."""
    if t <= keys[0][0]:
        return np.array(keys[0][1], float)
    for (t0, v0), (t1, v1) in zip(keys, keys[1:]):
        if t <= t1:
            s = (t - t0) / (t1 - t0)
            return np.array(v0, float) * (1 - s) + np.array(v1, float) * s
    return np.array(keys[-1][1], float)


def bounds(points):
    pts = np.array(points, float)
    return {"min": [r(float(c)) for c in pts.min(0)], "max": [r(float(c)) for c in pts.max(0)]}


