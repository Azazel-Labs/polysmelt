"""MMD conformance cases: MikuMikuDance models (PMX 2.0 and 2.1, PMD) and motions (VMD), laid out as the PMX 2.0/2.1
specification and the published PMD and VMD structures describe them, little-endian and packed.

A PMX file is the header ("PMX ", version, the settings: text encoding, additional UV count and six index sizes),
the model's names and comments, then vertices (position, normal, UV, additional UVs, deform, edge scale), faces,
textures, materials, bones, morphs, display frames, rigid bodies, joints and, in 2.1, soft bodies. A PMD file is
the header ("Pmd", version, name, comment), vertices, faces, materials, bones, IK, morphs (a base morph that names
the vertices, the others offsets from it), display lists, English names, toon textures and physics. A VMD file is
the header ("Vocaloid Motion Data 0002" and the model's name), bone keys (frame, move, turn and four Bezier curves),
morph keys, camera, light and shadow keys.

MMD is left-handed and Y up with a unit of 8 cm, and its front faces wind clockwise: the cases expect points with Z
negated and scaled by 0.08, rotations (x, y, z, w) as (-x, -y, z, w), and faces that wind counter-clockwise around
their normals. Expected curve values come from evaluating each Bezier curve here, by bisection on its X, and
slerping the keys, not from the reader.
"""

