def fixed(s, n):
    b = s.encode("shift_jis") if isinstance(s, str) else s
    assert len(b) <= n
    return b + b"\0" * (n - len(b))


def pmd(name, comment, vertices, faces, materials, bones, iks, morphs, english=None, toons=None):
    """The bytes of a PMD file. `vertices` are (position, normal, uv, bone0, bone1, weight of bone0 in percent);
    `materials` dicts; `bones` (name, parent, tail, type, position); `iks` (bone, target, iterations, limit, chain);
    `morphs` (name, type, offsets), the first the base."""
    out = b"Pmd" + struct.pack("<f", 1.0) + fixed(name, 20) + fixed(comment, 256)
    out += struct.pack("<I", len(vertices))
    for p, n, uv, b0, b1, wt in vertices:
        out += struct.pack("<8fHHBB", *p, *n, *uv, b0, b1, wt, 0)
    out += struct.pack("<I", 3 * len(faces))
    for t in faces:
        out += struct.pack("<3H", *t)
