class Pmx:
    """Writes a PMX file: `utf8` picks the text encoding, `size` every index size."""

    def __init__(self, utf8=False, size=2, version=2.0, add_uvs=0):
        self.utf8, self.size, self.version, self.add_uvs = utf8, size, version, add_uvs
        self.out = b"PMX " + struct.pack("<fB", version, 8)
        self.out += bytes([1 if utf8 else 0, add_uvs] + [size] * 6)

    def text(self, s):
        b = s.encode("utf-8" if self.utf8 else "utf-16-le")
        self.out += struct.pack("<i", len(b)) + b

    def idx(self, v):
        """An index of a texture, material, bone, morph or rigid body: signed."""
        self.out += struct.pack({1: "<b", 2: "<h", 4: "<i"}[self.size], v)

    def vidx(self, v):
        """A vertex index: unsigned at 1 and 2 bytes, signed at 4."""
        self.out += struct.pack({1: "<B", 2: "<H", 4: "<i"}[self.size], v)

    def f(self, *v):
        self.out += struct.pack("<%df" % len(v), *v)

    def i32(self, v):
        self.out += struct.pack("<i", v)

    def u8(self, v):
        self.out += struct.pack("<B", v)


def pmx(names, vertices, faces, textures, materials, bones, morphs, utf8=False, size=2, version=2.0, add_uvs=0,
        tail=True):
    """The bytes of a PMX file.

    `vertices` are (position, normal, uv, additional UVs, deform) with deform (type, bones, weights);
    `faces` vertex index triples, clockwise; `materials` dicts; `bones` dicts; `morphs` (name, panel, type, offsets).
    """
    w = Pmx(utf8, size, version, add_uvs)
    for s in names:
        w.text(s)
    w.i32(len(vertices))
    for pos, nor, uv, extra, (kind, bs, ws) in vertices:
        w.f(*pos, *nor, *uv)
        for a in extra:
            w.f(*a)
        w.u8(kind)
        if kind == 0:
            w.idx(bs[0])
        elif kind == 1:
            w.idx(bs[0]), w.idx(bs[1]), w.f(ws[0])
        elif kind in (2, 4):
            for b in bs:
                w.idx(b)
            w.f(*ws)
        else:  # SDEF: two bones, a weight, then C, R0 and R1.
            w.idx(bs[0]), w.idx(bs[1]), w.f(ws[0]), w.f(*[0.0] * 9)
        w.f(1.0)
    w.i32(3 * len(faces))
    for t in faces:
        for v in t:
            w.vidx(v)
    w.i32(len(textures))
    for t in textures:
        w.text(t)
    w.i32(len(materials))
    for m in materials:
        w.text(m["name"]), w.text(m.get("english", ""))
        w.f(*m["diffuse"], *m.get("specular", [0, 0, 0]), m.get("power", 0.0), *m.get("ambient", [0, 0, 0]))
        w.u8(m.get("flags", 0))
        w.f(*m.get("edge_color", [0, 0, 0, 1]), m.get("edge_size", 1.0))
        w.idx(m.get("texture", -1)), w.idx(m.get("sphere", -1)), w.u8(m.get("sphere_mode", 0))
        w.u8(1), w.u8(m.get("toon", 0))
        w.text(m.get("memo", "")), w.i32(3 * m["faces"])
    w.i32(len(bones))
    for b in bones:
        w.text(b["name"]), w.text(b.get("english", ""))
        w.f(*b["position"])
        w.idx(b.get("parent", -1))
        w.i32(0)
        flags = 0x001E | (0x0020 if "ik" in b else 0) | (0x0100 if "inherit" in b else 0)
        w.out += struct.pack("<H", flags)
        w.f(0.0, 1.0, 0.0)
        if "inherit" in b:
            w.idx(b["inherit"][0]), w.f(b["inherit"][1])
        if "ik" in b:
            target, loops, limit, links = b["ik"]
            w.idx(target), w.i32(loops), w.f(limit), w.i32(len(links))
            for bone, lim in links:
                w.idx(bone)
                w.u8(1 if lim else 0)
                if lim:
                    w.f(*lim[0], *lim[1])
    w.i32(len(morphs))
    for name, panel, kind, offsets in morphs:
        w.text(name), w.text(""), w.u8(panel), w.u8(kind), w.i32(len(offsets))
        for o in offsets:
            if kind == 0:
                w.idx(o[0]), w.f(o[1])
            elif kind == 1:
                w.vidx(o[0]), w.f(*o[1])
            elif kind == 2:
                w.idx(o[0]), w.f(*o[1], *o[2])
            elif 3 <= kind <= 7:  # UV, and additional UVs 1 to 4: a vertex and four numbers.
                w.vidx(o[0]), w.f(*o[1])
            elif kind == 8:  # Material: an operation, then each of the material's values.
                w.idx(o["material"]), w.u8(o["operation"])
                w.f(*o["diffuse"], *o["specular"], o["power"], *o["ambient"], *o["edge_color"], o["edge_size"],
                    *o["texture"], *o["sphere"], *o["toon"])
            elif kind == 9:  # Flip (2.1): morphs and ratios, as a group.
                w.idx(o[0]), w.f(o[1])
            elif kind == 10:  # Impulse (2.1): a rigid body, whether local, a velocity and a torque.
                w.idx(o[0]), w.u8(o[1]), w.f(*o[2], *o[3])
    if tail:
        w.i32(0), w.i32(0), w.i32(0)
        if version > 2.05:
            w.i32(0)
    return w.out


