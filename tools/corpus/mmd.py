def gl(p):
    """A point in glTF space: Z negated, in meters."""
    return [r(p[0] * UNIT), r(p[1] * UNIT), r(-p[2] * UNIT)]


def glq(q):
    """A rotation in glTF space."""
    return [r(-q[0]), r(-q[1]), r(q[2]), r(q[3])]


def bounds(points):
    pts = [gl(p) for p in points]
    return {"min": [min(p[k] for p in pts) for k in range(3)], "max": [max(p[k] for p in pts) for k in range(3)]}


