LINEAR = [20] * 8 + [107] * 8


def curve(rotation=None):
    """A key's 64 bytes of curves: the four X1, Y1, X2, Y2 rows of X, Y, Z and rotation, then their copies."""
    rows = list(LINEAR)
    if rotation:
        x1, y1, x2, y2 = rotation
        rows[3], rows[7], rows[11], rows[15] = x1, y1, x2, y2
    return bytes(rows * 4)


def vmd(model, bones, morphs=(), cameras=0, old=False):
    """The bytes of a VMD file. `bones` are (name, frame, position, rotation, curve bytes)."""
    if old:
        out = fixed(b"Vocaloid Motion Data file", 30) + fixed(model, 10)
    else:
        out = fixed(b"Vocaloid Motion Data 0002", 30) + fixed(model, 20)
    out += struct.pack("<I", len(bones))
    for name, frame, pos, rot, crv in bones:
        out += fixed(name, 15) + struct.pack("<I3f4f", frame, *pos, *rot) + crv
    out += struct.pack("<I", len(morphs))
    for name, frame, weight in morphs:
        out += fixed(name, 15) + struct.pack("<If", frame, weight)
    out += struct.pack("<I", cameras) + bytes(61 * cameras)
    return out


def bezier(x1, y1, x2, y2, x):
    """The curve's Y where its X is `x`, its control points in 0-127."""
    x1, y1, x2, y2 = x1 / 127, y1 / 127, x2 / 127, y2 / 127

    def at(a, b, t):
        return 3 * (1 - t) ** 2 * t * a + 3 * (1 - t) * t * t * b + t ** 3

    lo, hi = 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if at(x1, x2, mid) < x:
            lo = mid
        else:
            hi = mid
    return at(y1, y2, (lo + hi) / 2)


def slerp(a, b, t):
    dot = sum(x * y for x, y in zip(a, b))
    if dot < 0:
        b, dot = [-x for x in b], -dot
    th = math.acos(min(1.0, dot))
    if th < 1e-9:
        return list(a)
    s = math.sin(th)
    return [(math.sin((1 - t) * th) * x + math.sin(t * th) * y) / s for x, y in zip(a, b)]


def yrot(angle):
    return [0.0, math.sin(angle / 2), 0.0, math.cos(angle / 2)]


