def lzf_compress(data):
    """LZF (liblzf's format): runs of literals and back references, found greedily."""
    out, lit, i, seen = bytearray(), bytearray(), 0, {}

    def flush():
        for k in range(0, len(lit), 32):
            run = lit[k:k + 32]
            out.append(len(run) - 1)
            out.extend(run)
        lit.clear()

    while i < len(data):
        key = data[i:i + 3]
        j = seen.get(key) if len(key) == 3 else None
        seen[key] = i
        if j is not None and i - j <= 8192:
            n = 3
            while i + n < len(data) and n < 264 and data[j + n] == data[i + n]:
                n += 1
            flush()
            off = i - j - 1
            if n - 2 < 7:
                out.append(((n - 2) << 5) | (off >> 8))
            else:
                out += bytes([(7 << 5) | (off >> 8), n - 2 - 7])
            out.append(off & 0xFF)
            i += n
        else:
            lit.append(data[i])
            i += 1
    flush()
    return bytes(out)


def lzf_decompress(data, size):
    out, i = bytearray(), 0
    while i < len(data):
        c = data[i]
        i += 1
        if c < 32:
            out += data[i:i + c + 1]
            i += c + 1
        else:
            n = c >> 5
            if n == 7:
                n += data[i]
                i += 1
            back = len(out) - ((c & 0x1F) << 8) - data[i] - 1
            i += 1
            for k in range(n + 2):
                out.append(out[back + k])
    assert len(out) == size
    return bytes(out)


assert lzf_decompress(lzf_compress(bytes(range(50)) * 9 + bytes(300)), 750) == bytes(range(50)) * 9 + bytes(300)

CODE = {("F", 4): "f", ("F", 8): "d", ("U", 1): "B", ("U", 2): "H", ("U", 4): "I", ("I", 1): "b", ("I", 2): "h",
        ("I", 4): "i"}


def pcd(fields, rows, data="ascii", version="0.7", width=None, height=1, points=None, viewpoint=None,
        nl="\n"):
    """`fields` are (name, type, size, count); `rows` lists each point's values in order."""
    n = len(rows)
    head = [f"# .PCD v{version} - Point Cloud Data file format", f"VERSION {version}",
            "FIELDS " + " ".join(f[0] for f in fields), "SIZE " + " ".join(str(f[2]) for f in fields),
            "TYPE " + " ".join(f[1] for f in fields), "COUNT " + " ".join(str(f[3]) for f in fields),
            f"WIDTH {width or n}", f"HEIGHT {height}"]
    if viewpoint is not None:
        head.append("VIEWPOINT " + " ".join(f"{v:g}" for v in viewpoint))
    head += [f"POINTS {n if points is None else points}", f"DATA {data}"]
    out = (nl.join(head) + nl).encode()
    codes = "".join(CODE[(f[1], f[2])] * f[3] for f in fields)
    if data == "ascii":
        return out + "".join(" ".join(fmt_value(v) for v in row) + nl for row in rows).encode()
    if data == "binary":
        return out + b"".join(struct.pack("<" + codes, *row) for row in rows)
    cols = b"".join(struct.pack(f"<{n}{c}", *[row[k] for row in rows]) for k, c in enumerate(codes))
    packed = lzf_compress(cols)
    return out + struct.pack("<II", len(packed), len(cols)) + packed


def fmt_value(v):
    return repr(v) if isinstance(v, float) and math.isnan(v) else (f"{v:.9g}" if isinstance(v, float) else str(v))


def packed_float(rgb):
    """0x00RRGGBB as the bits of a float, as PCL writes `rgb`."""
    return struct.unpack("<f", struct.pack("<I", (rgb[0] << 16) | (rgb[1] << 8) | rgb[2]))[0]


def lin(c):
    return [r(srgb_to_linear(x / 255)) for x in c] + [1.0]


def bounds(pts):
    return {"min": [r(min(p[k] for p in pts)) for k in range(3)], "max": [r(max(p[k] for p in pts)) for k in range(3)]}


