def read_pcd(b):
    """Positions and normals of a PCD file of float fields."""
    end = b.index(b"\nDATA ") + 1
    end = b.index(b"\n", end) + 1
    head = dict(line.split(" ", 1) for line in b[:end].decode().splitlines() if line and not line.startswith("#"))
    names, n = head["FIELDS"].split(), int(head["POINTS"])
    assert set(head["TYPE"].split()) == {"F"} and set(head["SIZE"].split()) == {"4"}
    if head["DATA"] == "ascii":
        rows = [[float(v) for v in line.split()] for line in b[end:].decode().splitlines() if line.strip()]
    else:
        packed, size = struct.unpack_from("<II", b, end)
        raw = lzf_decompress(b[end + 8:end + 8 + packed], size)
        cols = [struct.unpack_from(f"<{n}f", raw, 4 * n * k) for k in range(len(names))]
        rows = [[c[i] for c in cols] for i in range(n)]
    return names, rows


