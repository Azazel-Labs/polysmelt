"""MD2 conformance cases: Quake II models as the format's published structures (qfiles.h, version 8) lay them
out, little-endian and packed.

A file is a 68-byte header ("IDP2", version, skin width and height, frame size, then the counts and offsets of
skins, texture coordinates, triangles, GL commands and frames), 64-byte skin paths, texture coordinates (s and t as
16-bit pixels), triangles (three vertex indices, three texture coordinate indices) and frames (scale, translate,
a 16-byte name, then a byte x, y, z and normal index per vertex: position = byte * scale + translate).

The document has one mesh: frame 0 is its geometry and every later frame a morph target, with a linear weights
animation per run of frames whose names match once trailing digits are taken off (stand01, stand02 make "stand"),
ten frames a second. The first skin path is the texture, found by file name next to the model. Triangles wind
clockwise seen from the front, so the reader turns them around; texture coordinates run down the image, as glTF's
do. Quake is Z up, so a point (x, y, z) lands at (x, z, -y).
"""

import struct

from common import case, fresh, png

FMT = "md2"
SRC = "generated by tools/corpus/md2.py"
SPEC = "Quake II MD2 (qfiles.h, version 8)"

fresh(FMT)

# The anorms table's straight-up normal.
UP = 5


def fixed(s, n):
    b = s.encode("latin-1")
    assert len(b) < n
    return b + b"\0" * (n - len(b))


def build(skin_size, skins, st, tris, frames, n_xyz=None, frame_size=None, header=None):
    """The bytes of a file. `tris` are (vertex indices, st indices); `frames` are (scale, translate, name,
    [(x, y, z, normal)]). `header` overrides header fields by index (0 is the version)."""
    n_xyz = len(frames[0][3]) if n_xyz is None else n_xyz
    frame_size = 40 + 4 * n_xyz if frame_size is None else frame_size
    body_skins = b"".join(fixed(s, 64) for s in skins)
    body_st = b"".join(struct.pack("<2h", *c) for c in st)
    body_tris = b"".join(struct.pack("<6H", *v, *s) for v, s in tris)
    body_frames = b""
    for scale, translate, name, verts in frames:
        f = struct.pack("<3f3f", *scale, *translate) + fixed(name, 16)
        f += b"".join(struct.pack("<4B", *v) for v in verts)
        body_frames += f.ljust(frame_size, b"\0")[: max(frame_size, len(f))]
    ofs_skins = 68
    ofs_st = ofs_skins + len(body_skins)
    ofs_tris = ofs_st + len(body_st)
    ofs_frames = ofs_tris + len(body_tris)
    ofs_end = ofs_frames + len(body_frames)
    h = [8, skin_size[0], skin_size[1], frame_size, len(skins), n_xyz, len(st), len(tris), 0, len(frames),
         ofs_skins, ofs_st, ofs_tris, ofs_frames, ofs_end, ofs_end]
    for k, v in (header or {}).items():
        h[k] = v
    return b"IDP2" + struct.pack("<16i", *h) + body_skins + body_st + body_tris + body_frames


def yup(p):
    return [p[0], p[2], -p[1]]


# A unit quad facing +Z. The file winds clockwise from the front: 0 3 2 and 0 2 1 for corners counter-clockwise
# from +Z. The second triangle gives corner 0 a texture coordinate of its own, making a fifth vertex.
CORNERS = [(0, 0, 0, UP), (2, 0, 0, UP), (2, 2, 0, UP), (0, 2, 0, UP)]
ST = [(0, 0), (8, 0), (8, 4), (0, 4), (2, 1)]
TRIS = [((0, 3, 2), (0, 3, 2)), ((0, 2, 1), (4, 2, 1))]
NAMES = ["stand01", "stand02", "run1", "run2", "run3"]


def frame(f, name):
    """Frame f: the quad 1 + f wide and 1 deep, f up."""
    return ((0.5 * (1 + f), 0.5, 1.0), (0.0, 0.0, float(f)), name, CORNERS)


def frame_bounds(width, height):
    lo = yup([0, 1, height])
    hi = yup([width, 0, height])
    return {"min": [min(a, b) for a, b in zip(lo, hi)], "max": [max(a, b) for a, b in zip(lo, hi)]}


def pose(animation, time, width, height):
    return {"animation": animation, "time": time, "bounds": frame_bounds(width, height)}


frames = [frame(f, n) for f, n in enumerate(NAMES)]
case(FMT, "morph_frame_groups", {
    "quad.md2": build((8, 4), ["players/quad/skin.png"], ST, TRIS, frames),
    "skin.png": png([200, 40, 10]),
}, {
    "spec": SPEC + ": five frames in two named runs (stand, run) as morph targets with a weights animation each; "
                   "the skin path's file found next to the model",
    "source": SRC,
    "triangles": 2,
    "vertices": 5,
    "facts": {"frames": 5, "skins": 1},
    "document": {"animations": 2, "morph_targets": 4, "channels": 2, "node_names": ["quad"]},
    "json": {
        "/animations/0/name": "stand",
        "/animations/1/name": "run",
        "/meshes/0/extras/targetNames": ["stand02", "run1", "run2", "run3"],
        "/asset/extras/source/format": "MD2",
        "/asset/extras/source/version": "8",
        "/asset/extras/source/upAxis": "+Z",
        "/asset/extras/source/frameRate": 10,
    },
    "uvs_include": [[0, 0], [1, 0], [1, 1], [0, 1], [0.25, 0.25]],
    "normals_in": [[0, 1, 0]],
    "winding_matches_normals": True,
    "bounds": frame_bounds(1, 0),
    "materials": [{"textured": True, "pixel": [200, 40, 10]}],
    "poses": [
        pose(0, 0.0, 1, 0),
        pose(0, 0.05, 1.5, 0.5),
        pose(0, 0.1, 2, 1),
        pose(1, 0.0, 3, 2),
        pose(1, 0.1, 4, 3),
        pose(1, 0.15, 4.5, 3.5),
        pose(1, 0.2, 5, 4),
    ],
})

# No skins and no texture coordinates; names that are all digits or empty fall into one run called "frames".
plain = [frame(f, n) for f, n in enumerate(["", "1", "2"])]
case(FMT, "unnamed_frames_no_skin", {
    "plain.md2": build((0, 0), [], [], [((0, 3, 2), (0, 0, 0)), ((0, 2, 1), (0, 0, 0))], plain),
}, {
    "spec": SPEC + ": no skins or texture coordinates; frames whose names are empty or digits make one run",
    "source": SRC,
    "triangles": 2,
    "vertices": 4,
    "uvs": False,
    "facts": {"frames": 3, "skins": 0},
    "document": {"animations": 1, "morph_targets": 2},
    "json": {"/animations/0/name": "frames"},
    "winding_matches_normals": True,
    "poses": [pose(0, 0.0, 1, 0), pose(0, 0.2, 3, 2)],
})

# A single frame: no targets and no animation.
case(FMT, "single_frame", {
    "still.md2": build((8, 4), ["missing.pcx"], ST, TRIS, frames[:1]),
}, {
    "spec": SPEC + ": one frame, so no morph targets or animation; a skin that isn't there leaves the material "
                   "untextured",
    "source": SRC,
    "triangles": 2,
    "uvs": True,
    "document": {"animations": 0, "morph_targets": 0},
    "materials": [{"textured": False}],
    "bounds": frame_bounds(1, 0),
})

# A loop whose last frame is the first again: that frame needs no target, only zero weights.
loop = [frame(0, "stand01"), frame(1, "stand02"), frame(0, "stand03")]
case(FMT, "loop_back_to_first_frame", {
    "loop.md2": build((8, 4), [], ST, TRIS, loop),
}, {
    "spec": SPEC + ": a frame that repeats the first makes no morph target; its key weighs every target zero",
    "source": SRC,
    "triangles": 2,
    "facts": {"frames": 3},
    "document": {"animations": 1, "morph_targets": 1},
    "json": {"/meshes/0/extras/targetNames": ["stand02"]},
    "poses": [pose(0, 0.1, 2, 1), pose(0, 0.15, 1.5, 0.5), pose(0, 0.2, 1, 0)],
})

good = build((8, 4), [], ST, TRIS, frames)


def errors(name, data, text, what):
    case(FMT, name, {name + ".md2": data}, {"spec": SPEC + ": " + what, "source": SRC, "error": text})


errors("not_md2", b"IDP3" + good[4:], "no IDP2 signature", "a file without the IDP2 signature")
errors("truncated_in_frames", good[:-30], "more than it holds", "a file cut short inside its last frame")
errors("truncated_header", good[:40], "cut short", "a file cut short inside its header")
errors("vertex_index_out_of_range",
       build((8, 4), [], ST, [((0, 3, 9), (0, 3, 2))], frames),
       "names a vertex past", "a triangle naming a vertex past the frame's")
errors("st_index_out_of_range",
       build((8, 4), [], ST, [((0, 3, 2), (0, 3, 7))], frames),
       "names a texture coordinate past", "a triangle naming a texture coordinate past the list")
errors("negative_count", build((8, 4), [], ST, TRIS, frames, header={7: -1}), "is negative",
       "a negative triangle count")
errors("frame_size_too_small", build((8, 4), [], ST, TRIS, frames, frame_size=40), "too few for",
       "frames too small for their vertices")
errors("huge_frame_count", build((8, 4), [], ST, TRIS, frames, header={9: 1 << 30}), "more than 1024",
       "a frame count far past what the file holds")
errors("no_frames", build((8, 4), [], ST, TRIS, frames, header={9: 0}), "no frames", "no frames at all")
