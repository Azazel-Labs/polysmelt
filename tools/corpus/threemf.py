def lattice(verts, beams, attrs, tris=(), more=""):
    """A mesh of `verts` and `tris` with a beam lattice: `beams` as (v1, v2, extra attributes)."""
    vs = "".join(f'<vertex x="{fmt(v[0])}" y="{fmt(v[1])}" z="{fmt(v[2])}"/>' for v in verts)
    ts = "".join(f'<triangle v1="{t[0]}" v2="{t[1]}" v3="{t[2]}"/>' for t in tris)
    bs = "".join(f'<b:beam v1="{a}" v2="{c}"{extra}/>' for a, c, extra in beams)
    return (f"<mesh><vertices>{vs}</vertices><triangles>{ts}</triangles>"
            f"<b:beamlattice{attrs}><b:beams>{bs}</b:beams>{more}</b:beamlattice></mesh>")


def gl(p, unit=1e-3):
    """A Z-up point in glTF's Y-up meters."""
    return [r(p[0] * unit, 9), r(p[2] * unit, 9), r(-p[1] * unit, 9)]


