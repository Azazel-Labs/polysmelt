"""3MF conformance cases: the 3MF Consortium's Core Specification (1.3) with its Materials and
Properties extension (1.2) and Production extension (1.1): the OPC package (relationships, case
of part names, stored or deflated entries), units, build items and their transforms (mirrors
too), components in the same model file and in others, base materials, color groups (per
triangle and blended across one), 2D textures; and the slicer projects of Bambu Studio and
PrusaSlicer (filament colors, per-part and per-volume filaments, painted triangles).

3MF is Z up in its unit (millimetres when unsaid); the expectations are in glTF's Y up and
metres: (x, y, z) becomes (x, z, -y) times the unit.
"""

