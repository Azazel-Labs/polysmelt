"""3MF conformance cases: the 3MF Consortium's Core Specification (1.3) with its Materials and
Properties extension (1.2), Production extension (1.1) and Beam Lattice extension (1.2): the OPC
package (relationships, case of part names, stored or deflated entries), units, build items and
their transforms (mirrors too), components in the same model file and in others, base materials,
color groups (per triangle and blended across one), 2D textures, beams (butt, sphere and
hemisphere caps), balls, beam sets and clipping; a volumetric level set, which has nothing to
draw; and the slicer projects of Bambu Studio and PrusaSlicer (filament colors, per-part and
per-volume filaments, painted triangles).

A beam is a frustum between its two radii closed by its caps; its section is a polygon whose
corners include the four along its axes (the curves' segments are always a multiple of four), so
a beam along an axis reaches its radius exactly there, as a sphere does at its poles and equator.

3MF is Z up in its unit (millimetres when unsaid); the expectations are in glTF's Y up and
metres: (x, y, z) becomes (x, z, -y) times the unit.
"""

