def box(lo, hi, unit=1e-3):
    """Bounds in glTF space of the Z-up box lo..hi, in a unit of `unit` metres."""
    a = [lo[0], lo[2], -hi[1]]
    b = [hi[0], hi[2], -lo[1]]
    return {"min": [r(c * unit, 9) for c in a], "max": [r(c * unit, 9) for c in b]}


CUBE = {"triangles": 12, "bounds": box((0, 0, 0), (SIZE,) * 3), "area": r(6 * (SIZE * 1e-3) ** 2, 12),
        "normals_in": AXES, "faces_outward": True, "winding_matches_normals": True}


def lin(rgb, a=255):
    return [r(srgb_to_linear(c / 255), 4) for c in rgb] + [r(a / 255, 4)]


def one_cube(**kw):
    return model(obj(1, CUBE_MESH), item(1), **kw)


