def rels(target="/3D/3dmodel.model"):
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            f' <Relationship Target="{target}" Id="rel0" '
            'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>\n'
            '</Relationships>\n')


def package(parts, compression=zipfile.ZIP_DEFLATED, root=True):
    """A zip of `parts` (name → str or bytes) with the content types and, if `root`, the
    relationship to /3D/3dmodel.model."""
    files = {"[Content_Types].xml": CONTENT_TYPES}
    if root:
        files["_rels/.rels"] = rels()
    files.update(parts)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression) as z:
        for name, data in files.items():
            # A fixed date, so the corpus regenerates byte for byte.
            z.writestr(zipfile.ZipInfo(name, (2024, 1, 1, 0, 0, 0)), data, compression)
    return buf.getvalue()


def fmt(x):
    return f"{x:g}"


def mesh(verts, tris, tri_attrs=None):
    vs = "".join(f'<vertex x="{fmt(v[0])}" y="{fmt(v[1])}" z="{fmt(v[2])}"/>' for v in verts)
    ts = ""
    for i, t in enumerate(tris):
        extra = tri_attrs(i) if tri_attrs else ""
        ts += f'<triangle v1="{t[0]}" v2="{t[1]}" v3="{t[2]}"{extra}/>'
    return f"<mesh><vertices>{vs}</vertices><triangles>{ts}</triangles></mesh>"


def model(resources, build, unit="millimeter", metadata="", ns=""):
    u = f' unit="{unit}"' if unit else ""
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<model{u} xml:lang="en-US" xmlns="{NS_CORE}"'
            f' xmlns:m="{NS_MAT}" xmlns:p="{NS_PROD}"{ns}>\n{metadata}<resources>{resources}</resources>\n'
            f'<build>{build}</build>\n</model>\n')


def obj(oid, body, attrs=""):
    return f'<object id="{oid}" type="model"{attrs}>{body}</object>'


def item(oid, transform=None, attrs=""):
    t = f' transform="{transform}"' if transform else ""
    return f'<item objectid="{oid}"{t}{attrs}/>'


# A 10-unit cube: side k (in CUBE_QUADS' order) is triangles 2k and 2k+1, counter-clockwise from
