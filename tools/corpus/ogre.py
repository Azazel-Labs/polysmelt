"""OGRE conformance cases: binary .mesh and .skeleton files as OGRE's serializers lay them out, their XML forms as
OGRE's converter writes them, and .material scripts.

A binary file starts with a 16-bit header id, 0x1000, whose byte order is the file's, and a version line
("[MeshSerializer_v1.100]", "[Serializer_v1.80]") ended by a line feed. Then come chunks: a 16-bit id and a 32-bit
length counting the six header bytes and whatever the chunk holds, child chunks included. Strings end with a line
feed. A mesh chunk (0x3000) holds a "skeletally animated" flag, then shared geometry (0x5000), submeshes (0x4000:
material name, a shared-geometry flag, an index count, a 32-bit index flag, the indices, its own geometry when it
doesn't share, then its operation 0x4010, bone assignments 0x4100 and texture aliases 0x4200), the skeleton link
(0x6000), shared bone assignments (0x7000: vertex, bone handle, weight), levels of detail (0x8000, laid out one way
up to v1.8 and another in v1.100), bounds (0x9000), submesh names (0xA000), edge lists (0xB000), poses (0xC000),
mesh animations (0xD000) and extreme points (0xE000). From v1.30 a geometry chunk holds a vertex declaration
(0x5100: per element its buffer, type, semantic, offset and index) and vertex buffers (0x5200: binding and vertex
size, then 0x5210 with the bytes); before that it holds the positions, then normal (0x5100), color (0x5200) and
texture coordinate (0x5300) chunks, and v1.10's two-dimensional texture coordinates run up the image. A skeleton
holds its blend mode (0x1010), bones (0x2000: name, handle, position, rotation x y z w, and from v1.80 an optional
scale, the chunk's length leaving the name out), parents (0x3000), animations (0x4000: tracks 0x4100 of keyframes
0x4110 with time, rotation, translation and optional scale, relative to the bind pose) and links to other
skeletons whose animations it shares (0x5000).

OGRE is right-handed and Y up with counter-clockwise faces, as glTF is, so expected positions are the file's.
Expected poses are worked out here with plain matrices; colors in vertex data and scripts are sRGB, made linear.
"""

