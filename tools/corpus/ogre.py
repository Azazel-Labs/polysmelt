# XML writers, from the same dicts.

def num(x):
    return repr(float(x)) if not float(x).is_integer() else str(int(x)) if abs(x) < 1e15 else repr(float(x))


def xyz(v, names=("x", "y", "z")):
    return " ".join(f'{n}="{num(c)}"' for n, c in zip(names, v))


def xml_geometry(tag, g):
    n = len(g["positions"])
    out = [f'<{tag} vertexcount="{n}">']
    attrs = 'positions="true"' + (' normals="true"' if g.get("normals") else "")
    out.append(f"<vertexbuffer {attrs}>")
    for v in range(n):
        out.append(f'<vertex><position {xyz(g["positions"][v])}/>'
                   + (f'<normal {xyz(g["normals"][v])}/>' if g.get("normals") else "") + "</vertex>")
    out.append("</vertexbuffer>")
    rest = []
    if g.get("tangents"):
        rest.append('tangents="true"' + (' tangent_dimensions="4"' if len(g["tangents"][0]) == 4 else ""))
    if g.get("binormals"):
        rest.append('binormals="true"')
    if g.get("diffuse"):
        rest.append('colours_diffuse="true"')
    if g.get("specular"):
        rest.append('colours_specular="true"')
    uvs = g.get("uvs", [])
    if uvs:
        rest.append(f'texture_coords="{len(uvs)}"')
        rest += [f'texture_coord_dimensions_{k}="float{len(s[0])}"' for k, s in enumerate(uvs)]
    if rest:
        out.append(f"<vertexbuffer {' '.join(rest)}>")
        for v in range(n):
            parts = []
            if g.get("tangents"):
                t = g["tangents"][v]
                parts.append(f"<tangent {xyz(t, ('x', 'y', 'z', 'w'))}/>")
            if g.get("binormals"):
                parts.append(f'<binormal {xyz(g["binormals"][v])}/>')
            for key in ("diffuse", "specular"):
                if g.get(key):
                    c = " ".join(num(x / 255) for x in g[key][v])
                    parts.append(f'<colour_{key} value="{c}"/>')
            for s in uvs:
                parts.append(f"<texcoord {xyz(s[v], ('u', 'v'))}/>")
            out.append("<vertex>" + "".join(parts) + "</vertex>")
        out.append("</vertexbuffer>")
    out.append(f"</{tag}>")
    return "\n".join(out)


OPERATIONS = {1: "point_list", 2: "line_list", 3: "line_strip", 4: "triangle_list", 5: "triangle_strip",
              6: "triangle_fan"}


def xml_faces(op, idx):
    if op == 4:
        groups = [idx[i:i + 3] for i in range(0, len(idx) - 2, 3)]
    elif op == 2:
        groups = [idx[i:i + 2] for i in range(0, len(idx) - 1, 2)]
    elif op in (5, 6):
        groups = [idx[:3]] + [[i] for i in idx[3:]]
    else:
        groups = [[i] for i in idx]
    faces = "".join("<face " + " ".join(f'v{k + 1}="{i}"' for k, i in enumerate(g)) + "/>" for g in groups)
    return f'<faces count="{len(groups)}">{faces}</faces>'


def xml_bones(assigns):
    return "<boneassignments>" + "".join(
        f'<vertexboneassignment vertexindex="{v}" boneindex="{b}" weight="{num(wt)}"/>' for v, b, wt in assigns
    ) + "</boneassignments>"


def xml_target(t):
    return 'target="mesh"' if t == 0 else f'target="submesh" index="{t - 1}"'


def mesh_xml(m):
    out = ["<?xml version=\"1.0\" encoding=\"UTF-8\"?>", "<mesh>"]
    if m.get("shared"):
        out.append(xml_geometry("sharedgeometry", m["shared"]))
    out.append("<submeshes>")
    for s in m["subs"]:
        idx = s.get("indices") or []
        op = s.get("op", 4)
        out.append(f'<submesh material="{s["material"]}" usesharedvertices="{str(s.get("shared", False)).lower()}" '
                   f'use32bitindexes="{str(s.get("idx32", False)).lower()}" operationtype="{OPERATIONS[op]}">')
        if idx:
            out.append(xml_faces(op, idx))
        if not s.get("shared"):
            out.append(xml_geometry("geometry", s["geometry"]))
        if s.get("bones"):
            out.append(xml_bones(s["bones"]))
        if s.get("aliases"):
            out.append("<textures>" + "".join(f'<texture alias="{a}" name="{t}"/>' for a, t in s["aliases"])
                       + "</textures>")
        out.append("</submesh>")
    out.append("</submeshes>")
    if m.get("skeleton"):
        out.append(f'<skeletonlink name="{m["skeleton"]}"/>')
    if m.get("shared_bones"):
        out.append(xml_bones(m["shared_bones"]))
    if m.get("lod"):
        lod = m["lod"]
        levels = lod["levels"]
        manual = isinstance(levels[0][1], str)
        out.append(f'<levelofdetail strategy="{lod.get("strategy", "distance_box")}" numlevels="{len(levels) + 1}" '
                   f'manual="{str(manual).lower()}">')
        for usage, what in levels:
            if manual:
                out.append(f'<lodmanual value="{num(usage)}" meshname="{what}"/>')
            else:
                lists = "".join(
                    f'<lodfacelist submeshindex="{k}" numfaces="{len(idx) // 3}">'
                    + "".join(f'<face v1="{idx[i]}" v2="{idx[i + 1]}" v3="{idx[i + 2]}"/>'
                              for i in range(0, len(idx), 3)) + "</lodfacelist>"
                    for k, idx in enumerate(what) if idx)
                out.append(f'<lodgenerated value="{num(usage)}">{lists}</lodgenerated>')
        out.append("</levelofdetail>")
    names = [(k, s["name"]) for k, s in enumerate(m["subs"]) if s.get("name")]
    if names:
        out.append("<submeshnames>" + "".join(f'<submeshname name="{n}" index="{k}"/>' for k, n in names)
                   + "</submeshnames>")
    if m.get("poses"):
        out.append("<poses>")
        for p in m["poses"]:
            offs = "".join(f'<poseoffset index="{o[0]}" {xyz(o[1])}'
                           + (" " + xyz(o[2], ("nx", "ny", "nz")) if len(o) > 2 else "") + "/>" for o in p["offsets"])
            out.append(f'<pose {xml_target(p["target"])} name="{p["name"]}">{offs}</pose>')
        out.append("</poses>")
    if m.get("animations"):
        out.append("<animations>")
        for a in m["animations"]:
            out.append(f'<animation name="{a["name"]}" length="{num(a["length"])}">')
            if a.get("base"):
                out.append(f'<baseinfo baseanimationname="{a["base"][0]}" basekeyframetime="{num(a["base"][1])}"/>')
            out.append("<tracks>")
            for t in a["tracks"]:
                out.append(f'<track {xml_target(t["target"])} type="{t["type"]}"><keyframes>')
                for k in t["keys"]:
                    if t["type"] == "morph":
                        body = "".join(f"<position {xyz(p)}/>" + (f"<normal {xyz(nm)}/>" if k.get("normals") else "")
                                       for p, nm in zip(k["positions"], k.get("normals") or k["positions"]))
                    else:
                        body = "".join(f'<poseref poseindex="{i}" influence="{num(f)}"/>' for i, f in k["refs"])
                    out.append(f'<keyframe time="{num(k["time"])}">{body}</keyframe>')
                out.append("</keyframes></track>")
            out.append("</tracks></animation>")
        out.append("</animations>")
    out.append("</mesh>")
    return "\n".join(out) + "\n"


def xml_rotation(tag, axis, deg):
    return f'<{tag} angle="{num(math.radians(deg))}"><axis {xyz(axis)}/></{tag}>'


def skeleton_xml(s):
    """An XML skeleton: like skeleton_binary's dict, but rotations as (axis, degrees)."""
    blend = {0: ' blendmode="average"', 1: ' blendmode="cumulative"'}.get(s.get("blend"), "")
    out = ["<?xml version=\"1.0\" encoding=\"UTF-8\"?>", f"<skeleton{blend}>", "<bones>"]
    for name, handle, pos, (axis, deg), scale, _ in s["bones"]:
        sc = f"<scale {xyz(scale)}/>" if scale else ""
        out.append(f'<bone id="{handle}" name="{name}"><position {xyz(pos)}/>{xml_rotation("rotation", axis, deg)}'
                   f"{sc}</bone>")
    out.append("</bones>")
    by_handle = {b[1]: b[0] for b in s["bones"]}
    out.append("<bonehierarchy>" + "".join(f'<boneparent bone="{b[0]}" parent="{by_handle[b[5]]}"/>'
                                           for b in s["bones"] if b[5] is not None) + "</bonehierarchy>")
    out.append("<animations>")
    for a in s.get("animations", []):
        out.append(f'<animation name="{a["name"]}" length="{num(a["length"])}">')
        if a.get("base"):
            out.append(f'<baseinfo baseanimationname="{a["base"][0]}" basekeyframetime="{num(a["base"][1])}"/>')
        out.append("<tracks>")
        for handle, keys in a["tracks"]:
            frames = "".join(
                f'<keyframe time="{num(t)}"><translate {xyz(tr)}/>{xml_rotation("rotate", *rot)}'
                + (f'<scale factor="{num(sc[0])}"/>' if sc and sc[0] == sc[1] == sc[2] else
                   f"<scale {xyz(sc)}/>" if sc else "") + "</keyframe>"
                for t, rot, tr, sc in keys)
            out.append(f'<track bone="{by_handle[handle]}"><keyframes>{frames}</keyframes></track>')
        out.append("</tracks></animation>")
    out.append("</animations>")
    if s.get("links"):
        out.append("<animationlinks>" + "".join(f'<animationlink skeletonName="{n}" scale="{num(sc)}"/>'
                                                for n, sc in s["links"]) + "</animationlinks>")
    out.append("</skeleton>")
    return "\n".join(out) + "\n"


def material(name, *pass_lines, parent=None, extra="", textures=()):
    """A material script with one technique of one pass: its lines, then texture units (lists of lines)."""
    units = "".join("            texture_unit" + (f" {u[0]}" if u[0] else "") + "\n            {\n"
                    + "".join(f"                {line}\n" for line in u[1:]) + "            }\n" for u in textures)
    head = f"material {name}" + (f" : {parent}" if parent else "")
    lines = "".join(f"            {line}\n" for line in pass_lines)
    return (f"{head}\n{{\n{extra}    technique\n    {{\n        pass\n        {{\n{lines}{units}"
            "        }\n    }\n}\n\n")


def lin(c):
    return [r(srgb_to_linear(x)) for x in c]


def lin_bytes(c):
    return [r(srgb_to_linear(x / 255)) for x in c[:3]] + [r(c[3] / 255)]


def rough(shininess):
    return r(math.sqrt(2 / (shininess + 2)))


def ogre_source(version, **more):
    return dict({"format": "OGRE", "version": version}, **more)


