# Binary writers. A geometry here is a dict: positions, and optionally normals, tangents (3 or 4 numbers),
# binormals, diffuse and specular (bytes, sRGB), uvs (a list of sets, each 1 or 2 numbers a vertex).

def standard_elements(g):
    """A geometry's elements in common types: positions and normals in buffer 0, the rest in buffer 1."""
    els = [(0, FLOAT3, POSITION, 0, g["positions"])]
    if g.get("normals"):
        els.append((0, FLOAT3, NORMAL, 0, g["normals"]))
    if g.get("tangents"):
        els.append((1, FLOAT4 if len(g["tangents"][0]) == 4 else FLOAT3, TANGENT, 0, g["tangents"]))
    if g.get("binormals"):
        els.append((1, FLOAT3, BINORMAL, 0, g["binormals"]))
    if g.get("diffuse"):
        els.append((1, ABGR, DIFFUSE, 0, g["diffuse"]))
    if g.get("specular"):
        els.append((1, ABGR, SPECULAR, 0, g["specular"]))
    for k, s in enumerate(g.get("uvs", [])):
        els.append((1, FLOAT1 + len(s[0]) - 1, TEXCOORD, k, s))
    return els


def geometry(w, n, elements, count=None):
    """A v1.30-on geometry chunk: `elements` are (buffer, type, semantic, index, per-vertex values)."""
    strides, offsets = {}, []
    for src, ty, _, _, _ in elements:
        offsets.append(strides.get(src, 0))
        strides[src] = strides.get(src, 0) + element_size(ty)
    decl = b"".join(w.chunk(M_ELEMENT, w.pack("5H", e[0], e[1], e[2], offsets[i], e[3]))
                    for i, e in enumerate(elements))
    body = w.pack("I", n if count is None else count) + w.chunk(M_DECLARATION, decl)
    for src in sorted(strides):
        data = b"".join(w.element(e[1], e[4][v]) for v in range(n) for e in elements if e[0] == src)
        body += w.chunk(M_BUFFER, w.pack("HH", src, strides[src]) + w.chunk(M_BUFFER_DATA, data))
    return w.chunk(M_GEOMETRY, body)


def old_geometry(w, g, flip_v):
    """A pre-v1.30 geometry chunk."""
    n = len(g["positions"])
    body = w.pack("I", n) + w.pack("f" * 3 * n, *flat(g["positions"]))
    if g.get("normals"):
        body += w.chunk(M_OLD_NORMALS, w.pack("f" * 3 * n, *flat(g["normals"])))
    if g.get("diffuse"):
        body += w.chunk(M_OLD_COLOURS, b"".join(w.element(ABGR, c) for c in g["diffuse"]))
    for s in g.get("uvs", []):
        dim = len(s[0])
        vals = [(uv[0], 1 - uv[1]) for uv in s] if flip_v and dim == 2 else s
        body += w.chunk(M_OLD_TEXCOORDS, w.pack("H", dim) + w.pack("f" * dim * n, *flat(vals)))
    return w.chunk(M_GEOMETRY, body)


VERSIONS = ["1.10", "1.20", "1.30", "1.40", "1.41", "1.8", "1.100"]


def at_least(version, v):
    return VERSIONS.index(version) >= VERSIONS.index(v)


def mesh_binary(m, version="1.100", be=False):
    """A whole binary mesh from the dict `m` (see the cases)."""
    w = Out(be)

    def geo(g):
        if "elements" in g:
            return geometry(w, len(g["elements"][0][4]), g["elements"], g.get("count"))
        if at_least(version, "1.30"):
            return geometry(w, len(g["positions"]), standard_elements(g))
        return old_geometry(w, g, version == "1.10")

    def assign(cid, a):
        return w.chunk(cid, w.pack("IHf", *a))

    body = w.pack("?", bool(m.get("skeleton")))
    if m.get("shared"):
        body += geo(m["shared"])
    for s in m["subs"]:
        idx = s.get("indices") or []
        i32 = s.get("idx32", False)
        sb = string(s["material"]) + w.pack("?I?", s.get("shared", False), len(idx), i32)
        sb += w.pack(("I" if i32 else "H") * len(idx), *idx)
        if not s.get("shared"):
            sb += geo(s["geometry"])
        sb += w.chunk(M_SUBMESH_OPERATION, w.pack("H", s.get("op", 4)))
        sb += b"".join(assign(M_SUBMESH_BONE_ASSIGNMENT, a) for a in s.get("bones", []))
        sb += b"".join(w.chunk(M_SUBMESH_TEXTURE_ALIAS, string(a) + string(t)) for a, t in s.get("aliases", []))
        body += w.chunk(M_SUBMESH, sb)
    if m.get("skeleton"):
        body += w.chunk(M_SKELETON_LINK, string(m["skeleton"]))
    body += b"".join(assign(M_MESH_BONE_ASSIGNMENT, a) for a in m.get("shared_bones", []))
    if m.get("lod"):
        body += lod_binary(w, m["lod"], len(m["subs"]), version)
    if m.get("bounds"):
        lo, hi, rad = m["bounds"]
        body += w.chunk(M_BOUNDS, w.pack("7f", *lo, *hi, rad))
    names = [(k, s["name"]) for k, s in enumerate(m["subs"]) if s.get("name")]
    if names:
        body += w.chunk(M_NAME_TABLE, b"".join(w.chunk(M_NAME_ELEMENT, w.pack("H", k) + string(n)) for k, n in names))
    if m.get("edge_lists"):
        body += edge_lists(w, version)
    if m.get("poses"):
        pb = b""
        for p in m["poses"]:
            normals = any(len(o) > 2 for o in p["offsets"])
            b = string(p["name"]) + w.pack("H", p["target"])
            if at_least(version, "1.8"):
                b += w.pack("?", normals)
            for o in p["offsets"]:
                b += w.chunk(M_POSE_VERTEX, w.pack("I3f", o[0], *o[1]) + (w.pack("3f", *o[2]) if normals else b""))
            pb += w.chunk(M_POSE, b)
        body += w.chunk(M_POSES, pb)
    if m.get("animations"):
        ab = b""
        for a in m["animations"]:
            b = string(a["name"]) + w.pack("f", a["length"])
            if a.get("base"):
                b += w.chunk(M_BASEINFO, string(a["base"][0]) + w.pack("f", a["base"][1]))
            for t in a["tracks"]:
                tb = w.pack("HH", 1 if t["type"] == "morph" else 2 if t["type"] == "pose" else t["type"], t["target"])
                for k in t["keys"]:
                    if t["type"] == "morph":
                        normals = k.get("normals")
                        kb = w.pack("f", k["time"])
                        if at_least(version, "1.8"):
                            kb += w.pack("?", bool(normals))
                        vals = flat(p + nm for p, nm in zip(k["positions"], normals)) if normals else flat(
                            k["positions"])
                        tb += w.chunk(M_MORPH_KEY, kb + w.pack("f" * len(vals), *vals))
                    else:
                        refs = b"".join(w.chunk(M_POSE_REF, w.pack("Hf", i, f)) for i, f in k["refs"])
                        tb += w.chunk(M_POSE_KEY, w.pack("f", k["time"]) + refs)
                b += w.chunk(M_TRACK, tb)
            ab += w.chunk(M_ANIMATION, b)
        body += w.chunk(M_ANIMATIONS, ab)
    for sub, points in m.get("extremes", []):
        body += w.chunk(M_EXTREMES, w.pack("H", sub) + w.pack("f" * 3 * len(points), *flat(points)))
    return w.header(f"[MeshSerializer_v{version}]") + w.chunk(M_MESH, body)


def lod_binary(w, lod, subs, version):
    """Levels past the first: `lod` has an optional strategy and levels, each (usage, mesh name or per-submesh index
    lists)."""
    body = string(lod.get("strategy", "distance_box")) if at_least(version, "1.41") else b""
    levels = lod["levels"]
    body += w.pack("H", len(levels) + 1)
    if version == "1.100":
        for usage, what in levels:
            if isinstance(what, str):
                body += w.chunk(M_LOD_MANUAL, w.pack("f", usage) + string(what))
            else:
                b = w.pack("f", usage)
                for idx in what:
                    if idx is None:
                        # Reusing the index buffer of the level before.
                        b += w.pack("III", 3, 0, 0)
                    else:
                        b += w.pack("III", len(idx), 0, 0xFFFFFFFF) + w.pack("?I", False, len(idx))
                        b += w.pack("H" * len(idx), *idx)
                body += w.chunk(M_LOD_GENERATED, b)
        return w.chunk(M_LOD, body)
    manual = isinstance(levels[0][1], str)
    body += w.pack("?", manual)
    for usage, what in levels:
        if manual:
            inner = w.chunk(M_LOD_MANUAL, string(what))
        else:
            inner = b"".join(w.chunk(M_LOD_GENERATED, w.pack("I?", len(idx), False) + w.pack("H" * len(idx), *idx))
                             for idx in what)
        body += w.chunk(M_LOD_USAGE, w.pack("f", usage) + inner)
    return w.chunk(M_LOD, body)


def edge_lists(w, version):
    """One edge list of one triangle and one group of three edges, its bytes filler."""
    new = at_least(version, "1.40")
    b = w.pack("H?", 0, False) + (w.pack("?", True) if new else b"") + w.pack("II", 1, 1) + bytes(48)
    group = (w.pack("III", 0, 0, 1) if new else w.pack("I", 0)) + w.pack("I", 3) + bytes(75)
    b += w.chunk(M_EDGE_GROUP, group)
    # A manual level's list holds nothing more.
    manual = w.chunk(M_EDGE_LIST_LOD, w.pack("H?", 1, True))
    return w.chunk(M_EDGE_LISTS, w.chunk(M_EDGE_LIST_LOD, b) + manual)


def skeleton_binary(s, version="1.80", be=False):
    """A binary skeleton: `s` has bones (name, handle, position, rotation, scale or None, parent handle or None),
    animations (name, length, base, tracks of (handle, keys of (time, rotation, translation, scale or None))),
    links (name, scale) and an optional blend mode."""
    w = Out(be)
    body = b""
    if s.get("blend") is not None:
        body += w.chunk(S_BLENDMODE, w.pack("H", s["blend"]))
    for name, handle, pos, rot, scale, _ in s["bones"]:
        b = string(name) + w.pack("H3f4f", handle, *pos, *rot) + (w.pack("3f", *scale) if scale else b"")
        body += w.chunk(S_BONE, b, 6 + len(b) - len(string(name)))
    for name, handle, _, _, _, parent in s["bones"]:
        if parent is not None:
            body += w.chunk(S_PARENT, w.pack("HH", handle, parent))
    for a in s.get("animations", []):
        b = string(a["name"]) + w.pack("f", a["length"])
        if a.get("base"):
            b += w.chunk(S_BASEINFO, string(a["base"][0]) + w.pack("f", a["base"][1]))
        for handle, keys in a["tracks"]:
            tb = w.pack("H", handle)
            for time, rot, tr, sc in keys:
                tb += w.chunk(S_KEY, w.pack("f4f3f", time, *rot, *tr) + (w.pack("3f", *sc) if sc else b""))
            b += w.chunk(S_TRACK, tb)
        body += w.chunk(S_ANIMATION, b)
    for name, scale in s.get("links", []):
        body += w.chunk(S_LINK, string(name) + w.pack("f", scale))
    return w.header(f"[Serializer_v{version}]") + body


