# Chunk ids.
M_MESH, M_SUBMESH, M_SUBMESH_OPERATION, M_SUBMESH_BONE_ASSIGNMENT, M_SUBMESH_TEXTURE_ALIAS = (
    0x3000, 0x4000, 0x4010, 0x4100, 0x4200)
M_GEOMETRY, M_DECLARATION, M_ELEMENT, M_BUFFER, M_BUFFER_DATA = 0x5000, 0x5100, 0x5110, 0x5200, 0x5210
M_OLD_NORMALS, M_OLD_COLOURS, M_OLD_TEXCOORDS = 0x5100, 0x5200, 0x5300
M_SKELETON_LINK, M_MESH_BONE_ASSIGNMENT = 0x6000, 0x7000
M_LOD, M_LOD_USAGE, M_LOD_MANUAL, M_LOD_GENERATED = 0x8000, 0x8100, 0x8110, 0x8120
M_BOUNDS, M_NAME_TABLE, M_NAME_ELEMENT = 0x9000, 0xA000, 0xA100
M_EDGE_LISTS, M_EDGE_LIST_LOD, M_EDGE_GROUP = 0xB000, 0xB100, 0xB110
M_POSES, M_POSE, M_POSE_VERTEX = 0xC000, 0xC100, 0xC111
M_ANIMATIONS, M_ANIMATION, M_BASEINFO, M_TRACK, M_MORPH_KEY, M_POSE_KEY, M_POSE_REF = (
    0xD000, 0xD100, 0xD105, 0xD110, 0xD111, 0xD112, 0xD113)
M_EXTREMES = 0xE000
S_BLENDMODE, S_BONE, S_PARENT, S_ANIMATION, S_BASEINFO, S_TRACK, S_KEY, S_LINK = (
    0x1010, 0x2000, 0x3000, 0x4000, 0x4010, 0x4100, 0x4110, 0x5000)

# Vertex element types and semantics.
FLOAT1, FLOAT2, FLOAT3, FLOAT4, COLOUR, SHORT1, SHORT2, SHORT3, SHORT4, UBYTE4, ARGB, ABGR = range(12)
DOUBLE1, DOUBLE2, DOUBLE3, DOUBLE4, USHORT1, USHORT2, USHORT3, USHORT4 = range(12, 20)
INT1, INT2, INT3, INT4, UINT1, UINT2, UINT3, UINT4 = range(20, 28)
BYTE4, BYTE4_NORM, UBYTE4_NORM, SHORT2_NORM, SHORT4_NORM, USHORT2_NORM, USHORT4_NORM, INT_10_10_10_2 = range(28, 36)
HALF1, HALF2, HALF3, HALF4 = range(36, 40)
POSITION, BLEND_WEIGHTS, BLEND_INDICES, NORMAL, DIFFUSE, SPECULAR, TEXCOORD, BINORMAL, TANGENT = range(1, 10)


def element_layout(ty):
    """A type's struct code per component and component count."""
    table = [
        ((FLOAT1, FLOAT4), "f"), ((SHORT1, SHORT4), "H"), ((DOUBLE1, DOUBLE4), "d"), ((USHORT1, USHORT4), "H"),
        ((INT1, INT4), "i"), ((UINT1, UINT4), "I"), ((HALF1, HALF4), "e"),
    ]
    for (lo, hi), code in table:
        if lo <= ty <= hi:
            return code, ty - lo + 1
    return {BYTE4: ("b", 4), BYTE4_NORM: ("b", 4), UBYTE4_NORM: ("B", 4), UBYTE4: ("B", 4),
            SHORT2_NORM: ("h", 2), SHORT4_NORM: ("h", 4), USHORT2_NORM: ("H", 2), USHORT4_NORM: ("H", 4)}[ty]


def element_size(ty):
    if ty in (COLOUR, ARGB, ABGR, INT_10_10_10_2):
        return 4
    code, n = element_layout(ty)
    return struct.calcsize("<" + code) * n


class Out:
    """Packs values in one byte order."""

    def __init__(self, be=False):
        self.be = be
        self.o = ">" if be else "<"

    def pack(self, fmt, *v):
        return struct.pack(self.o + fmt, *v)

    def chunk(self, cid, body, length=None):
        return self.pack("HI", cid, 6 + len(body) if length is None else length) + body

    def header(self, line):
        return self.pack("H", 0x1000) + string(line)

    def element(self, ty, v):
        """One vertex's element: packed colors from byte values, 10-bit fields from signed integers, the rest as
        their struct codes."""
        if ty in (COLOUR, ABGR):
            return self.pack("I", v[0] | v[1] << 8 | v[2] << 16 | v[3] << 24)
        if ty == ARGB:
            return self.pack("I", v[2] | v[1] << 8 | v[0] << 16 | v[3] << 24)
        if ty == INT_10_10_10_2:
            return self.pack("I", (v[0] & 0x3FF) | (v[1] & 0x3FF) << 10 | (v[2] & 0x3FF) << 20 | (v[3] & 3) << 30)
        code, n = element_layout(ty)
        return self.pack(code * n, *v)


def string(s):
    return s.encode("utf-8") + b"\n"


def flat(vs):
    return [c for v in vs for c in v]


