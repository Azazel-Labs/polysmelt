# --- binary ------------------------------------------------------------------------------------

def binary(verts, faces, keyword="OFF"):
    out = (keyword + " BINARY\n").encode()
    out += struct.pack(">3i", len(verts), len(faces), 0)
    for v in verts:
        out += struct.pack(f">{len(v)}f", *v)
    for f in faces:
        corners, color = f if isinstance(f, tuple) else (f, ())
        out += struct.pack(f">{len(corners) + 1}i", len(corners), *corners)
        out += struct.pack(">i", len(color)) + struct.pack(f">{len(color)}f", *color)
    return out


case(FMT, "binary_cube", {"cube.off": binary(CUBE_V, QUADS)},
     {"spec": SPEC + ": OFF BINARY, big-endian 32-bit integers and floats", "source": SRC, **CUBE})

case(FMT, "binary_face_colors", {"cube.off": binary(CUBE_V, [(q, c) for q, c in zip(QUADS, FCOL)])},
     {"spec": SPEC + ": OFF BINARY, each face's color given by its own count of floats", "source": SRC, **CUBE,
      "colors": True, "colors_include": [[r(srgb_to_linear(x)) for x in c] + [1.0] for c in FCOL]})

case(FMT, "binary_coff", {"cube.off": binary([[*v, 0.0, 0.0, 1.0, 1.0] for v in CUBE_V], QUADS, "COFF")},
     {"spec": SPEC + ": COFF BINARY, vertex colors as floats", "source": SRC, **CUBE, "colors": True,
      "colors_include": [[0, 0, 1, 1]]})
