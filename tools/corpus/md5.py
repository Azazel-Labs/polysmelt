"""MD5 conformance cases: Doom 3 models and animations as the engine's text formats (version 10) lay them out.

An .md5mesh is `MD5Version 10`, `commandline`, `numJoints`, `numMeshes`, then `joints { "name" parent ( x y z )
( qx qy qz ) }` in object space, and `mesh { shader numverts vert numtris tri numweights weight }` blocks: a
vertex names a run of weights, each a joint, a bias and an offset in that joint's frame. An .md5anim is
`numFrames`, `numJoints`, `frameRate`, `numAnimatedComponents`, then `hierarchy { "name" parent flags start }`,
`bounds`, `baseframe { ( x y z ) ( qx qy qz ) }` in each parent's frame, and `frame k { numbers }`: flag bits
1, 2, 4, 8, 16, 32 say which of a joint's position x, y, z and quaternion x, y, z the frame gives, from `start`.
A quaternion's w is left out and taken as -sqrt(1 - x² - y² - z²), so the files here write each rotation with w
at or below zero.

A mesh becomes joints as nodes (relative to their parents), a skin over them, and a primitive per mesh block
whose positions are the bias-weighted sums of the weights' offsets carried into object space, with smooth
normals; a shader names its texture as `<shader>.tga` or `<shader>_d.tga`, found here in another image format.
An animation becomes the joints with their first frame as the rest pose and one linear animation of the
components the flags animate. Triangles wind clockwise seen from the front, so the reader turns them around;
texture coordinates run down the image, as glTF's do. Doom 3 is Z up, so a point (x, y, z) lands at (x, z, -y)
and a root's rotation q becomes r·q for r the quarter turn about x.
"""

import math
import os
import sys

# The shared modules are beside this script, which `python -I` leaves off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import case, fresh, png, r  # noqa: E402

FMT = "md5"
SRC = "generated by tools/corpus/md5.py"
SPEC = "Doom 3 MD5 (version 10)"

fresh(FMT)

S = math.sqrt(0.5)
Z_UP = [-S, 0.0, 0.0, S]


def about_z(deg):
    a = math.radians(deg) / 2
    return [0.0, 0.0, math.sin(a), math.cos(a)]


def written(q):
    """A quaternion as the files hold it: x, y, z of the sign whose w is at or below zero."""
    if q[3] > 0:
        q = [-c for c in q]
    return "( %s )" % " ".join("%.9g" % c for c in q[:3])


def vec(v):
    return "( %s )" % " ".join("%.9g" % c for c in v)


def yup(p):
    return [p[0], p[2], -p[1]]


# The mesh: a quad facing +Z, corners counter-clockwise (0,0) (1,0) (1,1) (0,1). The root joint is at the origin;
# "arm" is at (0, 1, 0), turned a quarter about z, so an offset (x, y) in its frame lands at (-y, x + 1).
# Corner 1 is half each: (1, 0) from the root, and (-1, -1) from the arm, which lands at (1, 0) too.
MESH = """MD5Version 10
commandline "generated by md5.py"

// Two joints, object space.
numJoints 2
numMeshes 2

joints {
\t"root"\t-1 ( 0 0 0 ) ( 0 0 0 )\t\t// the origin
\t"arm"\t0 ( 0 1 0 ) %(arm)s
}

mesh {
\t/* a block comment */
\tshader "models/box/skin"
\tnumverts 4
\tvert 0 ( 0 1 ) 0 1
\tvert 1 ( 1 1 ) 1 2
\tvert 2 ( 1 0 ) 3 1
\tvert 3 ( 0 0 ) 4 1

\tnumtris 2
\ttri 0 0 3 2
\ttri 1 0 2 1

\tnumweights 5
\tweight 0 0 1 ( 0 0 0 )
\tweight 1 0 0.5 ( 1 0 0 )
\tweight 2 1 0.5 ( -1 -1 0 )
\tweight 3 1 1 ( 0 -1 0 )
\tweight 4 1 1 ( 0 0 0 )
}

mesh {
\tshader "models/box/nothing"
\tnumverts 0
\tnumtris 0
\tnumweights 0
}
""" % {"arm": written(about_z(90))}

case(FMT, "skinned_quad", {
    "box.md5mesh": MESH,
    "skin_d.png": png([180, 120, 30]),
}, {
    "spec": SPEC + ": two joints in object space, a vertex split between them, a shader's _d texture, and a mesh "
                   "block with no triangles left out",
    "source": SRC,
    "triangles": 2,
    "vertices": 4,
    "material_count": 1,
    "facts": {"joints": 2, "meshes": 2},
    "document": {"skins": 1, "joints": 2, "nodes": 3, "node_names": ["root", "arm", "box"],
                 "attributes": ["POSITION", "NORMAL", "TEXCOORD_0", "JOINTS_0", "WEIGHTS_0"]},
    "json": {
        "/asset/extras/source/format": "MD5",
        "/asset/extras/source/version": "10",
        "/asset/extras/source/upAxis": "+Z",
        "/asset/extras/source/commandline": "generated by md5.py",
    },
    "bounds": {"min": [0, 0, -1], "max": [1, 0, 0]},
    "positions_include": [yup([1, 0, 0]), yup([1, 1, 0])],
    "uvs_include": [[0, 1], [1, 1], [1, 0], [0, 0]],
    "normals_in": [[0, 1, 0]],
    "winding_matches_normals": True,
    "materials": [{"textured": True, "pixel": [180, 120, 30]}],
    "rig": [
        {"node": "root", "parent": None, "translation": [0, 0, 0], "rotation": Z_UP},
        {"node": "arm", "parent": "root", "translation": [0, 1, 0], "rotation": [r(c) for c in about_z(90)]},
    ],
})


def anim(rate, frames=3):
    """The animation: the root moves along x (flag 1); the arm rises along y and turns about z (flags 2 and 32).
    The base frame puts the arm elsewhere, which only the first frame's values make the rest pose."""
    out = ["MD5Version 10", 'commandline ""', "", "numFrames %d" % frames, "numJoints 2",
           "frameRate %s" % rate, "numAnimatedComponents 3", "", "hierarchy {",
           '\t"root"\t-1 1 0\t// x', '\t"arm"\t0 34 1\t// y, qz', "}", "", "bounds {"]
    out += ["\t( 0 0 0 ) ( 1 1 1 )"] * frames
    out += ["}", "", "baseframe {", "\t( 0 0 0 ) ( 0 0 0 )", "\t( 0 5 0 ) %s" % written(about_z(10)), "}", ""]
    for f in range(frames):
        qz = written(about_z(90 + 45 * f)).split()[3]
        out += ["frame %d {" % f, "\t%d %d %s" % (f, 1 + f, qz), "}", ""]
    return "\n".join(out)


def turned(deg):
    return [r(c) for c in about_z(deg)]


case(FMT, "anim_alone", {
    "wave.md5anim": anim("10"),
}, {
    "spec": SPEC + ": an animation read on its own: its skeleton from the hierarchy and base frame, with the "
                   "first frame as the rest pose and the flagged components animated",
    "source": SRC,
    "no_mesh": True,
    "facts": {"joints": 2, "frames": 3, "components": 3},
    "document": {"nodes": 2, "animations": 1, "channels": 3, "node_names": ["root", "arm"]},
    "json": {"/animations/0/name": "wave", "/asset/extras/source/frameRate": 10.0},
    "rig": [
        {"node": "root", "parent": None, "translation": [0, 0, 0], "rotation": Z_UP,
         "keys": {"translation": [0, 0.1, 0.2], "rotation": None}},
        {"node": "arm", "parent": "root", "translation": [0, 1, 0], "rotation": turned(90),
         "keys": {"translation": 3, "rotation": 3}},
        {"node": "root", "time": 0.2, "translation": yup([2, 0, 0])},
        {"node": "arm", "time": 0.1, "translation": [0, 2, 0], "rotation": turned(135)},
        {"node": "arm", "time": 0.2, "translation": [0, 3, 0], "rotation": turned(180)},
    ],
})

case(FMT, "anim_without_rate", {
    "still.md5anim": anim("0", frames=2),
}, {
    "spec": SPEC + ": a frame rate that isn't positive plays at the engine's 24 a second",
    "source": SRC,
    "no_mesh": True,
    "facts": {"joints": 2, "frames": 2, "components": 3},
    "json": {"/asset/extras/source/frameRate": 24.0, "/asset/extras/source/assumed": ["frameRate"]},
    "rig": [{"node": "root", "keys": {"translation": [0, 1 / 24]}}],
})


def errors(name, fname, text, want, what, kind):
    case(FMT, name, {fname: text}, {"spec": SPEC + ": " + what, "source": SRC, "error": want, "error_kind": kind})


errors("not_md5", "x.md5mesh", MESH.replace("MD5Version", "MD6Version"), "doesn't start with MD5Version",
       "a file that doesn't start with MD5Version", "UnknownFormat")
errors("truncated_mesh", "cut.md5mesh", MESH[:MESH.index("weight 3")], "cut short",
       "a mesh cut short inside its weights", "Truncated")
errors("weight_joint_out_of_range", "w.md5mesh", MESH.replace("weight 4 1 1", "weight 4 7 1"),
       "names joint 7", "a weight naming a joint past the skeleton", "Corrupt")
errors("vertex_weights_past_end", "v.md5mesh", MESH.replace("vert 3 ( 0 0 ) 4 1", "vert 3 ( 0 0 ) 4 9"),
       "run past numweights", "a vertex whose weights run past the block's", "Corrupt")
errors("triangle_index_out_of_range", "t.md5mesh", MESH.replace("tri 1 0 2 1", "tri 1 0 2 4"),
       "names a vertex past numverts", "a triangle naming a vertex past the block's", "Corrupt")
errors("joint_parent_out_of_range", "p.md5mesh", MESH.replace('"arm"\t0', '"arm"\t5'), "has parent 5",
       "a joint whose parent is past the skeleton", "Corrupt")
errors("not_a_number", "n.md5mesh", MESH.replace("weight 1 0 0.5", "weight 1 0 half"),
       "line", "a word where a number belongs", "Corrupt")
errors("anim_components_past_count", "c.md5anim", anim("10").replace('"arm"\t0 34 1', '"arm"\t0 34 2'),
       "run past numAnimatedComponents", "a joint whose components run past numAnimatedComponents", "Corrupt")
errors("anim_frame_too_short", "f.md5anim", anim("10").replace("frame 1 {\n\t1 2", "frame 1 {\n\t1"),
       "expected numAnimatedComponents", "a frame with fewer values than numAnimatedComponents", "Corrupt")
errors("anim_baseframe_short", "b.md5anim", anim("10").replace("\t( 0 0 0 ) ( 0 0 0 )\n\t( 0 5 0 )", "\t( 0 5 0 )"),
       "baseframe has 1 joints", "a base frame with fewer joints than the hierarchy", "Corrupt")
