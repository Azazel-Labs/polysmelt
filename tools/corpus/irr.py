def node(kind, name, pos=None, rot=None, scale=None, extra=(), mats=None, animators=(), children="", visible=True):
    items = [("string", "Name", name)]
    if pos:
        items.append(("vector3d", "Position", ", ".join(map(g, pos))))
    if rot:
        items.append(("vector3d", "Rotation", ", ".join(map(g, rot))))
    if scale:
        items.append(("vector3d", "Scale", ", ".join(map(g, scale))))
    if not visible:
        items.append(("bool", "Visible", "false"))
    out = f'<node type="{kind}">\n<attributes>\n{attrs([*items, *extra])}</attributes>\n'
    if mats:
        out += "<materials>\n" + "".join(f"<attributes>\n{attrs(m)}</attributes>\n" for m in mats) + "</materials>\n"
    if animators:
        out += "<animators>\n" + "".join(f"<attributes>\n{attrs(a)}</attributes>\n" for a in animators)
        out += "</animators>\n"
    return out + children + "</node>\n"


def scene(*nodes, ambient=None):
    head = attrs([("colorf", "AmbientLight", ambient)]) if ambient else ""
    return f'<?xml version="1.0"?>\n<irr_scene>\n<attributes>\n{head}</attributes>\n' + "".join(nodes) + "</irr_scene>\n"


