def tangent(uv, n):
    # A tangent and a binormal square to the normal and to each other.
    t = [n[1], n[2], n[0]]
    b = [n[1] * t[2] - n[2] * t[1], n[2] * t[0] - n[0] * t[2], n[0] * t[1] - n[1] * t[0]]
    return [g(c) for c in t + b]


