def read_irrmesh(text):
    """Every buffer's positions and triangles, by the rules above."""
    points, triangles = [], 0
    for b in re.findall(r"<buffer>(.*?)</buffer>", text, re.S):
        m = re.search(r'<vertices type="(\w+)"[^>]*>(.*?)</vertices>', b, re.S)
        per = {"standard": 9, "2tcoords": 11, "tangents": 15}[m.group(1)]
        tokens = m.group(2).split()
        verts = [[float(t) for t in tokens[k:k + 3]] for k in range(0, len(tokens), per)]
        idx = [int(t) for t in re.search(r"<indices[^>]*>(.*?)</indices>", b, re.S).group(1).split()]
        triangles += len(idx) // 3
        points += [verts[k] for k in idx]
    return points, triangles


