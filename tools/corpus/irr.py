"""Irrlicht conformance cases: the Irrlicht Engine's XML mesh (`.irrmesh`) and scene (`.irr`) formats, as the
engine writes and reads them (CIrrMeshWriter, CIrrMeshFileLoader, CSceneLoaderIrr and the scene nodes'
serializeAttributes).

A mesh is a list of <buffer>s, each a <material> (typed attributes: Type, Diffuse, Emissive, Lighting,
BackfaceCulling, Texture1 to Texture4...), <vertices> of a type (standard: position, normal, an aarrggbb color and
a texture coordinate; 2tcoords with a second coordinate set; tangents with a tangent and a binormal) and
<indices>, three per triangle. A scene is a tree of <node>s, each with its attributes (Name, Position, Rotation in
degrees, Scale, Visible and the node type's own), materials, animators and children; a node's transform is
T * Rz * Ry * Rx * S, its rotation matrices the usual ones applied to column vectors.

Irrlicht is Y up and left-handed: a triangle's vertices wind so that (b - a) x (c - a), worked out as numbers,
points along its outward normal. glTF is right-handed, so the reader mirrors z: a point (x, y, z) is (x, y, -z)
there, and faces keep facing out.

Irrlicht draws with the vertices' color in place of the material's diffuse; vertices that are all white take the
diffuse color, all of one other color take that color, and differing ones are kept per vertex. The cube scene node
is centered, `Size` on each side; the sphere has PolyCountX segments around and PolyCountY from pole to pole, so
2 * X * (Y - 1) triangles. Animators: `rotation` adds its Rotation (degrees) every 10 ms, `flyCircle` sets the
position to Center + Radius * (cos(a) * U + sin(a) * V) with a = Speed * milliseconds and V, U worked out from
Direction, and `flyStraight` runs from Start to End in TimeForWay milliseconds.

Also a real file from assimp's test models (test/models/IRRMesh; BSD license, see LICENSE-assimp beside the
cases), kept in its case folder (or read from the folder given as the first argument). Its expectations come from
reading it here, by the rules above.
"""

