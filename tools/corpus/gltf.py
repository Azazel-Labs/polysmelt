SPEC1 = "glTF 1.0 (Khronos, 2016)"
BINARY = "binary_glTF"
V1_NAMES = {"buffers": "buffer", "bufferViews": "view", "accessors": "acc", "meshes": "mesh", "nodes": "node",
            "materials": "mat", "textures": "tex", "images": "img", "samplers": "smp", "scenes": "scene",
            "cameras": "cam"}


def v1(g, materials=None, binary=False, bin_name="model.bin"):
    """`g` as glTF 1.0: objects keyed by ID (`<kind>_<n>`), references by ID, strides on accessors,
    JOINTS_0 and WEIGHTS_0 as JOINT and WEIGHT."""
    j = g.finish()

    def ref(kind, i):
        return BINARY if kind == "buffers" and binary else f"{V1_NAMES[kind]}_{i}"

    out = {"asset": {"version": "1.0", "generator": SRC}}
    views = j.get("bufferViews", [])
    if "buffers" in j:
        out["buffers"] = {ref("buffers", 0): {**j["buffers"][0], "type": "arraybuffer",
                                              "uri": "data:," if binary else bin_name}}
    out["bufferViews"] = {ref("bufferViews", i): {**{k: v for k, v in bv.items() if k != "byteStride"},
                                                  "buffer": ref("buffers", bv["buffer"])}
                          for i, bv in enumerate(views)}
    out["accessors"] = {ref("accessors", i): {"byteOffset": 0, **a, "byteStride": views[a["bufferView"]].get("byteStride", 0),
                                              "bufferView": ref("bufferViews", a["bufferView"])}
                        for i, a in enumerate(j.get("accessors", []))}
    sem = {"JOINTS_0": "JOINT", "WEIGHTS_0": "WEIGHT"}
    out["meshes"] = {}
    for i, m in enumerate(j.get("meshes", [])):
        prims = []
        for pr in m["primitives"]:
            q = {"attributes": {sem.get(k, k): ref("accessors", v) for k, v in pr["attributes"].items()},
                 "mode": pr.get("mode", 4)}
            if "indices" in pr:
                q["indices"] = ref("accessors", pr["indices"])
            if "material" in pr:
                q["material"] = ref("materials", pr["material"])
            prims.append(q)
        out["meshes"][ref("meshes", i)] = {"primitives": prims}
    out["nodes"] = {}
    for i, n in enumerate(j.get("nodes", [])):
        n = dict(n)
        if "mesh" in n:
            n["meshes"] = [ref("meshes", n.pop("mesh"))]
        if "children" in n:
            n["children"] = [ref("nodes", c) for c in n["children"]]
        if "camera" in n:
            n["camera"] = ref("cameras", n["camera"])
        n.pop("skin", None)
        out["nodes"][ref("nodes", i)] = n
    out["scenes"] = {ref("scenes", i): {"nodes": [ref("nodes", x) for x in sc["nodes"]]}
                     for i, sc in enumerate(j["scenes"])}
    out["scene"] = ref("scenes", j.get("scene", 0))
    out["cameras"] = {ref("cameras", i): c for i, c in enumerate(j.get("cameras", []))}
    out["samplers"] = {ref("samplers", i): sm for i, sm in enumerate(j.get("samplers", []))}
    out["images"] = {}
    for i, im in enumerate(j.get("images", [])):
        if "bufferView" in im:
            im = {"uri": "data:,", "extensions": {"KHR_binary_glTF": {
                "bufferView": ref("bufferViews", im["bufferView"]), "mimeType": im["mimeType"], "width": 2,
                "height": 2}}}
        out["images"][ref("images", i)] = im
    out["textures"] = {ref("textures", i): {"format": 6408, "internalFormat": 6408, "target": 3553, "type": 5121,
                                            "sampler": ref("samplers", t.get("sampler", 0)),
                                            "source": ref("images", t["source"])}
                       for i, t in enumerate(j.get("textures", []))}
    out["materials"] = materials or {}
    used = ["KHR_binary_glTF"] if binary else []
    if any("KHR_materials_common" in m.get("extensions", {}) for m in out["materials"].values()):
        used.append("KHR_materials_common")
    if used:
        out["extensionsUsed"] = used
    for k in [k for k, v in out.items() if v == {}]:
        del out[k]
    return out


def v1_gltf(doc, g):
    return json.dumps(doc, indent=1), bytes(g.bin)


def v1_glb(doc, g):
    """A binary glTF 1.0 (KHR_binary_glTF) file: a 20-byte header, the JSON, the body."""
    text = json.dumps(doc, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    body = bytes(g.bin)
    return b"glTF" + struct.pack("<IIII", 1, 20 + len(text) + len(body), len(text), 0) + text + body


