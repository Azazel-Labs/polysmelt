# --- scene graph ------------------------------------------------------------------------------


def scene(models, placements, extra=b""):
    """`models`: list of (size, voxels). `placements`: list of (model, frame, attrs, layer).
    Root transform 0 -> group 1 -> transform/shape pairs."""
    out = b"".join(size(*s) + xyzi(v) for s, v in models)
    n = len(placements)
    children = [2 + 2 * i for i in range(n)]
    out += ntrn(0, 1) + ngrp(1, children)
    for i, (m, frame, attrs, layer) in enumerate(placements):
        out += ntrn(2 + 2 * i, 3 + 2 * i, frame, attrs, layer) + nshp(3 + 2 * i, m)
    return vox(out + extra)


