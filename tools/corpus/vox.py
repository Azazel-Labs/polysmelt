def chunk(cid, content=b"", children=b""):
    return cid + struct.pack("<II", len(content), len(children)) + content + children


def string(s):
    b = s.encode()
    return struct.pack("<I", len(b)) + b


def dict_(d):
    return struct.pack("<I", len(d)) + b"".join(string(k) + string(v) for k, v in d.items())


def size(x, y, z):
    return chunk(b"SIZE", struct.pack("<3i", x, y, z))


def xyzi(voxels):
    return chunk(b"XYZI", struct.pack("<I", len(voxels)) + b"".join(struct.pack("<4B", *v) for v in voxels))


def rgba(colors):
    """`colors[i]` is color index i + 1."""
    pal = list(colors) + [(0, 0, 0, 255)] * (256 - len(colors))
    return chunk(b"RGBA", b"".join(struct.pack("<4B", *c) for c in pal))


def ntrn(node, child, frame=None, attrs=None, layer=-1, frames=None):
    """`frames`, when given, replaces the one `frame`."""
    frames = frames if frames is not None else [frame or {}]
    body = struct.pack("<I", node) + dict_(attrs or {}) + struct.pack("<Iii", child, -1, layer)
    body += struct.pack("<I", len(frames)) + b"".join(dict_(f) for f in frames)
    return chunk(b"nTRN", body)


def ngrp(node, children):
    return chunk(b"nGRP", struct.pack("<I", node) + dict_({}) + struct.pack("<I", len(children))
                 + b"".join(struct.pack("<I", c) for c in children))


def nshp(node, model):
    return chunk(b"nSHP", struct.pack("<I", node) + dict_({}) + struct.pack("<I", 1) + struct.pack("<I", model) + dict_({}))


def layr(layer, hidden=False, name=None):
    d = {"_hidden": "1"} if hidden else {}
    if name:
        d["_name"] = name
    return chunk(b"LAYR", struct.pack("<i", layer) + dict_(d) + struct.pack("<i", -1))


def matl(index, d):
    return chunk(b"MATL", struct.pack("<I", index) + dict_(d))


def vox(*chunks, version=200):
    return b"VOX " + struct.pack("<I", version) + chunk(b"MAIN", b"", b"".join(chunks))


def lin(c):
    return [r(srgb_to_linear(v / 255), 4) for v in c[:3]] + [1]


def y_up(p):
    return [p[0], p[2], -p[1]]


def bounds(lo, hi):
    """Z-up box corners to Y-up bounds."""
    a, b = y_up(lo), y_up(hi)
    return {"min": [min(a[i], b[i]) for i in range(3)], "max": [max(a[i], b[i]) for i in range(3)]}


def block(sx, sy, sz, color=1):
    return [(x, y, z, color) for z in range(sz) for y in range(sy) for x in range(sx)]


