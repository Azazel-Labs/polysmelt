"""MagicaVoxel .vox conformance cases, written per the format description in
ephtracy/voxel-model (MagicaVoxel-file-format-vox.txt and -vox-extension.txt): models, the
palette and its off-by-one, the default palette, the scene graph (transforms, rotations, groups,
hidden nodes and layers) and materials.

Expectations use surface area and bounds rather than triangle counts, so a reader may merge
coplanar faces.
"""

