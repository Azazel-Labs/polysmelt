"""VRM conformance cases: avatars (.vrm) and animations (.vrma), GLB files whose extensions
describe a humanoid. VRM 1.0 (VRMC_vrm, VRMC_materials_mtoon, VRMC_springBone) faces +Z as
glTF does; VRM 0.x (the VRM extension) faces -Z, so it is turned half about Y. A VRM material's
metallic-roughness fallback is what's drawn, even when a file marks the extensions required.
"""

