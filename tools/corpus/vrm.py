def cube_triangles():
    """The unit cube as 24 flat vertices and 36 indices."""
    pos, nrm, idx = [], [], []
    for q, n in CUBE_QUADS:
        base = len(pos)
        pos += [CUBE_V[i] for i in q]
        nrm += [n] * 4
        idx += [base, base + 1, base + 2, base, base + 2, base + 3]
    return pos, nrm, idx


def glb(doc, binary):
    text = json.dumps(doc, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    binary += b"\0" * (-len(binary) % 4)
    out = struct.pack("<I4s", len(text), b"JSON") + text + struct.pack("<I4s", len(binary), b"BIN\0") + binary
    return b"glTF" + struct.pack("<II", 2, 12 + len(out)) + out


def avatar(extensions, used, required=(), color=(1.0, 0.5, 0.25), material_ext=None, offset=(0, 0, 0)):
    """A one-cube avatar with a hips bone: the cube at `offset`, under `Hips`."""
    pos, nrm, idx = cube_triangles()
    pos = [[c + o for c, o in zip(p, offset)] for p in pos]
    bin_pos = b"".join(struct.pack("<3f", *p) for p in pos)
    bin_nrm = b"".join(struct.pack("<3f", *n) for n in nrm)
    bin_idx = b"".join(struct.pack("<H", i) for i in idx)
    binary = bin_pos + bin_nrm + bin_idx
    material = {"name": "Skin", "pbrMetallicRoughness": {"baseColorFactor": [*color, 1.0], "metallicFactor": 0.0}}
    if material_ext:
        material["extensions"] = material_ext
    doc = {
        "asset": {"version": "2.0", "generator": SRC},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"name": "Hips", "children": [1]}, {"name": "Body", "mesh": 0}],
        "meshes": [{"primitives": [{"attributes": {"POSITION": 0, "NORMAL": 1}, "indices": 2, "material": 0}]}],
        "materials": [material],
        "accessors": [
            {"bufferView": 0, "componentType": 5126, "count": 24, "type": "VEC3",
             "min": [min(p[k] for p in pos) for k in range(3)], "max": [max(p[k] for p in pos) for k in range(3)]},
            {"bufferView": 1, "componentType": 5126, "count": 24, "type": "VEC3"},
            {"bufferView": 2, "componentType": 5123, "count": 36, "type": "SCALAR"},
        ],
        "bufferViews": [
            {"buffer": 0, "byteOffset": 0, "byteLength": len(bin_pos), "target": 34962},
            {"buffer": 0, "byteOffset": len(bin_pos), "byteLength": len(bin_nrm), "target": 34962},
            {"buffer": 0, "byteOffset": len(bin_pos) + len(bin_nrm), "byteLength": len(bin_idx), "target": 34963},
        ],
        "buffers": [{"byteLength": len(binary)}],
        "extensionsUsed": list(used),
        "extensions": extensions,
    }
    if required:
        doc["extensionsRequired"] = list(required)
    return glb(doc, binary)


