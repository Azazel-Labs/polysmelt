# --- element types, as Gmsh has them ---------------------------------------------------------------

SHAPES = {"Point": "vertex", "Line": "line", "Triangle": "triangle", "Quadrilateral": "quad",
          "Tetrahedron": "tetra", "Hexahedron": "hexahedron", "Prism": "wedge", "Pyramid": "pyramid"}
KINDS = ["Point", "Curve", "Surface", "Volume"]
TYPES = {}
for t in list(range(1, 34)) + list(range(36, 67)) + list(range(71, 76)) + list(range(79, 84)) + list(range(92, 106)) \
        + list(range(118, 132)) + [137]:
    name, dim, order, nodes, _, corners = gmsh.model.mesh.getElementProperties(t)
    TYPES[t] = (SHAPES[name.split()[0]], dim, nodes, corners)
# The prisms of order 3 and up, whose properties Gmsh's module doesn't give: (p + 1)^2 (p + 2) / 2 nodes, or
# 6 + 9 (p - 1) incomplete.
for t, nodes in {90: 40, 91: 75, 106: 126, 107: 196, 108: 288, 109: 405, 110: 550, 111: 24, 112: 33, 113: 42,
                 114: 51, 115: 60, 116: 69, 117: 78}.items():
    TYPES[t] = ("wedge", 3, nodes, 6)


class Mesh:
    """A mesh as a file lists it: `nodes` are (tag, (x, y, z)) in the file's order, `elements` are
    (tag, type, physical tag, entity tag, node tags), `names` maps (dimension, physical tag) to a
    name, and `views` are (kind, name, components, {tag: values}), the values of element-node data
    a row for each node."""

    def __init__(self):
        self.nodes = []
        self.elements = []
        self.names = {}
        self.views = []
        self.ordered = True


def view_name(tag):
    return gmsh.option.getString("View[%d].Name" % gmsh.view.getIndex(tag))


def current():
    """The mesh Gmsh holds."""
    m = Mesh()
    tags, coords, _ = gmsh.model.mesh.getNodes()
    m.nodes = [(int(t), tuple(float(c) for c in coords[3 * i:3 * i + 3])) for i, t in enumerate(tags)]
    for dim, entity in gmsh.model.getEntities():
        physicals = gmsh.model.getPhysicalGroupsForEntity(dim, entity)
        types, element_tags, node_tags = gmsh.model.mesh.getElements(dim, entity)
        for ty, tags, nodes in zip(types, element_tags, node_tags):
            n = TYPES[int(ty)][2]
            for k, tag in enumerate(tags):
                m.elements.append((int(tag), int(ty), int(physicals[0]) if len(physicals) else 0, entity,
                                   [int(i) for i in nodes[k * n:(k + 1) * n]]))
    for dim, tag in gmsh.model.getPhysicalGroups():
        name = gmsh.model.getPhysicalName(dim, tag)
        if name:
            m.names[(dim, tag)] = name
    for v in gmsh.view.getTags():
        kind, tags, data, _, comps = gmsh.view.getModelData(v, 0)
        values = {}
        for tag, row in zip(tags, data):
            row = np.asarray(row, dtype=np.float64)
            values[int(tag)] = row.reshape(-1, comps) if kind == "ElementNodeData" else row
        m.views.append((kind, view_name(v), comps, values))
    return m


def read_gmsh(path):
    """What Gmsh reads from the file."""
    gmsh.clear()
    for v in gmsh.view.getTags():
        gmsh.view.remove(v)
    gmsh.open(path)
    return current()


def text_order(data):
    """The node tags of a text file of version 1 or 2, in order: each node's line starts with its
    tag."""
    lines = data.replace(b"\r\n", b"\n").split(b"\n")
    start = next(i for i, l in enumerate(lines) if l in (b"$Nodes", b"$NOD"))
    n = int(lines[start + 1])
    return [int(l.split()[0]) for l in lines[start + 2:start + 2 + n]]


def by_meshio(path, m, physicals=True):
    """Puts the mesh's nodes in the order meshio reads them in, which is the file's, and holds
    meshio's elements, physical tags and data against Gmsh's (not the tags when `physicals` is
    false: meshio doesn't read a partitioned file's). Returns whether meshio read it."""
    try:
        got = meshio.read(path)
    except BaseException:  # meshio exits on what it doesn't read
        return False
    where = {}
    for tag, p in m.nodes:
        assert p not in where, "two nodes in one place"
        where[p] = tag
    order = [where[tuple(float(c) for c in p)] for p in got.points]
    assert len(order) == len(m.nodes)
    place = dict(m.nodes)
    m.nodes = [(tag, place[tag]) for tag in order]
    # The elements, as their type, their corners' places and their physical tag.
    theirs = []
    for k, block in enumerate(got.cells):
        physical = got.cell_data.get("gmsh:physical")
        corners = {"vertex": 1, "line": 2, "triangle": 3, "quad": 4, "tetra": 4, "hexahedron": 8, "wedge": 6,
                   "pyramid": 5}[block.type.rstrip("0123456789")]
        for i, nodes in enumerate(block.data):
            theirs.append((block.type.rstrip("0123456789"), tuple(order[n] for n in nodes[:corners]),
                           int(physical[k][i]) if physical is not None and physicals else 0))
    ours = [(TYPES[ty][0], tuple(nodes[:TYPES[ty][3]]), physical if physicals else 0)
            for _, ty, physical, _, nodes in m.elements]
    assert sorted(theirs) == sorted(ours), "meshio and Gmsh read different elements"
    for kind, name, comps, values in m.views:
        if kind == "NodeData":
            mine = np.asarray([values[tag] for tag in order]).reshape(len(order), -1)
            assert np.array_equal(mine, np.asarray(got.point_data[name]).reshape(len(order), -1)), name
    return True


def expectations(m):
    """The expectations and the reference for a mesh: each physical group a mesh of its own."""
    index = {tag: i for i, (tag, _) in enumerate(m.nodes)}
    points = np.asarray([p for _, p in m.nodes], dtype=np.float64)
    groups = {}
    if not m.elements:
        # Nodes alone are drawn as points.
        groups[None] = Group()
        groups[None].elements = [("vertex", [i]) for i in range(len(m.nodes))]
    element_group = {}
    for tag, ty, physical, _, nodes in m.elements:
        shape, dim, _, corners = TYPES[ty]
        key = (dim, physical) if physical else None
        if key not in groups:
            name = None
            if key:
                name = m.names.get(key, "Physical %s %d" % (KINDS[dim], physical))
            groups[key] = Group(name, {"physical": physical, "dimension": dim} if key else None)
        element_group[tag] = (groups[key], len(groups[key].elements))
        groups[key].elements.append((shape, [index[n] for n in nodes[:corners]]))
    point_data = {}
    for kind, name, comps, values in m.views:
        if kind == "NodeData":
            point_data[name] = [values.get(tag, np.zeros(comps)) for tag, _ in m.nodes]
            continue
        for group in groups.values():
            rows = [None] * len(group.elements)
            (group.cell_data if kind == "ElementData" else group.corner_data)[name] = rows
        for tag, ty, _, _, _ in m.elements:
            group, at = element_group[tag]
            corners = TYPES[ty][3]
            if kind == "ElementData":
                group.cell_data[name][at] = values.get(tag, np.zeros(comps))
            else:
                group.corner_data[name][at] = values.get(tag, np.zeros((corners, comps)))[:corners]
    return measure(points, list(groups.values()), point_data, ordered=m.ordered)


def add(name, fname, data, spec, source, m, **more):
    """Writes a case: the file `data`, and the expectations for the mesh `m` it holds."""
    expect, ref = expectations(m)
    expect.update(more)
    case(FMT, name, {fname: data, "reference.json": json.dumps(ref) + "\n"},
         {"spec": SPEC + ": " + spec, "source": source, **expect})


def fails(name, fname, data, spec, source, error, kind):
    case(FMT, name, {fname: data}, {"spec": SPEC + ": " + spec, "source": source, "error": error, "error_kind": kind})


def written(version, binary, views=(), save_all=False, name="out.msh"):
    """The file Gmsh writes for the mesh it holds, and the mesh Gmsh reads back from it."""
    gmsh.option.setNumber("Mesh.MshFileVersion", version)
    gmsh.option.setNumber("Mesh.Binary", 1 if binary else 0)
    gmsh.option.setNumber("Mesh.SaveAll", 1 if save_all else 0)
    path = os.path.join(TMP, name)
    gmsh.write(path)
    for v in views:
        gmsh.view.write(v, path, True)
    with open(path, "rb") as f:
        data = f.read()
    if not binary:
        # Gmsh on Windows ends a text file's lines with CRLF; the cases are the same wherever they're made.
        data = data.replace(b"\r\n", b"\n")
        with open(path, "wb") as f:
            f.write(data)
    return data, path


MESHIO_TYPES = {"vertex": 15, "line": 1, "triangle": 2, "quad": 3, "tetra": 4, "hexahedron": 5, "wedge": 6,
                "pyramid": 7}


def read_meshio(path):
    """What meshio reads from the file: for the files it writes that Gmsh refuses (it leaves the
    entities with no physical group out of `$Entities`)."""
    got = meshio.read(path)
    m = Mesh()
    m.nodes = [(i + 1, tuple(float(c) for c in p)) for i, p in enumerate(got.points)]
    tag = 0
    for k, block in enumerate(got.cells):
        for i, nodes in enumerate(block.data):
            tag += 1
            physical = int(got.cell_data["gmsh:physical"][k][i]) if "gmsh:physical" in got.cell_data else 0
            m.elements.append((tag, MESHIO_TYPES[block.type], physical, int(got.cell_data["gmsh:geometrical"][k][i]),
                               [int(n) + 1 for n in nodes]))
    m.names = {(int(dim), int(tag)): name for name, (tag, dim) in got.field_data.items()}
    return m


def measured(data, path, order=None, physicals=True):
    """The mesh Gmsh reads from the file at `path`, its nodes in the file's order: meshio's, or
    for a text file of version 1 or 2 the order of its node lines, or `order`."""
    try:
        gmsh.clear()
        gmsh.open(path)
    except Exception as e:
        assert "Unknown entity" in str(e), e
        return read_meshio(path)
    m = read_gmsh(path)
    if not by_meshio(path, m, physicals):
        if order is None and (data.startswith(b"$NOD") or data.split(b"\n")[1].split()[:2] == [b"2.2", b"0"]):
            order = text_order(data)
        if order is None:
            m.ordered = False
        else:
            place = dict(m.nodes)
            m.nodes = [(tag, place[tag]) for tag in order]
    return m


# --- writers, from the format's description ---------------------------------------------------------

def runs(items, key):
    """Consecutive items with the same key."""
    out = []
    for item in items:
        if out and key(item) == out[-1][0]:
            out[-1][1].append(item)
        else:
            out.append((key(item), [item]))
    return out


def views_out(m, binary, e):
    out = b""
    for kind, name, comps, values in m.views:
        out += b"$%s\n1\n\"%s\"\n1\n0\n3\n0\n%d\n%d\n" % (kind.encode(), name.encode(), comps, len(values))
        for tag, rows in values.items():
            flat = [float(v) for v in np.asarray(rows).flat]
            head = [tag, len(rows)] if kind == "ElementNodeData" else [tag]
            if binary:
                out += struct.pack("%s%di%dd" % (e, len(head), len(flat)), *head, *flat)
            else:
                out += (" ".join([str(h) for h in head] + ["%.16g" % v for v in flat]) + "\n").encode()
        out += b"%s$End%s\n" % (b"\n" if binary else b"", kind.encode())
    return out


def write_v2(m, binary=False, big=False, version="2.2", partitions=False, names_dim=True, comment=None):
    """Version 2: `$Nodes` and `$Elements` as one list each; binary elements in runs of one type."""
    e = ">" if big else "<"
    out = b"$MeshFormat\n%s %d 8\n" % (version.encode(), 1 if binary else 0)
    if binary:
        out += struct.pack(e + "i", 1) + b"\n"
    out += b"$EndMeshFormat\n"
    if comment:
        out += b"$Comments\n%s\n$EndComments\n" % comment.encode()
    if m.names:
        out += b"$PhysicalNames\n%d\n" % len(m.names)
        for (dim, tag), name in m.names.items():
            out += (("%d " % dim if names_dim else "") + "%d \"%s\"\n" % (tag, name)).encode()
        out += b"$EndPhysicalNames\n"
    out += b"$Nodes\n%d\n" % len(m.nodes)
    for tag, p in m.nodes:
        out += struct.pack(e + "i3d", tag, *p) if binary else ("%d %.16g %.16g %.16g\n" % (tag, *p)).encode()
    out += b"%s$EndNodes\n$Elements\n%d\n" % (b"\n" if binary else b"", len(m.elements))
    tags = lambda physical, entity: [physical, entity] + ([1, 1 + entity % 2] if partitions else [])
    if binary:
        for (ty, count), run in runs(m.elements, lambda el: (el[1], 4 if partitions else 2)):
            out += struct.pack(e + "3i", ty, len(run), count)
            for tag, _, physical, entity, nodes in run:
                out += struct.pack("%s%di" % (e, 1 + count + len(nodes)), tag, *tags(physical, entity), *nodes)
        out += b"\n"
    else:
        for tag, ty, physical, entity, nodes in m.elements:
            t = tags(physical, entity)
            out += (" ".join(str(v) for v in [tag, ty, len(t), *t, *nodes]) + "\n").encode()
    out += b"$EndElements\n"
    return out + views_out(m, binary, e)


def write_v1(m):
    """Version 1: `$NOD` and `$ELM`, each element with its node count."""
    out = b"$NOD\n%d\n" % len(m.nodes)
    for tag, p in m.nodes:
        out += ("%d %.16g %.16g %.16g\n" % (tag, *p)).encode()
    out += b"$ENDNOD\n$ELM\n%d\n" % len(m.elements)
    for tag, ty, physical, entity, nodes in m.elements:
        out += (" ".join(str(v) for v in [tag, ty, physical, entity, len(nodes), *nodes]) + "\n").encode()
    return out + b"$ENDELM\n"


def write_v4(m, v41=True, binary=False, big=False, wide=8, parametric=False):
    """Version 4: `$Entities`, then nodes and elements in blocks by entity. Every node goes in one
    block, on the first element's entity (with made-up parametric coordinates when asked)."""
    e = ">" if big else "<"
    size = "Q" if wide == 8 else "I"
    out = b"$MeshFormat\n%s %d %d\n" % (b"4.1" if v41 else b"4", 1 if binary else 0, wide)
    if binary:
        out += struct.pack(e + "i", 1) + b"\n"
    out += b"$EndMeshFormat\n"
    if m.names:
        out += b"$PhysicalNames\n%d\n" % len(m.names)
        for (dim, tag), name in m.names.items():
            out += ("%d %d \"%s\"\n" % (dim, tag, name)).encode()
        out += b"$EndPhysicalNames\n"
    # Each entity and its physical group.
    entities = [{}, {}, {}, {}]
    for _, ty, physical, entity, _ in m.elements:
        entities[TYPES[ty][1]][entity] = physical
    text = lambda values: (" ".join(("%.16g" % v) if isinstance(v, float) else str(v) for v in values) + "\n").encode()
    out += b"$Entities\n"
    out += struct.pack(e + "4" + size, *(len(d) for d in entities)) if binary else text([len(d) for d in entities])
    for dim, found in enumerate(entities):
        for entity, physical in found.items():
            box = [0.0] * (3 if dim == 0 and v41 else 6)
            physicals = [physical] if physical else []
            if binary:
                out += struct.pack("%si%dd%s%di" % (e, len(box), size, len(physicals)), entity, *box, len(physicals),
                                   *physicals)
                if dim:
                    out += struct.pack(e + size, 0)
            else:
                out += text([entity, *box, len(physicals), *physicals] + ([0] if dim else []))
    out += b"%s$EndEntities\n$Nodes\n" % (b"\n" if binary else b"")
    first = m.elements[0]
    dim, entity = TYPES[first[1]][1], first[3]
    n = len(m.nodes)
    tags = [tag for tag, _ in m.nodes]
    extra = dim if parametric else 0
    coords = [list(p) + [0.25 * (k + 1) for k in range(extra)] for _, p in m.nodes]
    if binary:
        head = [1, n] + ([min(tags), max(tags)] if v41 else [])
        out += struct.pack("%s%d%s" % (e, len(head), size), *head)
        block = [dim, entity] if v41 else [entity, dim]
        out += struct.pack(e + "3i" + size, *block, 1 if parametric else 0, n)
        if v41:
            out += struct.pack("%s%d%s" % (e, n, size), *tags)
            for c in coords:
                out += struct.pack("%s%dd" % (e, len(c)), *c)
        else:
            for tag, c in zip(tags, coords):
                out += struct.pack("%si%dd" % (e, len(c)), tag, *c)
        out += b"\n"
    else:
        out += text([1, n] + ([min(tags), max(tags)] if v41 else []))
        out += text(([dim, entity] if v41 else [entity, dim]) + [1 if parametric else 0, n])
        if v41:
            for tag in tags:
                out += text([tag])
            for c in coords:
                out += text(c)
        else:
            for tag, c in zip(tags, coords):
                out += text([tag] + c)
    out += b"$EndNodes\n$Elements\n"
    blocks = runs(m.elements, lambda el: (TYPES[el[1]][1], el[3], el[1]))
    element_tags = [el[0] for el in m.elements]
    head = [len(blocks), len(m.elements)] + ([min(element_tags), max(element_tags)] if v41 else [])
    out += struct.pack("%s%d%s" % (e, len(head), size), *head) if binary else text(head)
    for (dim, entity, ty), run in blocks:
        block = [dim, entity] if v41 else [entity, dim]
        if binary:
            out += struct.pack(e + "3i" + size, *block, ty, len(run))
            word = size if v41 else "i"
            for tag, _, _, _, nodes in run:
                out += struct.pack("%s%d%s" % (e, 1 + len(nodes), word), tag, *nodes)
        else:
            out += text(block + [ty, len(run)])
            for tag, _, _, _, nodes in run:
                out += text([tag] + nodes)
    out += b"%s$EndElements\n" % (b"\n" if binary else b"")
    return out + views_out(m, binary, e)


def agrees(data, m, fname="hand.msh"):
    """Gmsh reads the file written here as the mesh it was written from."""
    path = os.path.join(TMP, fname)
    with open(path, "wb") as f:
        f.write(data)
    got = read_gmsh(path)
    assert sorted(got.nodes) == sorted(m.nodes), "Gmsh reads other nodes"
    key = lambda el: (el[0], el[1], el[2], tuple(el[4]))
    assert sorted(map(key, got.elements)) == sorted(map(key, m.elements)), "Gmsh reads other elements"
    assert got.names == m.names or data.startswith(b"$NOD")
    assert len(got.views) == len(m.views)
    for (kind, name, comps, values), (kind2, name2, comps2, values2) in zip(m.views, got.views):
        assert (kind, name, comps) == (kind2, name2, comps2)
        assert values.keys() == values2.keys()
        assert all(np.array_equal(np.asarray(values[t]), np.asarray(values2[t])) for t in values)
    return data


