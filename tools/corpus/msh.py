"""Gmsh conformance cases: .msh files as the Gmsh reference manual's "MSH file format" chapter
defines them (versions 4.1, 4.0, 2.2 to 2.0 and 1.0, ASCII and binary).

The files are written by Gmsh itself (through its Python module) in every version and encoding it
writes, by meshio, and by the small writers here for what neither writes: big-endian binary, a
4-byte size_t, binary 4.0, versions 2.0 and 2.1, parametric nodes, sparse tags.

The expectations never come from Polysmelt. A file Gmsh or meshio wrote is read back with Gmsh
(`gmsh.open`), which gives its nodes, its elements by entity, each entity's physical groups and
the views; where meshio reads the file too, its points give the nodes' order in the file and its
cells and data must agree with Gmsh's. A file written here is expected to hold what was written,
and where Gmsh reads it, Gmsh must agree. What's drawn is then worked out with VTK (cellmesh.py):
each physical group is a mesh, volume elements draw as the faces only one of the group's elements
has, and that count is held against vtkDataSetSurfaceFilter's. Beside each expect.json,
reference.json holds hashes of the exact points and of every triangle, line and point drawn with
its attributes, which tests/fem.rs compares with what Polysmelt reads.

Two real files from meshio's test meshes (MIT, LICENSE-meshio) are kept in their case folders.

Run from the repository root with a Python that has gmsh, meshio and vtk installed (this file
can't be called gmsh.py, which would hide the module):

    python tools/corpus/msh.py [folder holding the real files]
"""

