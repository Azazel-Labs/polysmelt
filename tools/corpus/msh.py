def cube():
    """A unit cube meshed by Gmsh: a physical volume and a physical surface (its top)."""
    gmsh.clear()
    for v in gmsh.view.getTags():
        gmsh.view.remove(v)
    gmsh.model.add("cube")
    gmsh.model.occ.addBox(0, 0, 0, 1, 1, 1)
    gmsh.model.occ.synchronize()
    gmsh.option.setNumber("Mesh.MeshSizeMin", 1.0)
    gmsh.option.setNumber("Mesh.MeshSizeMax", 1.0)
    gmsh.model.addPhysicalGroup(3, [1], 7)
    gmsh.model.setPhysicalName(3, 7, "body")
    gmsh.model.addPhysicalGroup(2, [6], 3)
    gmsh.model.setPhysicalName(2, 3, "top")
