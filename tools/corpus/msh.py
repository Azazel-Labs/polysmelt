def cube_with_views(kinds):
    cube()
    views = []
    nodes = [int(t) for t in gmsh.model.mesh.getNodes()[0]]
    elements = []
    for dim, entity in [(2, 6), (3, 1)]:
        types, tags, _ = gmsh.model.mesh.getElements(dim, entity)
        for ty, found in zip(types, tags):
            elements += [(int(tag), TYPES[int(ty)][2]) for tag in found]
    if "node" in kinds:
        v = gmsh.view.add("temperature")
        gmsh.view.addHomogeneousModelData(v, 0, "cube", "NodeData", nodes, [0.125 * t - 1.0 for t in nodes], 0.0, 1)
        views.append(v)
        v = gmsh.view.add("velocity")
        gmsh.view.addHomogeneousModelData(v, 0, "cube", "NodeData", nodes,
                                          [c for t in nodes for c in (0.5 * t, -0.25 * t, 2.0)], 0.0, 3)
        views.append(v)
    if "tensor" in kinds:
        v = gmsh.view.add("strain")
        gmsh.view.addHomogeneousModelData(v, 0, "cube", "NodeData", nodes,
                                          [t + 0.25 * k for t in nodes for k in range(9)], 0.0, 9)
        views.append(v)
    if "element" in kinds:
        v = gmsh.view.add("zone")
        gmsh.view.addHomogeneousModelData(v, 0, "cube", "ElementData", [t for t, _ in elements],
                                          [float(t % 3) for t, _ in elements], 0.0, 1)
        views.append(v)
        v = gmsh.view.add("stress")
        gmsh.view.addHomogeneousModelData(v, 0, "cube", "ElementData", [t for t, _ in elements],
                                          [c for t, _ in elements for c in (0.5 * t, 1.0, -1.0 * t)], 0.0, 3)
        views.append(v)
    if "element-node" in kinds:
        v = gmsh.view.add("flux")
        gmsh.view.addModelData(v, 0, "cube", "ElementNodeData", [t for t, _ in elements],
                               [[t + 0.125 * k for k in range(n)] for t, n in elements], 0.0, 1)
        views.append(v)
    return views


